def _흐름표(작업들: list) -> str:
    표 = {w["이름"]: w for w in 작업들}
    줄 = ["", "### 흐름에서 쓰는 작업 — 인자와 예시", "",
         "인자 **목록**은 위 표와 같은 등록부(workspace/api.py)에서 나온다 — 예시 **값**은 "
         "참고용이다.", "",
         "| 작업 | 인자 | 예시 |", "|---|---|---|"]
    for 이름 in 흐름작업순서:
        w = 표.get(이름)
        if not w:
            continue    # 등록부에서 빠졌으면(이름이 바뀌었거나 지워졌으면) 조용히 건너뛴다
        인자들 = " · ".join(w["받는것"]) or "(없음)"
        예시 = 흐름예시.get(이름, "")
        줄.append(f"| `{이름}` | {인자들} | {예시} |")
    return "\n".join(줄) + "\n"


def 생성() -> str:
    """마커 사이에 들어갈 본문 — 마커 자체는 포함하지 않는다."""
    작업들 = _작업들()
    읽기 = [w["이름"] for w in 작업들 if w["읽기"]]
    쓰기 = [w["이름"] for w in 작업들 if not w["읽기"]]
    return (
        "읽기는 아무 때나, 쓰기는 정본을 바꾼다:\n\n"
        "| | 작업 |\n"
        "|---|---|\n"
        f"| 읽기 | {' · '.join(읽기)} |\n"
        f"| 쓰기 | {' · '.join(쓰기)} |\n"
        + _흐름표(작업들)
    )


def 끼워넣기(원본: str, 본문: str) -> str:
    """SKILL.md 원문의 마커 사이를 본문으로 갈아 끼운다.

    마커가 없으면 **조용히 넘어가지 않는다** — 누가 SKILL.md 를 통째로 고쳐 마커를
    지우면, 이 함수가 조용히 아무것도 안 바꾸고 통과한 것처럼 보이면 안 된다.
    """
    if 시작마커 not in 원본 or 끝마커 not in 원본:
        raise SystemExit(
            "SKILL.md 에서 작업목록 마커를 못 찾았다 — 다음 두 줄이 그대로 있어야 한다:\n"
            f"  {시작마커}\n  {끝마커}"
        )
    앞, 나머지 = 원본.split(시작마커, 1)
    _, 뒤 = 나머지.split(끝마커, 1)
    return 앞 + 시작마커 + "\n\n" + 본문 + "\n" + 끝마커 + 뒤


def main():
    본문 = 생성()
