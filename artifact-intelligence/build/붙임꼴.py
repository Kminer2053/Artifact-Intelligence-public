#!/usr/bin/env python3
"""시행문 본문에 섞여 들어온 "붙임" 표시 줄을 최상위 붙임 배열로 옮긴다.

전거: 내부 기록 (C) + bench3/runs/P/qwen-s3/
run.json(실패 로그, 5회 반려 원인 그대로). gongmun-docs.json 본보기는 붙임을 최상위 `붙임`
배열로 올바르게 예시하지만, 모델은 종종 "붙임 1. ○○ 1부." 같은 문장을 `본문` 배열의 한
항목(level 1)으로 낸다 — assemble_gongmun.gate_check 의 서술어 완결 검사("…다."로 안
끝나면 위반)가 이런 줄마다 하나씩 위반을 쌓는다. 실측 로그(run.json)엔 두 번째 이상의
붙임이 "붙임" 낱말 없이 번호만("2. 참석자 명단 양식 1부.")으로 이어지는 항목과, 문서의
'끝.' 표시를 항목 글 안에 직접 적어 넣은 항목("…1부. 끝.")까지 섞여 있었다 — 셋 다
아래에서 함께 다룬다.

방법 — 본문 **1수준(level==1)** 항목 중 "붙임"으로 시작하는 줄만 골라(오탐을 줄이려고
콜론 명시 라벨이 아니면 **"…N부."/"…부" 종결(숫자 필수)**을 건다 — "붙임 자료를 참고하시기
바랍니다."처럼 정말 서술문인 줄이나, "…행정지원부."·"…사전 배부" 처럼 숫자 없이 "부"로
끝나는 조직명·서술문은 이 종결이 없어(또는 숫자가 없어) 안 걸린다) 라벨·번호(그리고 항목
글 안에 잘못 섞여 들어온 '끝.' 표시)를 벗기고 `붙임` 배열로 옮긴다. **2수준 이하는 아예
보지 않는다** — gate_check 의 서술어 완결 검사 자체가 1수준만 보므로(assemble_gongmun.py)
이 모듈도 같은 범위를 지킨다(안 그러면 "다음 서류를 제출…" 아래 2수준 "붙임 서식에 따른
참가 신청서 1부" 처럼 붙임과 무관한 하위 개조식 항목까지 삼킨다, review34/bu_adv.py 실측).

"붙임 1. …1부. 2. …1부. 끝."처럼 **한 줄에 여러 첨부가 이어 붙은 경우**는 "…부." 뒤
"숫자. "가 다시 나오는 경계로 쪼갠다 — 안 쪼개고 통째로 옮기면, 이미 최상위 붙임 배열에
따로 있는 두 항목과 겹쳐 셋째(중복·병합) 항목이 새로 생긴다(실측: bench3 qwen-s3 
시도 중 1·5회차 실제 초안, review34/qwen_s3_real.py). '붙임'으로 시작한 줄 바로 다음에
번호만으로 이어지는 줄("2. …부.")도 같은 방식으로 같은 붙임으로 본다 — 다음 번호는
직전 줄의 **실제 라벨 번호**(또는 이번 줄이 쪼개져 낸 항목 수)로 정확히 센다(예전엔
항상 2로 되돌아가 "붙임 2." 다음에 오는 "3. …" 를 못 알아봤다, 실측 chain-break 케이스).

이미 같은 내용이 배열에 있으면(번호·마침표·공백을 정규화한 값으로 비교) 겹치지 않게
본문에서만 뺀다. 시행문(genre=="gongmun")이 아니거나(강제=True 가 아닌 한) 본문 모양이
낯설면(level 이 1~6 정수가 아닌 항목이 섞여 있으면) 아무것도 안 바꾸고 0을 돌려준다 —
api.py 등록 정규화 자리에서 장르를 가리지 않고 불러도 안전하다.

사용: assemble_gongmun.조립하기() 가 gate_check 전에 부르고(강제=True), tomd.py 의
시행문 분기도 같은 분리를 거쳐(강제=True) HTML·MD 가 같은 붙임 목록을 낸다.
"""
import re

# 콜론 라벨("※ 붙임: …")은 구조가 이미 또렷해 종결과 무관하게 붙임으로 본다 — assemble_gongmun.
# LABEL_ITEM("관련:"류)과 같은 발상이다.
_붙임_콜론 = re.compile(r"^\s*(?:※\s*)?붙임\s*[:：]")
# 라벨·번호(붙임[번호][./)/:])만 벗긴다 — 뒤에 남는 글은 손대지 않는다(1부. 의 마침표까지
# 그대로 doc["붙임"] 배열 표기(예: "…계획 1부.")와 맞춘다). 번호를 캡처해 둔다 — "붙임 2."
# 처럼 라벨 자체에 번호가 있으면 그 번호를 다음 이어짐 판정의 기준으로 쓴다(아래 분리하기).
_붙임_머리 = re.compile(r"^\s*(?:※\s*)?붙임\s*(?:(\d+)\s*)?[.):]?\s*")
# 첫 붙임 줄 다음에 "붙임" 낱말 없이 번호만으로 이어지는 줄(실측 run.json: "2. 참석자
# 명단 양식 1부.") — 직전 항목이 붙임으로 인정됐을 때만, 그것도 번호가 다음 순번일
# 때만 이어지는 붙임으로 본다(아무 "2. …" 항목이나 걸리면 개조식 세부 항목까지 삼킨다).
_붙임_이어짐 = re.compile(r"^\s*(\d+)\.\s*(.+)$")
# "…N부." 종결(숫자 필수) — 공문 붙임 관행의 표지. 예전엔 숫자 없이 "부"로만 끝나도
# 걸려("…사전 배부"·"…경영지원본부") 조직명·서술문까지 붙임으로 잘못 옮겼다(medium,
# review34/bu_adv.py 'lv2-배부'·'lv2-본부' 실측) — 부수(部數) 표기는 반드시 숫자가 붙는다.
_붙임_종결 = re.compile(r"\d+\s*부\.?\s*$")
# 문서의 '끝.' 표시는 조립기가 계산해서 넣는 것이지 항목 글 안에 있을 자리가 아니다 —
# 모델이 실수로 항목 글 끝에 직접 적으면("…1부. 끝.") 옮기기 전에 떼어 낸다(실측 run.json).
_끝표시_꼬리 = re.compile(r"\s*끝\.?\s*$")
# 한 줄에 여러 첨부가 이어 붙었을 때의 경계 — "…부." 뒤 공백(줄바꿈 포함)을 두고 다시
# "숫자. "가 오면 거기서 쪼갠다(실측: qwen-s3 실제 초안 1·차, 파일 머리 docstring).
_붙임_내부분리 = re.compile(r"(?<=부\.)\s*(?=\d+\.\s)")


def _벗기고종결확인(본문, 콜론라벨):
    """항목 글에 잘못 섞인 '끝.' 표시를 뗀 뒤 '…N부.' 종결(또는 콜론 라벨)을 확인한다.
    통과하면 옮겨 실을 순수 내용을, 아니면 None 을 돌려준다."""
    본문 = _끝표시_꼬리.sub("", 본문).rstrip()
    if not 본문:
        return None
    if 콜론라벨 or _붙임_종결.search(본문):
        return 본문
    return None


def _정규화키(s):
    """중복 판정용 열쇠 — 앞의 번호("1. ")와 끝 마침표·앞뒤 공백을 지운 값. 배열에
    이미 "교육 계획 1부"(마침표 없음)나 "1. 교육 계획 1부."가 있어도 같은 내용으로
    본다(medium, review34/bu_adv.py 'dedup-*' 실측 — 예전엔 글자가 완전히 같아야만
    중복으로 봐서 표기만 다른 중복 항목이 쌓였다)."""
    s = (s or "").strip()
    s = re.sub(r"^\d+\.\s*", "", s)
    return s.rstrip(".").strip()


def _붙임줄인가(t):
    """본문 1수준 줄 하나(이미 strip 된 글)가 '붙임' 표시로 **새로 시작**하는 줄이면
    (그 줄이 담은 첨부 내용 목록, 라벨 자체의 번호(없으면 None))을, 아니면 (None, None)
    을 돌려준다. 내용 목록은 한 줄에 여러 첨부가 이어 붙었을 때("붙임 1. …1부. 2. …1부.")
    그 개수만큼 나뉜다 — 안 나누면 늘 길이 1."""
    if not t:
        return None, None
    mh = _붙임_머리.match(t)
    if not mh:
        return None, None
    머리번호 = int(mh.group(1)) if mh.group(1) else None
    콜론라벨 = bool(_붙임_콜론.match(t))
    본문 = _붙임_머리.sub("", t, count=1).rstrip()
    본문 = _벗기고종결확인(본문, 콜론라벨)
    if 본문 is None:
        return None, None
    부분들 = [p.strip() for p in _붙임_내부분리.split(본문) if p.strip()]
    목록 = []
    for j, p in enumerate(부분들):
        if j > 0:
            mi = _붙임_이어짐.match(p)
            if mi:
                p = mi.group(2).strip()
        if p:
            목록.append(p)
    return (목록 or None), 머리번호


def 분리하기(doc, 강제=False) -> int:
    """시행문 doc 의 본문 **1수준** 가운데 '붙임' 표시 줄을 doc["붙임"] 배열로 옮긴다.
    doc 를 제자리에서 고치고, (본문에서) 옮긴 줄 개수를 돌려준다(0 이면 아무것도 안
    바꿨다 — 항목 하나가 여러 첨부로 쪼개져도 "옮긴 줄"은 1이다).

    `강제`(기본 False) — True 면 genre 검사를 건너뛴다. assemble_gongmun.조립하기·
    tomd.py 의 시행문 분기는 자기가 이미 시행문 조립 경로임을 알므로(손으로 지은 표본이
    genre 키를 빠뜨려도) 강제=True 로 부른다(low, review34 실측 — genre 없는 문서가
    이 두 곳에서도 조용히 건너뛰어졌다). api.py 의 등록 정규화 자리는 genre 를 이미
    확인한 뒤 부르므로 기본값 그대로 둔다.

    시행문이 아니거나(강제 아닌 한 genre != "gongmun") 본문 모양이 낯설면 손대지 않고
    0을 돌려준다 — 장르를 가리지 않고 걸어도 안전해야 한다(B 와의 약속)."""
    if not isinstance(doc, dict) or (not 강제 and doc.get("genre") != "gongmun"):
        return 0
    본문 = doc.get("본문")
    if not isinstance(본문, list):
        return 0
    # 시행문 본문 계약(level 1~6 정수 + text) 확인 — 하나라도 안 맞으면 낯선 모양이라
    # 손대지 않는다(표 항목은 이 계약 밖이라 건너뛴다, assemble_gongmun.build 와 같은 예외).
    for it in 본문:
        if not isinstance(it, dict):
            return 0
        if "표" in it:
            continue
        if not isinstance(it.get("level"), int) or not (1 <= it["level"] <= 6):
            return 0
        if not isinstance(it.get("text"), str):
            return 0

    옮김 = list(doc.get("붙임") or [])
    이미있음 = {_정규화키(x) for x in 옮김 if isinstance(x, str)}
    남길 = []
    옮긴수 = 0
    직전붙임 = False   # 바로 앞 항목이 붙임으로 인정됐는가(번호만 있는 이어짐 판정용)
    다음번호 = None    # 이어지는 붙임이 있다면 그 번호
    for it in 본문:
        if "표" in it or it.get("level") != 1:
            # 표·2수준 이하는 붙임 분리 범위 밖이다(위 docstring) — 그대로 두고 이어짐
            # 연쇄만 끊는다(다른 수준이 끼어들면 번호 이어짐도 끊긴 것으로 본다).
            남길.append(it)
            직전붙임, 다음번호 = False, None
            continue
        t = it.get("text")
        t = t.strip() if isinstance(t, str) else ""
        목록, 머리번호 = _붙임줄인가(t)
        새로시작 = 목록 is not None
        if not 새로시작 and 직전붙임 and 다음번호 is not None:
            mi = _붙임_이어짐.match(t)
            if mi and int(mi.group(1)) == 다음번호:
                내용 = _벗기고종결확인(mi.group(2).strip(), 콜론라벨=False)
                if 내용 is not None:
                    목록 = [내용]
        if not 목록:
            남길.append(it)
            직전붙임, 다음번호 = False, None
            continue
        옮긴수 += 1
        직전붙임 = True
        # 다음 순번은 이 줄이 낸 항목 수만큼 이어간다 — 라벨 자체가 번호를 밝혔으면
        # (예: "붙임 2.") 그 번호부터, 아니면 1(암묵적 첫 붙임)부터 센다(medium — 예전엔
        # 늘 2로 되돌아가 "붙임 2." 다음의 "3. …"을 못 알아봤다, chain-break 실측).
        다음번호 = (머리번호 if 새로시작 and 머리번호 else (1 if 새로시작 else 다음번호)) + len(목록)
        for 내용 in 목록:
            키 = _정규화키(내용)
            if 키 not in 이미있음:
                옮김.append(내용)
                이미있음.add(키)
    if 옮긴수:
        doc["본문"] = 남길
        doc["붙임"] = 옮김
    return 옮긴수
