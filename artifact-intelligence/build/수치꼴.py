#!/usr/bin/env python3
"""표 칸이 '순수 수치(숫자·부호·단위·기호만)'인지 재는 공용 판정 — 열 단위 우측정렬에 쓴다
(assemble.py·assemble_full.py 동일 패턴, assemble:F10 '26-09-27 한 곳으로 합침).

왜 한 곳인가 — 두 조립기에 같은 정규식을 따로 복사해 두었더니 단위 목록이 갈라졌다(예:
%p 가 한쪽에만 빠짐). 앞으로 세 번째 조립기가 표를 그릴 때도 이 모듈만 부르면 같은 판정을
쓴다.

순수 수치 칸(숫자·부호·단위·기호만)만 우측정렬 대상으로 삼는다 — 글자가 섞이면(예: '6분
(△△공단 도입 사례)') 대상에서 뺀다. 정렬은 **열 단위**로 매긴다: 그 열에서 빈 칸·대시를
뺀 나머지가 하나 이상 있고 전부 순수 수치일 때만 그 열 전체(대시 포함)를 우측정렬한다
(data_elements.표.디자인.현재기본.정렬, '26-09-26 벤치마크 진단 → 2차 검토로 열 단위 판정으로
되돌리고 단위 목록을 넓혔다).

'26-09-27 3차 확장(assemble:F10) — %p(퍼센트포인트)가 단위 목록에 없어 증감 열('2.7%p')이
정렬에서 갈라졌고, 크기 자리(만·억·조 …)가 한 번만 허용돼 '1조 2,000억원'·'5천만원' 같은
복합 금액이 안 맞았다. ㎞·개사·개국·톤도 흔한 공공 보고서 단위인데 빠져 있었다. 단위를
넓히고, 크기 자리를 공백으로 이어지는 여러 조각(사이즈수 연쇄)으로 바꿨다.

'26-09-27 4차 고침(asm:F2·F5, 회귀) — 3차 정규식은 사이즈수 뒤에 꼬리 \\s*를 남겨 두고
연쇄가 곧바로 \\s+를 요구했다. 그러면 연속 공백 한 틈을 두 쪽이 나눠 먹는 방법이 여러
가지가 되어(공백 k칸이면 k갈래), 끝이 글자로 끝나 매칭이 실패하면 그 경우의 수를 전부
되짚었다(지수 역추적·ReDoS, 표 칸 하나로 조립 전체가 수십 분 멈춤). 같은 틈이 크기 자리
없는 맨숫자끼리도 이어 줘서 '1, 3, 5'·'2024, 2025'·'010 1234 5678' 같은 숫자 나열까지
순수 수치로 오판했다(F5). _수의 쉼표를 천 단위 그룹(\\d{1,3}(,\\d{3})+)으로 좁혀 뒤쉼표·
자유 쉼표 나열을 막고, 연쇄는 '앞 조각은 반드시 크기 자리 뒤 공백'(수·크기·공백을 한
덩이로) 이어야만 이어지도록 좁혔다 — 마지막 조각만 크기 자리가 선택이다. 그래서 크기
자리 없는 맨숫자는 절대 이어붙지 않고(F5), 공백을 먹는 자리가 조각마다 하나로 고정돼
경우의 수가 사라진다(F2).
"""
import re

# 크기 자리(만·억·조 …) — 긴 것부터 먼저 시도해야 한다("천만"을 "천"+"만"으로 쪼개 매칭하면
# 뒷글자 "만"이 안 붙어 전체 매칭이 깨진다).
_크기 = r"(?:천만|백만|조|억|만|천)"
# 숫자 — 쉼표는 천 단위 그룹(1,234 / 12,345,678)만 허용한다. [\d,]+ 처럼 쉼표를 자유롭게
# 허용하면 '1,'·'1,3,5' 같은 뒤쉼표·나열도 통째로 먹혀 F5(숫자 나열 오판)가 된다.
_수 = r"(?:\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)"
# 사이즈수 연쇄 — "1조 2,000억"처럼 크기 자리가 붙은 조각을 공백으로 이은 것(마지막 조각만
# 크기 자리가 선택). 이어지는 앞 조각은 반드시 '수+크기+공백'을 한 덩이로 먹는다 — 크기
# 자리가 없는 맨숫자끼리는 여기서 걸리지 않아 F5(숫자 나열 오판)가 안 생긴다. 공백을 먹는
# 자리가 조각마다 하나(크기 뒤)로만 고정돼 있어 앞뒤 조각이 공백 하나를 나눠 먹는 경우의
# 수가 없다 — 그래서 되짚기가 늘지 않는다(F2, ReDoS).
_크기연쇄 = rf"(?:{_수}\s*{_크기}\s+)*{_수}(?:\s*{_크기})?"
# 단위 — 길게 겹치는 조각(개월·개소·개사·개국)을 짧은 조각("개")보다 먼저 둔다. 정규식
# 교대(|)는 그 자리에서 처음 맞는 것을 취하므로, 짧은 것을 먼저 두면 뒷글자가 안 붙어
# 매칭 전체가 깨진다(예: "개"가 "개월"보다 먼저면 "개월"의 "월"이 안 붙는다).
_단위 = (r"%p|개월|개소|개사|개국|원|건|개|명|년|월|일|시간|분|초|배|위|등|점|회|대|쪽|곳|"
        r"가구|톤|㎡|㎥|kg|km|㎞|kWh|℃|%")
_순수수치_패턴 = re.compile(
    rf"^[△▲▼+\-]?{_크기연쇄}"
    rf"(?:\s*[~∼]\s*[△▲▼+\-]?{_크기연쇄})?"
    rf"\s*(?:{_단위})?\s*$")
_수치_빈값 = ("", "-", "–", "—", "N/A", "해당없음", "해당 없음")


def 순수수치인가(v):
    """칸 하나가 숫자·단위·기호로만 됐는가 — 빈 칸·대시류는 여기서 걸러(False) 열 판정에
    맡긴다(호출부가 그 열의 비지 않은 칸만 넘긴다)."""
    v = (v or "").strip()
    if v in _수치_빈값:
        return False
    return bool(_순수수치_패턴.match(v))


def 표_열_우측정렬(rows, ncols):
    """열 단위 우측정렬 판정 — 첫 열은 제외. 그 열에서 비지 않은(대시 제외) 칸이 하나 이상
    있고 전부 순수 수치일 때만 그 열 전체(대시 포함)를 우측정렬 대상으로 본다. 글자 섞인
    칸이 하나라도 있으면 그 열은 전부 정렬 기본값(가운데)으로 남는다."""
    out = [False] * ncols
    for j in range(1, ncols):
        비지않은 = [row[j] for row in rows if j < len(row) and (row[j] or "").strip() not in _수치_빈값]
        out[j] = bool(비지않은) and all(순수수치인가(v) for v in 비지않은)
    return out
