def 무덤뿌리():
    return os.path.join(자료뿌리.세션들뿌리(), 무덤이름)


def _밀어내기(열쇠):
    """세션방을 **한 번의 os.rename** 으로 무덤에 옮긴다. 옮긴 곳(없으면 None).

    왜 지우지 않고 미나 — `shutil.rmtree` 는 파일을 하나씩 지우느라 오래 걸린다
    (실측 4.20ms, 최대 8.31ms · 항목 32개짜리 세션방). 그 몇 ms 동안 세션방은 반쯤
    지워진 채로 살아 있어서, 그 사이 돌아온 요청이 **속이 파인 방**에 글을 쓴다
    (적대리뷰 ①의 `세션방=['마지막활동']` 이 그 모양이다). `os.rename` 은 실측 183µs·
    최대 351µs 의 한 걸음이고 원자적이다 — 이름이 넘어가는 순간부터 그 방은 아무도
    못 찾고, 돌아온 요청은 **새 방**을 얻는다(자료뿌리가 표를 보고 다시 세운다).
    """
    방 = 자료뿌리.세션방(열쇠)
    무덤 = 무덤뿌리()
    os.makedirs(무덤, exist_ok=True)
    import uuid
    간곳 = os.path.join(무덤, f"{열쇠}-{uuid.uuid4().hex[:8]}")
    try:
        os.rename(방, 간곳)
    except OSError:
        return None                    # 남이 먼저 밀어냈다 — 그게 맞는 상태다
    return 간곳


def 무덤치우기(묵힘초=0.0):
    """무덤에 남은 옛 방을 **바로** 쓸어 낸다 — 고아 청소기(적대리뷰 ①, 2026-08-09 닫음).

    무덤에 뭔가 남아 있다는 것은 밀어낸 세션방이다. `끝내기` 가 이제 rmtree 를 **빗장
    안에서** 하므로(아래 참고), 정상 흐름에서는 무덤에 온전한 방이 남지 않는다. 그런데도
    여기 뭔가 있다면 그것은 **rename~rmtree 사이에 프로세스가 죽어** 남은 고아다 — 그
    안엔 문서 원문이 통째로 들어 있고, 세션 밖(sessions/.무덤) 자리다. "마감 뒤 사례
    소멸"의 구멍이라 **바로** 지운다(묵힘초=0). 예전엔 60초(빗장묵힘초)를 두고 봤는데
    그 60초 동안 원문이 세션 밖에 남았다 — 그 창을 닫는 것이 이 고침이다.

    나이(묵힘초)를 기본 0 으로 둘 수 있는 근거 — 무덤 안 방은 **언제나 고아**다.
    제 방(sessions/<열쇠>)이 이미 rename 으로 떨어져 나갔으니 살아 있는 세션이 아니고,
    돌아온 요청은 자료뿌리가 세운 **새 방**을 받는다(못 찾는다). 살아 있는 `끝내기` 가
    빗장 안에서 같은 방을 rmtree 하는 그 몇 ms 동안 이 청소기가 겹쳐 건드려도
    `ignore_errors=True` 라 서로 다치지 않는다(둘 다 지우면 먼저 지운 쪽이 이기고
    나머지는 조용히 no-op). 그래서 무덤 안 방은 나이와 무관하게 지워도 안전하다.
    호출자가 나이를 주면 그 이상 묵은 것만 지운다(시험·특수 상황용).

    서버 시작·다음 세션 활동 어디서 도나 — `청소()` 가 요청마다 맨 먼저 이걸 부른다
    (게으른 청소). 서버가 막 떴어도 첫 요청이 곧 쓸어 낸다. serve.py 는 손대지 않는다.
    """
    무덤 = 무덤뿌리()
    if not os.path.isdir(무덤):
        return 0
    이제 = time.time()
    n = 0
    for 이름 in os.listdir(무덤):
        p = os.path.join(무덤, 이름)
        if 묵힘초 > 0:
            try:
                if 이제 - os.path.getmtime(p) <= 묵힘초:
                    continue
            except OSError:
                continue
        shutil.rmtree(p, ignore_errors=True)
        n += 1
    return n


def 끝내기(열쇠, 사유="마감", 한도=None):
    """후보를 뽑아 남기고 **세션 디렉터리를 통째로 지운다.**

    순서가 중요하다 — 지우고 나면 뽑을 것이 없다. 후보를 못 남기면 지우지도 않는다
    (조용히 자료만 사라지는 것보다, 남아서 다음 청소에 다시 걸리는 편이 낫다).

    **빗장을 쥐고 한다**(적대리뷰 ①⑥). 전에는 `후보남기기() → rmtree()` 두 걸음을
    묶는 배타성이 하나도 없어서, 요청 N개가 같은 만료 세션을 동시에 끝내면 후보
    파일이 N개 생기고(uuid 라 이름이 안 겹쳐 전부 남는다) rmtree 는 하나만 성공했다.
    후보 파일은 세션이 남기는 유일한 통계이고 출시계획 1-6 A안의 그 분모다 — 몇 배로
    부푼 값은 잰 값이 아니다(규칙 1). 이제 빗장을 잡은 하나만 끝낸다.

    `한도` 를 주면 **빗장 안에서 만료를 다시 잰다** — 그 사이에 요청이 들어와 살아난
    세션은 여기서 살려 보낸다. 명시적 마감(사용자가 누른 것)은 한도를 안 준다.
    """
    방 = 자료뿌리.세션방(열쇠)
    if not os.path.isdir(방):
        return {"ok": False, "로그": "그런 세션이 없습니다"}
    with 자료뿌리.빗장(방, 기다림초=0, 필수=False) as 잡음:
        if not 잡음:
            # 남이 지금 이 세션을 정리하고 있다. 후보를 하나 더 쓰면 통계가 부푼다.
            return {"ok": False, "로그": "이 세션은 지금 다른 요청이 정리하고 있습니다"}
        if not os.path.isdir(방):
            return {"ok": False, "로그": "그런 세션이 없습니다"}
        if 한도 is not None:
            if (time.time() - 마지막활동(열쇠)) <= 한도:
                return {"ok": False, "로그": "그 사이에 요청이 들어와 살아 있는 세션입니다"}
            if 열쇠 in 자료뿌리.쓰이는열쇠들():
                # 시계는 멈춰 있지만 **일하는 중**이다(자료뿌리.쓰이는열쇠들 주석 참고)
                return {"ok": False, "로그": "지금 요청을 처리하고 있는 세션입니다"}
        껍데기 = not 요청받은적있나(열쇠)
        p, n = (None, 0) if 껍데기 else 후보남기기(열쇠, 사유)
        간곳 = _밀어내기(열쇠)
        if 간곳 is None:
            return {"ok": False, "로그": "그런 세션이 없습니다"}
        # rmtree 를 **빗장 안**에서 한다(2026-08-09, ② 고침). 전에는 여기서 빗장을 놓고
        # 밖에서 지웠는데, rename 직후~rmtree 직전에 죽으면 문서 원문 통째가 sessions/.무덤
        # (세션 밖)에 ~60초+ 남았다("마감 뒤 사례 소멸"의 구멍). 빗장 안으로 들이는 값은
        # 실측(이 기계·APFS·32파일 방): rmtree median 2.4ms·max 11.1ms 만큼 빗장을 더
        # 쥐는 것뿐이다. `끝내기` 는 `기다림초=0`(위) 로 빗장을 잡으므로 같은 세션을
        # 동시에 끝내려는 요청은 **기다리지 않고 즉시** 물러난다("다른 요청이 정리하고
        # 있습니다") — 더 쥐는 시간을 아무도 기다리지 않는다. 다른 세션은 빗장이 방마다
        # 따로라(빗장(방)) 경합이 없다. rename 을 먼저 쓰는 이유(속 파인 방에 못 쓰게)는
        # 그대로 산다 — 이름이 넘어간 순간부터 아무도 못 찾고, 그 다음 지운다.
        shutil.rmtree(간곳, ignore_errors=True)
    if 껍데기:
        return {"ok": True, "값": {"후보수": 0, "후보파일": None, "사유": 사유,
                                 "껍데기": True},
                "로그": "요청을 한 번도 안 받은 빈 세션방을 치웠습니다 "
                      "— 후보는 남기지 않습니다(산 적이 없는 것은 분모가 아닙니다)"}
    return {"ok": True, "값": {"후보수": n, "후보파일": os.path.basename(p),
                             "사유": 사유},
            "로그": f"세션을 마쳤습니다 — 내용은 지웠고 익명 후보 {n}건을 남겼습니다"}


def 청소(지금세션=""):
    """만료된 세션을 훑어 정리한다. **게으른 청소** — 요청이 올 때마다 한 번씩 돈다.

    스레드를 안 쓰는 까닭(WP-S2 명세) — 청소 스레드는 서버가 죽을 때 같이 안 죽고,
    시험에서 재현이 안 되며, 무엇보다 이 일은 listdir 하나라 요청 하나에 얹어도
    싸다. 지금 처리 중인 세션은 방금 활동을 적었으니 어차피 안 걸리지만, 시각
    해상도 때문에 걸리는 일이 없게 이름으로도 한 번 더 뺀다.

    **두 번 잰다**(적대리뷰 ①). 한 번 재고 지우면, 재는 시점과 지우는 시점 사이에
    돌아온 사용자의 세션이 통째로 사라진다 — 사용자는 200 ok 와 빈 목록을 받는다.
    그래서 ① 싸게 훑어 만료 후보를 고르고 ② 만료 후보가 하나라도 있을 때만
    `재검사여유초` 만큼 두었다가 ③ 세션마다 빗장을 쥐고 **다시 재서** 지운다.
    만료 세션이 없는 흔한 길에서는 자지도, 빗장을 잡지도 않는다.
    """
    한도 = 만료초()
    이제 = time.time()
    무덤치우기()
    # 일하는 중인 세션은 시계가 멈춰 있어 만료로 보인다 — 시각 말고 '쥐고 있는가' 로 뺀다
    # (`자료뿌리.쓰이는열쇠들` 주석에 실측을 적어 뒀다).
    쓰는중 = 자료뿌리.쓰이는열쇠들()
    후보 = [열쇠 for 열쇠, 때 in 살아있는것()
          if 열쇠 != 지금세션 and 열쇠 not in 쓰는중 and 이제 - 때 > 한도]
    if not 후보:
        return []
    time.sleep(재검사여유초)               # 그 사이에 돌아온 요청이 mtime 을 되살린다
    지운것 = []
    for 열쇠 in 후보:
        try:
            r = 끝내기(열쇠, "만료", 한도=한도)
        except OSError as e:
            sys.stderr.write(f"세션 청소 실패({열쇠[:6]}…): {e}\n")
            continue
        if r["ok"] and r["값"].get("후보파일"):
            지운것.append({"익명id": r["값"]["후보파일"], "후보수": r["값"]["후보수"]})
    return 지운것


def main():
    깃발 = sys.argv[1:] or ["--목록"]
    if "--청소" in 깃발:
        지운것 = 청소()
        print(f"만료 세션 {len(지운것)}건 정리 (만료 {만료초()}초)")
        for x in 지운것:
            print(f"  · 후보 {x['후보수']}건 → feedback/candidates/{x['익명id']}")
        return 0
    한도, 이제 = 만료초(), time.time()
    삶 = 살아있는것()
    print(f"세션 {len(삶)}건 · 만료 {한도}초 · {자료뿌리.세션들뿌리()}")
    for 열쇠, 때 in 삶:
        남음 = int(한도 - (이제 - 때))
        print(f"  {열쇠[:8]}…  마지막활동 {time.strftime('%H:%M:%S', time.localtime(때))}"
              f"  남은 {남음}초" + ("  ← 만료" if 남음 <= 0 else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
