def 활동적기(열쇠):
    """마지막 활동 시각을 세션 디렉터리에 적는다.

    **mtime 이 정본**이고 파일 내용(ISO 시각)은 사람이 읽으라고 같이 적는다.
    시각을 파일 내용으로만 두면 손으로 고칠 때 두 값이 갈리고, mtime 으로만 두면
    디렉터리를 들여다본 사람이 무엇인지 모른다.
    """
    p = 자료뿌리.마지막활동길(열쇠)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    자료뿌리.원자쓰기(p, time.strftime("%Y-%m-%dT%H:%M:%S") + "\n")
    return p


def 마지막활동(열쇠):
    """마지막 활동 시각(epoch). 파일이 없으면 세션 디렉터리 자체의 시각을 쓴다."""
    p = 자료뿌리.마지막활동길(열쇠)
    try:
        return os.path.getmtime(p)
    except OSError:
        try:
            return os.path.getmtime(자료뿌리.세션방(열쇠))
        except OSError:
            return 0.0


def 만료초():
    """무반응 몇 초에 끊나. 관리자가 `설정.json` 으로 조정한다(출시계획 3-4 ②).

    설정 파일이 없거나 값이 이상하면 **기본값으로 조용히 돌아가지 않고** 기본값을
    쓰되, 값이 있는데 못 읽은 경우는 그 자체가 관리자 실수라 나중에 WP-S5 가
    화면에서 보여 준다. 여기서는 서버가 멈추면 안 되므로 죽지 않는다.
    """
    try:
        with open(자료뿌리.설정길(), encoding="utf-8") as f:
            v = (json.load(f) or {}).get("세션만료초")
        v = int(v)
        return v if v > 0 else 기본만료초
    except Exception:
        return 기본만료초


def 살아있는것():
    """지금 있는 세션들 — [(열쇠, 마지막활동epoch)]. 열쇠 꼴이 아닌 디렉터리는 무시한다."""
    안 = 자료뿌리.세션들뿌리()
    out = []
    try:
        이름들 = sorted(os.listdir(안))
    except OSError:
        return out
    for 이름 in 이름들:
        if not 자료뿌리.열쇠올바른가(이름):
            continue                       # 손으로 만든 잡동사니는 우리 것이 아니다
        if not os.path.isdir(os.path.join(안, 이름)):
            continue
        out.append((이름, 마지막활동(이름)))
    return out


# ── 원장 후보 — 내용은 버리고 규칙 이름만 ───────────────────────────────

def 후보뽑기(열쇠):
    """그 세션에서 **어느 규칙이 울렸는지**만 모은다. 문서 글자는 한 자도 안 담는다.

    긁는 자리는 지금 실제로 규칙 이름이 쌓이는 두 곳뿐이다(코드를 보고 정한 것이다):

      ① `build/observed/_규칙기록.jsonl` — `자료뿌리.규칙적기()` 가 적는다.
         문체검사의 soft/hard 규칙 id · 되묻기(어긋남) 건수 · HWPX 완전성 가드 구멍이
         여기로 온다. **세션이 있을 때만** 적히므로 개발·CLI 경로는 한 줄도 안 남긴다.
      ② `build/observed/_ledger-candidates.json` — `build/observe.py` 가 예전부터
         적어 온 "도구·규칙 차원의 문제로 보이는 것". 거기엔 **문서 이름**이 붙어
         있으므로 여기서 떼어 내고 (장르, 사실)만 남긴다.

    관측 기록 본체(`build/observed/<문서>.json`)의 `_실패` 도 같은 성격이지만
    `_ledger-candidates.json` 이 이미 그것을 모아 둔 것이라 두 번 세지 않는다.

    후보가 0건인 것은 **정상이다** — 아무 규칙도 안 울린 세션이 있다.
    """
    방 = 자료뿌리.세션방(열쇠)
    관측 = os.path.join(방, "build", "observed")
    셈 = {}

    def 더(출처, 규칙, n=1):
        열 = (출처, 규칙)
        셈[열] = 셈.get(열, 0) + int(n)

    기록 = os.path.join(관측, "_규칙기록.jsonl")
    if os.path.exists(기록):
        with open(기록, encoding="utf-8") as f:
            for 줄 in f:
                줄 = 줄.strip()
                if not 줄:
                    continue
                try:
                    d = json.loads(줄)
                except ValueError:
                    continue
                for r, n in (d.get("규칙") or {}).items():
                    더(str(d.get("출처") or "?"), str(r), n)

    옛후보 = os.path.join(관측, "_ledger-candidates.json")
    if os.path.exists(옛후보):
        try:
            with open(옛후보, encoding="utf-8") as f:
                항목 = (json.load(f) or {}).get("항목") or []
        except ValueError:
            항목 = []
        for it in 항목:
            # **문서 이름은 버린다.** 사용자가 지은 이름이라 내용을 짐작하게 한다.
            # 사유(사실)도 sink 규율을 지난다 — observe.py 의 `_실패` 는 "계측 실패 —
            # <오류>" 같은 **자유 문장**이라 내용이 섞일 수 있다(적대리뷰 ①). `규칙라벨정리`
            # 가 문장을 버리므로 대개 None 이 되고, 그러면 통제 어휘인 **장르 id** 만 남는다
            # (관리자는 "이 장르에서 관측 실패가 몇 건" 이라는 규칙 차원 신호를 얻고,
            # 후보 파일엔 문서 내용이 한 자도 안 들어간다). 장르도 규율을 지난다.
            장르 = 자료뿌리.규칙라벨정리(it.get("장르")) or 자료뿌리.거른버킷
            사실 = 자료뿌리.규칙라벨정리(it.get("사실"))
            더("관측", f"{장르}:{사실}" if 사실 else 장르)

    return [{"출처": 출처, "규칙": 규칙, "횟수": n}
            for (출처, 규칙), n in sorted(셈.items())]


def 요청받은적있나(열쇠):
    """이 세션방이 **요청을 한 번이라도 받았나** — `마지막활동` 파일이 있느냐로 잰다.

    serve.py 는 GET·HEAD·POST 세 문 어디로 들어와도 `활동적기()` 를 맨 먼저 부른다
    (`_세션으로`). 그래서 그 파일이 없는 방은 요청을 한 번도 안 받은 **빈 껍데기**다.

    껍데기가 왜 생기나(2026-08-07 실측) — 세션을 마감하면 방이 사라지는데, 그 뒤
    **같은 요청의 응답을 만들면서** `자료뿌리.뿌리()` 를 한 번 더 부르는 자리가 있다
    (serve.py `_봉합` → `지울앞머리`). 뿌리가 없어졌으니 자료뿌리가 규칙대로 다시
    세운다 — 마감한 열쇠로 디렉터리·등록부만 있는 방이 하나 남는다. 그 방을 나중에
    청소가 '만료 세션'으로 세면 **익명 후보가 하나 더 생긴다** — 세션 하나가 후보
    둘을 남기는 셈이라 관리자가 보는 분모가 부푼다(⑥이 막으려던 바로 그 오염).
    그래서 껍데기는 지우되 **후보는 안 남긴다** — 산 적이 없는 것은 분모가 아니다.
    """
    return os.path.exists(자료뿌리.마지막활동길(열쇠))


def 후보남기기(열쇠, 사유):
    """세션을 지우기 전에 익명 후보 파일 하나를 남긴다. 경로를 돌려준다.

    후보가 0건이어도 **파일은 남긴다** — "세션이 몇 개 지나갔는데 아무 규칙도 안
    울렸다" 는 것 자체가 관리자에게 필요한 정보다(0건 기록이 없으면 분모를 모른다).
    """
    import uuid
    낼곳 = 자료뿌리.후보뿌리()
    os.makedirs(낼곳, exist_ok=True)
    후보 = 후보뽑기(열쇠)
    익명id = uuid.uuid4().hex[:8]           # 열쇠에서 파생시키지 않는다(머리말 참고)
    본 = {"때": time.strftime("%Y-%m-%dT%H:%M:%S"),
         "익명id": 익명id,
         "사유": 사유,
         "산것초": int(max(0, time.time() - _생년(열쇠))),
         "후보수": len(후보),
         "후보": 후보,
         "_doc": ("익명 원장 후보(출시계획 1-6 A안). 규칙 id 와 횟수만 있고 문서 "
                  "이름·본문은 없다. 관리자가 읽고 채택/기각한다.")}
    p = os.path.join(낼곳, f"{time.strftime('%Y%m%d')}-{익명id}.json")
    자료뿌리.원자json(p, 본, indent=1)             # 원자 쓰기(WP-S2 ③)
    return p, len(후보)


def _생년(열쇠):
    try:
        return os.path.getctime(자료뿌리.세션방(열쇠))
    except OSError:
        return time.time()


