# C-3 시각·기산점·부칙 날짜
# ══════════════════════════════════════════════════════════════════════════
# 물결 — 반각 '~', 수학 '∼'(U+223C), 파도 '〜'(U+301C), **전각 '～'(U+FF5E, 한글 입력기·HWP
# 원자료에 흔하다, 적대검토 M4)**.
_물결 = "~∼〜～"
# 앞뒤 공백 변형('09:00 ~ 18:00', '18:00 까지')도 받는다(적대검토 M3 — '까지 까지로' 깨짐).
_시각_RX = re.compile(r"(?<![\d:])(\d{1,2}:\d{2})\s*[~∼〜～]\s*(\d{1,2}:\d{2})(?![\d:])(\s?까지)?")
_까지뒤조사 = {"을": "를", "를": "를", "은": "는", "는": "는", "이": "가", "가": "가",
            "과": "와", "와": "와", "으로": "로", "로": "로", "에": ""}   # '까지에'는 '까지'(F11)
_시각뒤조사_RX = re.compile(r"^\s?(으로|로|을|를|은|는|이|가|과|와|에)(?![가-힣])")
# 비(比)·배율 — '경쟁률 1:10~1:20'은 시각이 아니다(적대검토 L4).
_비율앞말_RX = re.compile(r"(?:비율|경쟁률|배율|대비|성비|(?<![가-힣])비)\s*(?:은|는|이|가|을|를|의|도)?\s*$")
# 기산점 '…로부터' — 앞말이 **날짜 명사**일 때만 고친다(적대검토 H2: '파일로부터'·'이메일로부터'·
# '위탁한 일(업무)로부터'가 '…부터'가 되어 출처가 순서로 뜻이 바뀌었다).
#  · '날로부터'(다음날·그날·받은 날) — 늘 날짜다.
#  · 숫자에 붙은 '일'('1일로부터'·'3월 1일로부터')·날짜 합성어('신청일·승인일·시행일…')
#  · 관형형 뒤 맨 '일'('신청한 일로부터')은 뒤가 기간('7일 이내'·'30일'·'1년')일 때만.
_기산_날_RX = re.compile(r"날로부터")
_기산일말 = ("신청", "승인", "통보", "통지", "접수", "시행", "공포", "발령", "휴", "전", "다음", "익", "기준",
          "지급", "계약", "종료", "만료", "임용", "발생", "완료", "허가", "제출", "개시", "시작", "등록",
          "결정", "처분", "요", "해당", "퇴직", "입사", "채용", "교부", "납부", "도래", "경과")
_기산_일_RX = re.compile(r"(?:(?<=\d)|(?<=\d\s)|(?<=" + ")|(?<=".join(_기산일말) + r"))일로부터")
_기산_맨일_RX = re.compile(r"(?<=[한된은는]\s)일로부터(?=\s*(?:\d+\s*(?:일|개월|년|주|시간)|이내|까지))")
_부칙날짜_RX = re.compile(r"([\d○]{4})\.\s?([\d○]{1,2})\.\s?([\d○]{1,2})\.\s?(부터|에)")


def _수떼기(x):
    return str(int(x)) if x.isdigit() else x


def _시각교정(t, 기록, 경로):
    if not any(c in t for c in _물결):
        return t
    나온다, i = [], 0
    for m in _시각_RX.finditer(t):
        뒤 = t[m.end():]
        if re.match(r"^\s?(사이|동안)", 뒤):
            continue       # '…~… 사이'는 고치지 않는다 — soft W-조문물결이 알린다
        if _비율앞말_RX.search(t[max(0, m.start() - 12):m.start()]):
            continue       # '경쟁률 1:10~1:20' — 비(比)라 시각이 아니다(soft W-조문물결)
        나온다.append(t[i:m.start()])
        꼬리 = ""
        건너뜀 = 0
        if not m.group(3):
            c = _시각뒤조사_RX.match(뒤)
            if c:
                꼬리 = _까지뒤조사[c.group(1)]
                건너뜀 = c.end()
        나온다.append(f"{m.group(1)}부터 {m.group(2)}까지{꼬리}")
        i = m.end() + 건너뜀
        기록.append(f"{경로}: 시각 '{m.group(0)}' → '{m.group(1)}부터 {m.group(2)}까지'")
    나온다.append(t[i:])
    return "".join(나온다)


def _기산교정(t, 기록, 경로):
    새 = _기산_날_RX.sub("날부터", t)
    새 = _기산_일_RX.sub("일부터", 새)
    새 = _기산_맨일_RX.sub("일부터", 새)
    if 새 != t:
        기록.append(f"{경로}: 기산점 '…로부터' → '…부터'")
    return 새


def _부칙날짜교정(t, 기록, 경로):
    def _바꿔(m):
        새 = f"{_수떼기(m.group(1))}년 {_수떼기(m.group(2))}월 {_수떼기(m.group(3))}일{m.group(4)}"
        기록.append(f"{경로}: 부칙 날짜 '{m.group(0)}' → '{새}'")
        return 새
    return _부칙날짜_RX.sub(_바꿔, t)


