def _글마디(원문):
    """자료 글을 문장(마침표·줄바꿈) 단위로 자른다 — 숫자 바로 뒤 온점은 문장 끝이 아니다(4차 ③: 날짜 '2027. 3. 2.'·
    'M. D.'·'07. 01.'·소수 '1.5배'·판 'v2.1'·'6.1부터' 를 모두 한 규칙으로 — 3차는 날짜 꼴마다 가림을 두어 '07 / 부터'·
    '6 / 1부터'·'1은 …'처럼 구절이 깨졌다). 숫자 뒤 빈칸 하나 뒤의 온점('2027 . 03 . 02')도 같다. 전각 숫자는 반각으로
    보고 자르되 구절은 자료 글 그대로 낸다."""
    원 = str(원문 or "")
    판 = 원.translate(_날짜글꼴)          # 한 글자를 한 글자로 — 자리가 같다
    나온, 앞 = [], 0
    for m in re.finditer(r"(?<!\d)(?<!\d\s)\.|[。!?\n]", 판):
        나온.append(원[앞:m.start()])
        앞 = m.end()
    나온.append(원[앞:])
    return [s.strip() for s in 나온 if s.strip()]


