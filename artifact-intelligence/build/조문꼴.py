def _자료연도없는(자료):
    """자료 날짜 집합에서 연도가 적혀 있지 않은 것 — ({(월, 일)}, {일}) (4차 ①: 이 월·일에는 초안이 어떤 연도를 붙여도
    지어냄으로 걸지 않는다 — 연도를 추론하지 않는다). 일만 아는 날짜는 지금 날짜들()이 내지 않는다(빈 집합)."""
    return ({(x[1], x[2]) for x in 자료 if x[0] is None and x[1] and x[2]},
            {x[2] for x in 자료 if x[0] is None and x[1] is None and x[2]})


