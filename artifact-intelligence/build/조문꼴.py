# C-2 술어 계열
# ══════════════════════════════════════════════════════════════════════════
# 셈 표지 — 술어 하나를 한 번만 센다. '된'(U+B41C)은 '되'(U+B418)와 다른 음절이라 따로 적는다
# (예전 `아니\s?되`는 '아니 된다'를 못 세어 전통형 문서를 현대형으로 오판했다, 적대검토 F2).
# '하여서는 아니 된다'는 한 덩이로 센다. '해서는 아니 된다'는 두 계열이 섞인 꼴이라 전통('아니 된')
# 하나·현대('해서는') 하나로 센다(적대검토 F1(a)·L3 — 예전엔 둘 다 못 세어 (0, 0)이었다). 그래서 이
# 꼴만 있는 문서는 1:1 → 전통형으로 고쳐진다.
_전통_RX = re.compile(r"아니하|하여야|되어야|(?:하여서는\s?)?아니\s?(?:되|된|돼)")
# '안 된'(관형 '승인이 안 된 장비')도 현대형이다 — 표에 없어 못 고치므로 셈에 넣어야 '전부 아니면
# 전무'가 제대로 막고 알림이 거짓('맞췄습니다')이 되지 않는다(적대검토 L3).
# 맨 '해서는'은 세지 않는다 — '대해서는'(대하여서는)은 술어 부정이 아니라 셈에 넣으면 커밋 표본
# 두 건이 '섞임'으로 오판됐다(이번 수정 중 실측). 부정 술어 앞의 '해서는'만 센다.
_현대_RX = re.compile(r"해서는\s?안\s?(?:되|된|돼)|해서는(?=\s?아니\s?(?:되|된|돼))|않|해야|돼야|"
                    r"(?<![가-힣])안\s?(?:된다|돼|되는|되며|되고|되나|된)")

# '않-' 어미표 — 긴 것부터(는다·아야가 는·아 보다 먼저).
_않어미 = [("는다", "아니한다"), ("도록", "아니하도록"), ("으면", "아니하면"), ("아야", "아니하여야"),
         ("거나", "아니하거나"), ("으며", "아니하며"), ("는", "아니하는"), ("은", "아니한"),
         ("을", "아니할"), ("고", "아니하고"), ("았", "아니하였"), ("아", "아니하여"),
         ("게", "아니하게"), ("음", "아니함")]
_않_RX = re.compile(r"(?<!그렇지 )(?<!그렇지)않(" + "|".join(e for e, _ in _않어미) + ")")
_않표 = dict(_않어미)
_술어치환 = [
    # 뒤 어미('된다'·'되며'·'되는'·'된')는 그대로 두고 앞만 바꾼다(예전엔 '된다'만 받았다).
    (re.compile(r"해서는\s?(?:아니|안)\s?(?=되|된)"), "하여서는 아니 "),
    (re.compile(r"(?<=[가-힣])서는\s?안\s?(?=되|된)"), "서는 아니 "),
    # 맨 '해야'('신고를 해야 한다')도 '하여야'다 — 앞말에 붙은 꼴만 받으면 이 한 곳 때문에 전부
    # 아니면 전무가 문서 전체 교정을 막았다(적대검토 F1). '해야만'도 받는다.
    (re.compile(r"해야(만)? (한다|하며|하고|할|하는)"), r"하여야\1 \2"),
    (re.compile(r"돼야 (한다|하며|하고)"), r"되어야 \1"),
    (re.compile(r"아니된다"), "아니 된다"),
]


def 술어셈(doc):
    """(전통형 수, 현대형 수) — 조문 자리의 인용 밖 글만 센다."""
    전, 현 = 0, 0
    for _경로, v, _쓰기 in _조문자리(doc):
        t = _밖글(v)
        전 += len(_전통_RX.findall(t))
        현 += len(_현대_RX.findall(t))
    return 전, 현


def _술어한칸(t):
    t = _않_RX.sub(lambda m: _않표[m.group(1)], t)
    for rx, 새 in _술어치환:
        t = rx.sub(새, t)
    return t


def _술어교정(doc, 기록):
    """전통형 다수일 때만, 전부 고칠 수 있을 때만 고친다. 고쳤으면 True, 판정 사유 문자열."""
    전, 현 = 술어셈(doc)
    띄어쓰기만 = any("아니된다" in _밖글(v) for _p, v, _w in _조문자리(doc))
    if 현 == 0 and not 띄어쓰기만:
        return None
    if 현 > 전:
        # 순수 현대형(전통형 0)은 기관이 고른 계열이라 알릴 것도 없다(온톨로지 jomun.종결.rule).
        return (f"술어 계열: 현대형 {현}·전통형 {전} — 현대형이 많아 고치지 않았습니다" if 전 else None)
    바꿀 = []
    for 경로, v, 쓰기 in list(_조문자리(doc)):
        새 = _밖에서(v, _술어한칸)
        if 새 != v:
            바꿀.append((경로, v, 새, 쓰기))
    # 전부 아니면 전무 — 고친 뒤에도 현대형 표지가 남으면(표에 없는 어미·'그렇지 않-'·맨 '안
    # 된다') 한 곳도 안 고친다.
    남은 = 0
    바뀐경로 = {p: 새 for p, _v, 새, _w in 바꿀}
    for 경로, v, _w in _조문자리(doc):
        남은 += len(_현대_RX.findall(_밖글(바뀐경로.get(경로, v))))
    if 남은:
        return (f"술어 계열: 고칠 수 없는 현대형 {남은}곳이 남아(표에 없는 어미·'그렇지 않-'·"
                "'안 된다'·'안 된') 문서 전체를 고치지 않았습니다")
    for 경로, v, 새, 쓰기 in 바꿀:
        쓰기(새)
    if 바꿀:
        기록.append(f"술어 계열을 전통형으로 맞췄습니다({len(바꿀)}칸 — '않도록'→'아니하도록'·"
                  f"'해야'→'하여야' 등, 고치기 전 전통형 {전}·현대형 {현})")
    return None


