_지난날_RX = re.compile(r"(\d{1,3})\s?(일|개월)\s?(?:이|을)?\s?(?:지난|경과한|경과된|지나|경과하)|(\d{1,3})\s?일\s?(?:후|뒤)(?![가-힣])")


def _문장자리들(t):
    """(시작, 끝) — _글마디 와 같은 자르기(숫자 뒤 온점은 문장 끝이 아니다)."""
    자리, 앞 = [], 0
    for m in re.finditer(r"(?<!\d)(?<!\d\s)\.|[。!?\n]", t):
        자리.append((앞, m.start()))
        앞 = m.end()
    자리.append((앞, len(t)))
    return 자리


def _마지막날짜(글):
    """글 안에서 **맨 뒤에** 나온 날짜 하나 — (연|None, 월, 일) 또는 None(자료 쪽 읽기)."""
    후보 = []
    for rx, 꼴 in ((_풀날짜_RX, "풀"), (_두자리연도_RX, "두"), (_월일_RX, "월일"), (_점월일_RX, "월일"), (_꼬리점월일_RX, "월일")):
        for m in rx.finditer(글):
            g = [int(x) for x in m.groups()]
            y, mo, d = ((g[0], g[1], g[2]) if 꼴 == "풀" else (2000 + g[0], g[1], g[2]) if 꼴 == "두" else (None, g[0], g[1]))
            if 1 <= mo <= 12 and 1 <= d <= 31:
                후보.append((m.start(), (y, mo, d)))
        글 = rx.sub(lambda mo: " " * len(mo.group(0)), 글)     # 긴 꼴을 먼저 지워 속의 'M. D.'를 다시 읽지 않는다
    return max(후보)[1] if 후보 else None


def _상대달(원문):
    """자료의 상대 달 표현 → (셈한 날짜 {(연|None, 월, 일)}, 기준이 오늘인 날 {일})."""
    import calendar
    t = str(원문 or "").translate(_날짜글꼴)
    셈, 날 = set(), set()
    자리 = _문장자리들(t)

    def _기준(pos, 앞문장=True):
        for k, (a, b) in enumerate(자리):
            if a <= pos <= b:
                앞글 = t[a:pos]
                기 = _마지막날짜(앞글)
                if 기 is None and k > 0 and 앞문장:
                    기 = _마지막날짜(t[자리[k - 1][0]:자리[k - 1][1]])
                return 기
        return None

    def _달끝(y, mo):
        return calendar.monthrange(y or 2001, mo)[1]      # 연도 모르면 평년

    def _달더함(y, mo, n):
        k = mo - 1 + n
        return (y + k // 12 if y else None), k % 12 + 1

    def _날더함(기, n):
        import datetime
        if not 기[0]:
            return None
        try:
            x = datetime.date(기[0], 기[1], 기[2]) + datetime.timedelta(days=n)
        except ValueError:
            return None
        return (x.year, x.month, x.day)

    for m in _같은달_RX.finditer(t):
        d = int(m.group(1))
        기 = _기준(m.start())
        if 기 and 1 <= d <= _달끝(기[0], 기[1]):
            셈.add((기[0], 기[1], d))
        elif 1 <= d <= 31:
            날.add(d)
    for m in _다음달_RX.finditer(t):
        d = int(m.group(3))
        if not 1 <= d <= 31:
            continue
        기 = _기준(m.start(), 앞문장=False)            # 같은 문장(그 표현 앞)의 기준 날짜
        기앞 = 기 or _기준(m.start())                  # 없으면 바로 앞 문장
        # 기준을 가리키는 말이 붙은 것만 셈으로 확정한다 — '익월'·'그 다음 달'·'…한 날이 속하는 달의 다음 달'. 맨 '다음 달·내달·
        # 이달'은 같은 문장에 날짜가 있어도 기준이 그 날인지 오늘인지 모호하니 셈한 날도 받고 그 날 면제도 둔다(정밀도 우선).
        명시 = m.group(1) == "익" or bool(re.search(r"(?:그|달의|월의)\s?$", t[max(0, m.start() - 4):m.start()]))
        if 기앞:
            y, mo = _달더함(기앞[0], 기앞[1], 1 if m.group(1) else 0)
            if d <= _달끝(y, mo):
                셈.add((y, mo, d))
        if not (기 and 명시):
            날.add(d)                                   # 기준이 오늘이거나 모호 — 그 날에는 어떤 연·월도 걸지 않는다
    for m in _지난날_RX.finditer(t):
        기 = _기준(m.start())
        if not 기 or not 기[0]:
            continue
        n = int(m.group(1) or m.group(3))
        if m.group(2) == "개월":
            y, mo = _달더함(기[0], 기[1], n)
            끝 = (y, mo, min(기[2], _달끝(y, mo)))
            셈.update(x for x in (끝, _날더함(끝, 1)) if x)
        else:
            셈.update(x for x in (_날더함(기, n), _날더함(기, n + 1)) if x)
    for m in _다음날_RX.finditer(t):
        기 = _기준(m.start())
        if 기:
            y, mo, d = 기
            if d < _달끝(y, mo):
                셈.add((y, mo, d + 1))
            elif mo < 12:
                셈.add((y, mo + 1, 1))
            else:
                셈.add((y + 1 if y else None, 1, 1))
    for m in _말일_RX.finditer(t):
        if m.group(2) or m.group(3):                    # 다음 달·이번 달 말일 — 위 '다음 달 N일'과 같은 규칙
            기 = _기준(m.start(), 앞문장=False)
            기앞 = 기 or _기준(m.start())
            명시 = m.group(2) == "익" or bool(re.search(r"(?:그|달의|월의)\s?$", t[max(0, m.start() - 4):m.start()]))
            if 기앞:
                y, mo = _달더함(기앞[0], 기앞[1], 0 if (m.group(3) or m.group(2) == "이번") else 1)
                셈.add((y, mo, _달끝(y, mo)))
            if not (기 and 명시):
                날.update({28, 29, 30, 31})
            continue
        기 = _기준(m.start())
        if 기:
            셈.add((기[0], 기[1], _달끝(기[0], 기[1])))
        else:
            날.update({28, 29, 30, 31})
    return 셈, 날


# 연도 없는 월·일 언급의 갈래(reg12 fixup '26-09-30, reg12/verify.md H1) — 11차 구현은 "상대 연도 낱말 목록에 든 말이 붙은
# 언급만 면제"라 목록 밖 말('이듬 해'·'차기 연도'·'다음 회계연도'·'새해'·'후년')이면 맞는 초안 '2027년 3월 2일'이 옛 제정일
# '2014. 3. 2.'의 되풀이로 읽혀 교정 지시 길에 올랐다(새 40건 198경우). 방향을 뒤집는다(정밀도 우선 — 목록이 모자라면
# 놓침이 되지 헛걸림이 되지 않게): 되풀이로 읽어 면제하지 않는 것은 **확실한 되풀이 표지**가 붙은 언급뿐이다 —
#   앞(같은 문장 14자 안): '다만'·'매년(도)'·'매해'·'해마다'·'시행일'·'같은 날'·'당일' · 뒤: '전에·전까지·이전·전 '.
# 상대 연도 말(목록, 또는 월·일 바로 앞의 숫자 없는 해 말 '…해·…연도·…년도·…년')이 붙은 언급은 표지보다 먼저 면제다.
# 표지 없는 맨 되풀이('등록 창구는 4. 1.에 연다')는 4차처럼 면제로 두고 확인 물음이 구절을 보여 준다(판정 C-H3 문면의
# 두 예 '다만, 3. 2. 전에'·'매년 3월 2일'은 표지라 계속 걸린다).
_해말붙음_RX = re.compile(r"(?<![\d매])(?<!매\s)(?:연도|년도|해|년)\s?(?:도|의|에는|에|부터는|부터)?\s*$")
_되풀이앞_RX = re.compile(r"다만|매\s?년|매\s?해|해마다|시행일|같은\s?날|당일")
_되풀이뒤_RX = re.compile(r"\.?\s?[)）]?\s?(?:전에|전까지|이전|전\s)")
_연도날짜_RX = (_풀날짜_RX, _두자리연도_RX)


def _월일언급갈래(원문):
    """자료의 연도 없는 월·일 언급 → (상대 연도 말이 붙은 {(월, 일)}, 확실한 되풀이 표지가 붙은 {(월, 일)})."""
    t = str(원문 or "").translate(_날짜글꼴)
    for rx in _연도날짜_RX:                               # 연도 적힌 날짜 속 'M. D.'는 언급이 아니다
        t = rx.sub(lambda m: " " * len(m.group(0)), t)
    상대, 되풀이 = set(), set()
    for rx in _월일꼴들:
        for m in rx.finditer(t):
            md = (int(m.group(1)), int(m.group(2)))
            앞 = re.split(r"(?<!\d)(?<!\d\s)\.|[。!?\n]", t[max(0, m.start() - _상대창):m.start()])[-1]
            if _상대연도말_RX.search(앞) or _해말붙음_RX.search(앞):
                상대.add(md)
            elif _되풀이앞_RX.search(앞) or _되풀이뒤_RX.match(t, m.end()):
                되풀이.add(md)
    return 상대, 되풀이


def _면제날(자료, 원문):
    """지어냄으로 걸지 않을 자료 날짜 — ({(월, 일)}, {일}).
    · 자료가 연도 없이 적은 월·일(4차 ①) — 다만 자료가 같은 월·일을 **연도와 함께도** 적었고 그 언급에 확실한 되풀이
      표지('다만, 3. 2. 전에'·'매년 3월 2일'·'시행일(3월 2일)')가 붙었으면 그 연도로 읽고 면제하지 않는다(판정 C-H3). 상대
      연도 말이 붙은 언급('내년·이듬 해·차기 연도 3월 2일')이 하나라도 있으면 면제한다 — 그래서 R01 꼴(옛 제정일
      '2014. 3. 2.' + '내년 3월 2일')은 여전히 어떤 연도도 걸지 않는다. 표지 없는 맨 되풀이도 면제(위 머리말, fixup).
    · 상대 달 중 기준이 오늘인 날(판정 D ②) — 그 일에는 어떤 연·월을 붙여도."""
    연도없는, 일만 = _자료연도없는(자료)
    연도적힌 = {(x[1], x[2]) for x in 자료 if x[0] and x[1] and x[2]}
    상대, 되풀이 = _월일언급갈래(원문)
    _셈, 날 = _상대달(원문)
    return {md for md in 연도없는 if md not in 연도적힌 or md in 상대 or md not in 되풀이}, 일만 | 날


def 자료날짜들(원문):
    """자료 쪽 날짜 전부 — 날짜들(원문, 점월일=True)에 상대 달 셈(판정 D ①)을 더한 것."""
    셈, _날 = _상대달(원문)
    return 날짜들(원문, 점월일=True) | 셈


def 부칙지어낸날짜(글, 원문) -> list:
    """부칙 글의 구체 날짜 가운데 자료 어디에도 없는 것 → [(날짜, 까닭)] (지어냄 후보, 판정 ②).
    초안 쪽은 날짜로 **확정한** 꼴만 본다(4차 ② — 날짜들(글): 두 자리 맨 번호열·연도 없는 'M. D.'는 걸지 않는다). 자료
    쪽은 모호한 꼴까지 넓게 읽는다(날짜들(원문, 점월일=True)). 완전한 연월일은 자료에 같은 연월일이 없으면 후보다 — 자료에
    연·월만 있는데 일까지 정했어도 후보. 다만 자료의 그 월·일에 연도가 적혀 있지 않으면('내년 3월 2일'·'같은 해 7. 1.'·맨
    '4. 1.'·'3/2') 초안이 어떤 연도를 붙였든 후보가 아니다(4차 ① — 연도를 추론하지 않는다, 확인 물음만). 월·일만
    ('○○○○년 1월 1일')은 자료에 같은 월·일이 없을 때만. 연·월만('2027년 4월부터')은 구체 날짜가 아니라 보지 않는다. 날짜가
    자료에 딴 대상(상위 규정 시행일 등)으로 나와도 여기서는 걸지 않는다(물음이 그 구절을 보여 준다)."""
    자료 = 자료날짜들(원문)
    연도없는월일, 일만 = _면제날(자료, 원문)
    나온 = []
    for d in sorted(날짜들(글), key=lambda x: tuple(-1 if v is None else v for v in x)):
        if d[2] is None or d[1] is None:
            continue
        if (d[1], d[2]) in 연도없는월일 or d[2] in 일만:
            continue       # 자료가 연도 없이 적은 날짜 — 어떤 연도를 붙였든 지어냄으로 걸지 않는다(4차 ①)
        if d[0] is None:
            if not any(x[1] == d[1] and x[2] == d[2] for x in 자료):
                나온.append((d, f"자료에 없는 날짜({d[1]}월 {d[2]}일)를 정했습니다"))
            continue
        if d in 자료:
            continue
        if (d[0], d[1], None) in 자료:
            까닭 = f"자료의 날짜는 '{d[0]}년 {d[1]}월'인데 부칙은 일자('{d[2]}일')까지 정했습니다"
        else:
            까닭 = f"자료에 없는 날짜({d[0]}년 {d[1]}월 {d[2]}일)를 정했습니다"
        나온.append((d, 까닭))
    return 나온


def 자료날짜가림(글, 원문):
    """글 속 날짜 가운데 자료에 (표기를 정규화해) 있는 것을 같은 길이 공백으로 가린다 — 지어냈나.재기(숫자 대조)가 표기
    차이로 맞는 날짜의 숫자를 헛거는 것을 막는다(3차: 자료 '27.3.2.'는 숫자 '27.3.2' 한 토막이라 초안 '2027년 3월 2일'의
    2027·3·2 가 모두 '자료에 없는 숫자'로 걸렸다). 자료가 연도 없이 적은 월·일('내년 3월 2일')은 초안이 붙인 연도째 가린다
    (4차 ① — 부칙지어낸날짜와 같은 규칙). 자료에 없는 날짜는 그대로 둔다(숫자 대조가 계속 본다).
    reg12('26-09-30) — 면제·상대 달 셈은 부칙지어낸날짜와 같은 _면제날·자료날짜들을 쓴다(C-H3·D). 상대 연도의 연·월/연도만
    요약('내년 3월부터' → 초안 '2027년 3월부터', '내년부터' → '2027년부터')도 연도째 가린다(C-M2 — 판정 ①의 연·월판)."""
    t = str(글 or "").translate(_날짜글꼴)
    자료 = 자료날짜들(원문)
    연도없는월일, 일만 = _면제날(자료, 원문)
    자료연월 = {(x[0], x[1]) for x in 자료 if x[0]}
    상대월, 상대연도만 = _상대연도월들(원문)

    def _있나(y, m, d):
        if (y, m, d) in 자료 or (m, d) in 연도없는월일 or d in 일만:
            return True
        return y is None and any(x[1] == m and x[2] == d for x in 자료)

    def _가려(꼴):
        def f(mo):
            a, b, c = (int(x) for x in mo.groups())
            y = 2000 + a if 꼴 == "두" else a
            return " " * len(mo.group(0)) if 1 <= b <= 12 and 1 <= c <= 31 and _있나(y, b, c) else mo.group(0)
        return f
    t = _풀날짜_RX.sub(_가려("풀"), t)
    t = _두자리연도_RX.sub(_가려("두"), t)
    t = _연월_RX.sub(lambda mo: " " * len(mo.group(0)) if ((int(mo.group(1)), int(mo.group(2))) in 자료연월
                                                          or int(mo.group(2)) in 상대월)
                    else mo.group(0), t)
    t = _월일_RX.sub(lambda mo: " " * len(mo.group(0)) if _있나(None, int(mo.group(1)), int(mo.group(2)))
                    else mo.group(0), t)
    if 상대연도만:
        t = _연도만_RX.sub(lambda mo: " " * len(mo.group(0)), t)
    return t


# 연도만 요약 — 시행 때를 말하는 자리('2027년부터'·'2027년 중'·'2027년 1학기'·'2027년 ○월')만. 달 앞('2027년 4월')은 뺀다.
# '까지'·'말'은 뺀다 — 목표·기한('2030년까지 달성')은 시행 때 요약이 아니라 재기가 계속 본다.
_연도만_RX = re.compile(r"(?<!\d)(?:19|20)\d{2}\s*(?:학)?년(?:도)?(?=\s?(?:부터|중(?![가-힣])|초(?![가-힣])|에\s?(?:시행|적용)"
                    r"|상반기|하반기|\d\s?학기|○))")


_모호두자리_RX = re.compile(r"(?<![\d.A-Za-z’'‘`])\d{2}\s*\.\s*\d{1,2}\s*\.\s*\d{1,2}(?:\s*\.)?(?!\d)")


def 모호날짜가림(글):
    """초안 글의 두 자리 맨 번호열('11.2.3.'·'표 12.5.3.'·'27. 3. 2.' — 따옴표·'년' 없는 것)을 같은 길이 공백으로 가린다 —
    날짜로 확정 못 하는 꼴이라 초안 쪽 달 대조(지어냈나 월표현)에 넣지 않는다(4차 ②)."""
    return _모호두자리_RX.sub(lambda m: " " * len(m.group(0)), str(글 or ""))

# 제명 끝의 제정·개정 꼬리 — '제정(안)'·'개정(안)'·' 제정안'·'(제정안)'·'(안)'(reg12 '26-09-30 판정 B-H5 · C-H4: 제명이
# '○○공사 출장 여비 규칙(제정안)'이면 「○○공사 출장 여비 규칙」과 끝이 어긋나 이 규정의 시행 구절이 물음에서 빠졌다).
# reg12 fixup(verify.md M1) — 괄호 꼴을 넓힌다: '[제정안]'·'〈제정안〉'·'(초안)'·'제정안(초안)'·' 제정'·' (제정)'·'…지침안'.
# 이 꼬리는 물음 구절 고르기(이 규정 이름 견주기)에만 쓰인다 — 표시를 만들지 않는다.
_이름꼬리_RX = re.compile(r"(?:\s?[\[(（〈<【]\s*(?:(?:전부|일부)\s?)?(?:제정|개정)?\s?(?:안|초안)\s*[\])）〉>】]"
                     r"|\s?[(（]\s*(?:(?:전부|일부)\s?)?(?:제정|개정)\s*[)）]"
                     r"|\s?(?:(?:전부|일부)\s?)?(?:제정|개정)\s?(?:\(\s*안\s*\)|안)?)\s*$")
_이름끝안_RX = re.compile(r"(규정|지침|내규|세칙|기준|요령|예규|훈령|규칙|규약|강령|준칙|정관|요강|수칙|방침|매뉴얼)안$")


def _이름꼬리뗌(글):
    글 = str(글 or "").strip()
    for _ in range(3):                                 # '제정안(초안)'처럼 꼬리가 둘 붙은 꼴
        새 = _이름꼬리_RX.sub("", 글).strip()
        if 새 == 글:
            break
        글 = 새
    return _이름끝안_RX.sub(r"\1", 글).strip()


def _이름같나(인용, 제목):
    """「…」 안 이름이 이 문서 제목인가 — 띄어쓰기를 지우고 같거나, 한쪽이 다른 쪽 끝을 이루면(기관명 앞머리 차이).
    양쪽 끝의 제정·개정 꼬리('제정(안)'·' 제정안'·'(제정안)'·'(안)')는 떼고 견준다(reg12 B-H5)."""
    a = re.sub(r"\s", "", _이름꼬리뗌(인용))
    b = re.sub(r"[\s「」『』]", "", _이름꼬리뗌(re.sub(r"[「」『』]", "", 제목 or "")))
    return len(a) >= 4 and len(b) >= 4 and (a == b or a.endswith(b) or b.endswith(a))


# 기관 이름 앞머리 — 제명 첫 낱말이 기관 이름 꼴이면('○○공사'·'○○진흥원') 뗀 이름도 이 규정 이름으로 본다(reg12 C-H4:
# '직무 교육 운영 지침의 시행일은 …'이 제명 '○○공사 직무 교육 운영 지침'과 같은 규정인 것을 못 봤다).
_기관앞머리_RX = re.compile(r"^(?:[가-힣○]*○[가-힣○]*|[가-힣]+(?:공사|공단|진흥원|연구원|재단|센터|협회|은행|위원회|청|처|원))\s+")
_종전말_RX = re.compile(r"(?:종전|현행|기존|옛|구|상위)\s?$")


def _맨이름든(s, 제목):
    """문장이 「」 없이 이 규정 이름을 그대로 쓰는가(띄어쓰기 무시, 기관 앞머리 뗀 이름 포함, 6자 이상). 이름 앞에
    '종전·현행·기존·상위'가 붙으면 딴 규정이다."""
    if not 제목:
        return False
    본 = _이름꼬리뗌(re.sub(r"[「」『』]", "", 제목))
    이름들 = {re.sub(r"\s", "", 본), re.sub(r"\s", "", _기관앞머리_RX.sub("", 본))}
    # 앞 낱말을 뗀 부분 이름('○○공사 사내 도서실 운영 지침' → '도서실 운영 지침' — verify.md M1). 두 낱말 이상·6자 이상만.
    낱 = _기관앞머리_RX.sub("", 본).split()
    이름들 |= {"".join(낱[k:]) for k in range(1, len(낱) - 1)}
    for 이름 in 이름들:
        if len(이름) < 6:
            continue
        # 띄어쓰기를 무시하고 찾는다 — 글자 사이에 빈칸 0~1개
        rx = r"\s?".join(map(re.escape, 이름))
        for m in re.finditer(rx, s):
            if not _종전말_RX.search(s[max(0, m.start() - 4):m.start()]):
                return True
    return False


# reg12 fixup(verify.md M1) — '동·당 규정은'(공공 문서에 흔한 가리킴)과 목적어 '이 규정을 … 시행한다'를 더한다. '새·이번·해당'과
# 맨 '지침은'(문장 첫머리)은 제목의 종류말(끝 낱말)과 같을 때만 본다(아래 _자기) — 딴 '새 기준은 …'을 이 규정으로 올리지 않게.
_이규정명시_RX = re.compile(r"(?<![가-힣])(?:이|본|동|당)\s?" + _이규정말 + r"(?:은|는|의|을|를)(?![가-힣])")
_시행일머리_RX = re.compile(r"^\s*(?:시행|적용)\s?(?:개시\s?)?(?:일자?|날짜|시기|시점|개시일|예정일)\s?(?:은|는|[:：])")
_날짜머리시행_RX = re.compile(r"^\s*[’'‘]?\d[\d\s.년월일’'‘]*(?:부터|에)\s?(?:시행|적용)")


def 시행구절(원문, 폭=120, 수=3, 제목=None):
    """확인 물음에 붙일 자료 구절 — 넓게 뽑는다(틀려도 초안은 안 바뀐다). 앞 순서가 먼저, 세 문장까지:
    시행일 이름('시행일·시행 시기·적용 개시일…')·'부칙'·'이 ○○은 … 시행'이 든 문장(바로 뒤에 날짜 든 줄이 이어지면
    — '시행 일정은 다음과 같이 정한다.' 뒤의 '1단계: 2027. 1. 1.' — 그 줄들도 함께) → '시행'·'적용'에 날짜가 함께 든
    문장 → '시행' → '적용' → '효력·발효·발령·공포·도입·개시'. '시행'에는 시작 표현('운영을 시작'·'실시'·'한시로 운영')도 든다.
    딴 대상·지난 일의 문장('…교육은 … 시행했다'·'상위 규정은 … 시행 중'·「딴 규정」)은 이 규정의 시행 구절 뒤로 미룬다 —
    한도가 남으면 그대로 싣는다(3차 M2). 「…」로 든 이름이 이 문서 제목(제목)이면 딴 대상이 아니라 이 규정이다 — 첫 층에
    올린다(4차 ③: 「○○공사 사내 어린이집 운영 규정」은 … 시행한다'가 딴 대상으로 밀려 앞의 세 문장에 한도를 뺏겼다).
    위 층에 하나도 없으면 날짜와 '부터·까지'가 함께 든 문장('매뉴얼은 2027. 3. 2.부터 운영한다·사용한다')을 싣는다(4차 ③).
    없으면 None."""
    마디 = _글마디(원문)

    def _자기(s):
        # 이 규정 구절 — 「」·『』 이름이 제목과 같은 문장(4차 ③), '이 규정은·본 지침의'처럼 이 규정을 밝힌 문장, 제목을
        # 그대로(「」 없이) 쓴 문장(reg12 C-H4 — 전에는 '입주 신청 기준은 … 적용한다' 셋이 앞에 있으면 이런 문장이 세 문장
        # 한도에서 밀렸다). 모두 시행·적용 말이나 시행일 이름이 함께 있어야 한다.
        if re.search(_시행말 + "|" + _시행곁말_RX.pattern + "|" + _시행일이름, s) is None:
            return False
        if _이규정명시_RX.search(s) or _시행일머리_RX.search(s) or _날짜머리시행_RX.search(s):
            return True
        if 종류말 and (re.search(r"(?<![가-힣])(?:새|이번|해당)\s?" + 종류말 + r"(?:은|는|의|을|를)(?![가-힣])", s)
                    or re.match(r"\s*" + 종류말 + r"(?:은|는)\s", s)):
            return True
        return bool(제목) and (any(_이름같나(m.group(1), 제목) for m in re.finditer(r"[「『]([^」』\n]*)[」』]", s))
                             or _맨이름든(s, 제목))

    # 제목의 종류말 — 꼬리를 뗀 제명의 끝 낱말이 규정 종류말이면('…운영 지침' → '지침')
    _끝 = re.search(r"(" + _이규정말 + r")$", re.sub(r"[「」『』\s]", "", _이름꼬리뗌(제목 or "")))
    종류말 = re.escape(_끝.group(1)) if _끝 and _끝.group(1) not in ("개정안", "제정안") else ""

    첫층 = []
    for i, s in enumerate(마디):
        # '시행: 결재한 날부터 시행'처럼 쌍점 머리 '시행:'도 이 규정의 시행 구절이다(reg13 J7 — 없으면 첫 층이 비어 아래 층의
        # 경과조치 줄이 따라 붙었다). '적용:'은 적용 범위 머리일 때가 많아 넣지 않는다.
        if re.search(_시행일이름 + r"|부칙", s) or _이규정시행_RX.search(s) or _자기(s) or re.match(r"\s*시행\s?[:：]", s):
            첫층.append(s)
            j = i + 1
            while j < len(마디) and 날짜들(마디[j], 점월일=True) and not re.search(_시행말, 마디[j]):
                첫층.append(마디[j])
                j += 1
    층 = ([s for s in 첫층 if _자기(s)],          # 「이 규정 이름」 문장이 맨 먼저(4차 ③ — '급식 기준은 …'도 첫 층이다)
         첫층,
         [s for s in 마디 if re.search(_시행말, s) and 날짜들(s, 점월일=True)],
         # 날짜 없는 맨 '실시'('교육은 매 분기 실시')는 시행 구절이 아니다 — 날짜가 붙거나(위 층) 이 규정이 주어일 때만
         [s for s in 마디 if re.search(r"시행|" + _시작말.replace("실시|", "", 1), s)],
         [s for s in 마디 if "적용" in s],
         [s for s in 마디 if _시행곁말_RX.search(s)])

    def _미룸(s):
        return (bool(_지난시행_RX.search(s) or _딴대상_RX.search(s)) and not _이규정시행_RX.search(s)
                and not _자기(s))

    # reg13('26-09-30 bench15 J7) — 이 규정의 시행 구절(첫 층, 미루지 않은 문장)이 잡히면 그 구절만 싣는다. 전에는 세 문장
    # 한도가 남으면 아래 층('적용'·'시행'이 든 문장)이 채워 적용 범위('적용 대상: …')·경과조치('시행 전 …')가 물음에 붙었다
    # (bench15 A·M 사례 중 사례). 시행·적용 말에 날짜가 함께 든 문장(셋째 층)은 시행일 구절일 수 있어 남긴다.
    # reg13 fixup(review_checks H3) — 자르기는 첫 층에 **시행 말이 든** 미루지 않은 문장이 있을 때만 한다. '부칙' 낱말만 든 경과
    # 문장('부칙에는 경과조치를 둔다')으로 자르면, 넷째 층의 진짜 시행 구절('운영은 내년 상반기 중 시작한다')이 물음에서 빠졌다.
    if any(not _미룸(s) and (re.search(_시행말 + "|" + _시행일이름, s) or re.match(r"\s*시행\s?[:：]", s)) for s in 첫층):
        층 = 층[:3]
    고른 = []
    for 미룬것 in ((False,) if len(층) == 3 else (False, True)):
        for 무리 in 층:
            for s in 무리:
                if _미룸(s) == 미룬것 and s not in 고른 and len(고른) < 수:
                    고른.append(s)
    if not 고른:
        고른 = [s for s in 마디 if 날짜들(s, 점월일=True) and re.search(r"부터|까지", s)][:수]
    if not 고른:
        return None
    # 자르기는 날짜를 끊지 않는다(reg12 C-H4 — 137자 한 문장이 앞머리만 실리고 날짜가 잘렸다). 첫 문장이 폭을 넘으면
    # 앞머리와 날짜 자리를 '…'로 잇는다. 뒤 문장은 자리가 남을 때만, 날짜 도중에서 끊지 않는다.
    첫 = 고른[0]
    if len(첫) > 폭:
        자리 = _날짜자리들(첫)
        if 자리:
            시 = re.search(_시행말, 첫)
            앞날 = [x for x in 자리 if 시 and x[0] < 시.start()]
            a, b = 앞날[-1] if 앞날 else 자리[0]          # 시행 말 바로 앞의 날짜(없으면 첫 날짜)
            시작 = max(0, a - 12)
            끝 = min(len(첫), max(b, 시.end() if 시 and 시.start() >= b else b) + 12)
            # reg12 fixup(verify.md H4) — 날짜 구절 끝이 폭 안이면 그냥 앞에서 자른다(날짜는 끊지 않는다). 전에는 앞머리
            # `첫[:남]`과 가운데(날짜 앞 12자부터)가 겹쳐 같은 구절이 두 번 실렸다. 앞머리는 가운데 시작 앞까지만 싣는다.
            if 끝 <= 폭 - 1:
                끊음 = 폭 - 1
                for a2, b2 in 자리:
                    if a2 < 끊음 < b2:
                        끊음 = a2
                return 첫[:끊음].rstrip() + "…"
            가운데 = 첫[시작:끝].strip() + ("…" if 끝 < len(첫) else "")
            남 = min(폭 - len(가운데) - 3, 시작)
            if 시작 == 0:
                return 가운데
            return (첫[:남].rstrip() + " … " + 가운데) if 남 > 8 else "…" + 가운데
        return 첫[:폭 - 1] + "…"
    글 = " / ".join(고른)
    if len(글) <= 폭:
        return 글
    끊음 = 폭 - 1
    for a, b in _날짜자리들(글):
        if a < 끊음 < b:
            끊음 = a
    return 글[:끊음].rstrip() + "…"


def _날짜자리들(글):
    """글 속 날짜 표기 자리 [(시작, 끝)] — 자르기가 날짜를 끊지 않게(자료 쪽 꼴)."""
    t = str(글 or "").translate(_날짜글꼴)
    자리 = []
    for rx in (_풀날짜_RX, _두자리연도_RX, _월일_RX, _점월일_RX, _꼬리점월일_RX, _여덟자리_RX):
        for m in rx.finditer(t):
            s, e = m.start(), m.end()
            if t[s:s + 1] in "’'‘`" or (s > 0 and t[s - 1] in "’'‘`"):
                s = max(0, s - 1)
            if e < len(t) and t[e] == ".":
                e += 1
            자리.append((s, e))
    return sorted(자리)


def 시행확인물음(원문, 제목=None):
    """원문이 온 새 규정마다 남기는 확인 물음 한 줄(사장님 판정 '26-09-29). 제목 = 문서 제명(「」 이름 견주기, 4차 ③)."""
    구절 = 시행구절(원문, 제목=제목)
    return ("부칙의 시행일을 확인해 주세요 — " + (f'자료: "{구절}"' if 구절 else "자료에는 시행일 언급이 없습니다"))


