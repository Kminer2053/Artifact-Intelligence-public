# 숫자 읽기의 받침 — 끝자리 0(십·백)·3(삼)·6(육)은 받침(ㄹ 아님), 1·7·8(일·칠·팔)은 ㄹ,
# 2·4·5·9(이·사·오·구)는 받침 없음.
def _받침(수글):
    끝 = 수글[-1]
    if 끝 in "036":
        return "받침"
    if 끝 in "178":
        return "ㄹ"
    return "없음"


# 받침에 따라 갈리는 조사 짝 — (받침 있음, ㄹ 받침, 받침 없음)
_조사짝 = {
    "을": ("을", "을", "를"), "를": ("을", "을", "를"),
    "이": ("이", "이", "가"), "가": ("이", "이", "가"),
    "은": ("은", "은", "는"), "는": ("은", "은", "는"),
    "과": ("과", "과", "와"), "와": ("과", "과", "와"),
    "으로": ("으로", "로", "로"), "로": ("으로", "로", "로"),
    "으로서": ("으로서", "로서", "로서"), "로서": ("으로서", "로서", "로서"),
    "으로써": ("으로써", "로써", "로써"), "로써": ("으로써", "로써", "로써"),
    # 계사 과거 '였/이었' — '30%였던'(퍼센트였던)을 '100분의 30이었던'으로(적대검토 L2)
    "였": ("이었", "이었", "였"), "이었": ("이었", "이었", "였"),
}
_가변조사_RX = re.compile(r"^(?:(으로서|으로써|로서|로써|으로|로|을|를|이|가|은|는|과|와)(?![가-힣])|(이었|였))")
# 받침과 무관하게 그대로 붙어도 되는 말(조사·의존명사·계사) — 이것으로 시작하면 그대로 둔다.
# '인'·'임'(계사 활용 — '100분의 30인'·'100분의 2인')도 받침과 무관하다(적대검토 L2·M5(c)).
_불변말_RX = re.compile(r"^(?:의|에서|에게|에|까지|부터|만|도|보다|씩|마다|이내|이상|이하|미만|초과|"
                    r"범위|수준|가량|정도|내외|이다|이며|이고|이면|이어야|인(?![가-힣])|임(?![가-힣]))")


def _조사다시(수글, 뒤):
    """'100분의 N' 뒤에 올 글의 첫머리를 N 받침에 맞춘다. (바뀐 첫머리, 나머지) 또는
    못 가리면 None."""
    if not 뒤 or not re.match(r"[가-힣]", 뒤[0]):
        return "", 뒤
    m = _가변조사_RX.match(뒤)
    if m:
        짝 = _조사짝[m.group(1) or m.group(2)]
        k = {"받침": 0, "ㄹ": 1, "없음": 2}[_받침(수글)]
        return 짝[k], 뒤[m.end():]
    if _불변말_RX.match(뒤):
        return "", 뒤
    return None


def _비율교정(s, 기록, 경로):
    if not any(c in s for c in _퍼센트기호):
        return s
    법령문 = bool(_법령인용_RX.search(s))

    def _조각(t):
        if not any(c in t for c in _퍼센트기호):
            return t

        # ⓪ 반쯤 옮긴 분수 — 분모 100이면 '%'만 뗀다. 다른 분모는 그대로 둔다(soft W-조문퍼센트).
        def _분수(m):
            분모 = re.sub(r"[\s,]", "", m.group(1).split("분의")[0])
            if 분모 != "100":
                return m.group(0)
            기록.append(f"{경로}: '{m.group(0)}'에서 겹친 '%'를 뗐습니다('100분의 {m.group(2)}'가 이미 비율)")
            return m.group(1)
        t = _분수퍼센트_RX.sub(_분수, t)
        # ① 기준량 비율 — 앞에서부터 하나씩(뒤 글을 보고 조사를 다시 붙여야 해서 sub 콜백 대신
        # 직접 이어 간다).
        if not 법령문:
            나온다, i = [], 0
            while True:
                m = _기준량_RX.search(t, i)
                if not m:
                    break
                수 = m.group(2)
                앞말 = re.search(r"([가-힣]+)$", t[:m.start() + 1])
                if not (1 <= int(수) <= 100) or (앞말 and 앞말.group(1) in _의낱말_아님):
                    나온다.append(t[i:m.end()])
                    i = m.end()
                    continue
                결과 = _조사다시(수, t[m.end():])
                if 결과 is None:
                    나온다.append(t[i:m.end()])
                    i = m.end()
                    continue
                조사, _ = 결과
                나온다.append(t[i:m.start()] + f"의 100분의 {수}{조사}")
                # 조사를 갈아 끼웠으면 원래 조사 길이만큼 건너뛴다
                원조사 = _가변조사_RX.match(t[m.end():])
                i = m.end() + (len(원조사.group(0)) if (조사 and 원조사) else 0)
                기록.append(f"{경로}: 조문의 '{수}%'를 '100분의 {수}'"
                          f"{'로' if _받침(수) != '받침' else '으로'} 고쳤습니다(기준량 비율)")
            나온다.append(t[i:])
            t = "".join(나온다)
        # ② 나머지 %

        def _퍼센트(m):
            기록.append(f"{경로}: 조문의 '{m.group(1)}%'를 '{m.group(1)}퍼센트'로 고쳤습니다"
                      "(조문에는 % 기호를 쓰지 않습니다)")
            return f"{m.group(1)}퍼센트"
        return _그밖_RX.sub(_퍼센트, t)

    return _밖에서(s, _조각)


