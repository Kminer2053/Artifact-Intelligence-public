# ① 금액 단위 띄어쓰기 — 숫자 바로 뒤(또는 표 캡션의 "단위:" 뒤) '만원·억원·천원·조원'
#    (겹친 '천만원'·'백만원' 포함) → 사이에 공백
# ══════════════════════════════════════════════════════════════════════════
# 크기 자리 — build/수치꼴.py 의 _크기 와 같은 알파벳(긴 것부터: '천만'·'백만'을 먼저
# 시도해야 '천'+'만'으로 먼저 끊겨 뒷글자가 안 붙는 일이 없다).
_스케일 = r"(?:천만|백만|조|억|만|천)"
_금액단위_RX = re.compile(rf"({_스케일})원")


def _금액단위_교정(경로, s, 기록):
    if "원" not in s:
        return s
    if _URL파일코드꼴인가(s):
        return s
    바뀜 = []

    def _바꿔(m):
        앞 = s[:m.start()]
        # 숫자 바로 뒤(예: '20만원')이거나, 표 캡션처럼 '단위' 표시 뒤(예: '(단위: 만원)',
        # 숫자 없이 단위어만 나열)에 붙어 있으면 고친다 — 그 밖(예: '공연장은 만원이었다'
        # 처럼 '가득 참'의 뜻인 동음이의 낱말)은 숫자도 '단위'도 없어 건드리지 않는다.
        if (앞 and 앞[-1].isdigit()) or "단위" in 앞:
            바뀜.append(m.group(0))
            return f"{m.group(1)} 원"
        return m.group(0)

    새 = _금액단위_RX.sub(_바꿔, s)
    if not 바뀜:
        return s
    for 이전 in 바뀜:
        기록.append(f"{경로}: 금액 단위 띄어쓰기 \"{이전}\" → \"{이전[:-1]} 원\"")
    return 새


# ══════════════════════════════════════════════════════════════════════════
# ④ 큰따옴표 — 곧은 따옴표 짝("…")을 둥근 따옴표(“…”)로('26-09-28). 한글 맞춤법 문장 부호
#    규정의 큰따옴표는 “ ”이고, 5·6차 심사(front5/6-s5)가 곧은 따옴표를 거듭 짚었다. 한 칸
#    안에서 짝이 맞을 때만(개수가 짝수) 바꾸고, 코드·파일명·URL 꼴 칸은 건드리지 않는다.
# ══════════════════════════════════════════════════════════════════════════
_곧은따옴표_짝_RX = re.compile(r'"([^"\n]*)"')
# 태그 안(속성 따옴표)은 글이 아니다 — 1p items[].html·summary 는 강조 span
# (`<span class="num">`)을 싣는 칸이라, 속성 따옴표까지 둥글게 바꾸면 편집기
# 허용마크업()·조립기 _허용마크업() 이 태그로 못 알아보고 `&lt;` 로 잠근다(2단계 UI
# 검토 F1, '26-09-28 재현: 편집 0회로 두 번 열자 강조가 태그 글자로 드러났다).
# 태그는 잠시 빼 두고 글 조각에서만 짝을 센다.
_태그_RX = re.compile(r"</?[A-Za-z][^<>]*>")
_태그자리 = ""


def _태그따옴표_복원(경로, s, 기록):
    """앞선 판(태그 안까지 바꾸던 교정)이 이미 둥글게 만든 속성 따옴표(`class=“num”`)를
    곧은 따옴표로 되돌린다 — 저장 한 번에 되살아나게(태그로 살아 있을 때만 고칠 수 있다)."""
    if "<" not in s or ("“" not in s and "”" not in s):
        return s
    새 = _태그_RX.sub(lambda m: m.group(0).replace("“", '"').replace("”", '"'), s)
    if 새 != s:
        기록.append(f"{경로}: 태그 속성 따옴표 “…” → \"…\" 되돌림")
    return 새


def _따옴표_교정(경로, s, 기록):
    s = _태그따옴표_복원(경로, s, 기록)
    if '"' not in s or _태그자리 in s or _URL파일코드꼴인가(s):
        return s
    태그들 = _태그_RX.findall(s) if "<" in s else []
    글 = _태그_RX.sub(_태그자리, s) if 태그들 else s
    if '"' not in 글 or 글.count('"') % 2:
        return s
    새글 = _곧은따옴표_짝_RX.sub(lambda m: f"“{m.group(1)}”", 글)
    if 새글 == 글:
        return s
    if 태그들:
        조각 = 새글.split(_태그자리)
        새 = 조각[0] + "".join(t + c for t, c in zip(태그들, 조각[1:]))
    else:
        새 = 새글
    기록.append(f"{경로}: 큰따옴표 \"…\" → “…” {글.count(chr(34)) // 2}쌍")
    return 새


# ══════════════════════════════════════════════════════════════════════════
# ② 자기 호칭 통일(규정·시행문·보도자료만) — 문서가 스스로 정한 약칭과 다른 '회사'·
#    '당사'를 그 약칭으로
# ══════════════════════════════════════════════════════════════════════════
# 새문서(등록부 이름)·저장(doc.genre 값) 두 어휘를 다 담는다(모듈 머리말 "호출 규약").
_회사호칭_적용장르 = frozenset({"regulation", "gongmun", "press", "press-release"})

# 명시적 약칭 정의 — '(이하 "공사"라 한다)'·'(이하 공사라고 한다)' 류(따옴표 종류·
# '라'/'라고' 둘 다 받는다, bench4 심사 실측 문구 그대로). 약칭이 받침(자음)으로 끝나면
# '본원이라 한다'처럼 계사 '이'가 끼어든다 — '이'를 선택으로 받는다.
_약칭정의_RX = re.compile(r'이하\s*["“\']?\s*([가-힣A-Za-z0-9]{1,10})\s*["”\']?\s*이?라고?\s*한다')

# '기관명' 필드의 마지막 기관 유형 접미 — 실물 정본(build/regulation-docs.json·
# build/gongmun-docs.json 의 커밋된 표본)은 명시적 '(이하 …)' 정의 없이 이 접미 하나로
# 스스로를 가리킨다(예: "기관명":"○○공사" 문서의 조문은 그냥 "공사의 …"). 긴 것부터 —
# "연구원"이 "원"보다 먼저 맞아야 한다.
# 한 글자 접미(청·원·처·부·국)는 뺐다(검토 발견①, '26-09-28 되짚음) — 그 한 글자는
# 그 자체로 너무 흔한 낱말이라("○○병원"의 "원"처럼) 약칭이라기엔 막연하고, 여러 글자
# 접미(공사·공단·연구원 등)만으로도 실물 표본은 다 걸린다(아래 회귀 확인).
_기관유형_접미 = ("진흥원", "연구원", "위원회", "협의회", "관리공단", "공사", "공단",
               "재단", "협회", "센터")

_자기지칭어 = ("회사", "당사")

# '회사'·'당사' 를 실제로 고칠지는 **허용목록**으로 좁힌다(검토 발견①, '26-09-28 되짚음
# — 4차 벤치마크 뒤 첫 판은 "고치지 않을 낱말"만 몇 개 덴이리스트로 막았는데, 실물
# 문장이 훨씬 다양해 다 새 나갔다: 재현된 오교정 — '계약 당사자'→'계약 공사자',
# '당사국'→'공사국', '회사법'→'공사법', '귀 회사의'→'귀 공사의', '민간 회사'→'민간
# 공사', '각 회사'→'각 공사', '수신 △△회사'→'△△공사', '○○회사와'→'○○공사와', 인용문
# '"회사가 앞장서겠다"'까지, doc._맥락(사용자 원자료)까지). 커밋된 실물 표본
# (build/gongmun-docs.json)이 실제로 쓰는 자기 지칭 자리는 "회사는/당사는"처럼 **문장
# 맨 앞**이거나 "우리 회사는"뿐이다(아래 회귀 확인) — 그 두 자리만 허용하고, 그 밖의
# 모든 앞말(귀·민간·타·각·○○·△△ 같은 한정어나 다른 기관 이름)은 앞에 무엇이 오든 그냥
# 막는다 — 잘못 짚느니 가만두는 이 모듈의 기존 원칙을 앞말에도 그대로 편 것뿐이다.
_자기지칭_허용_앞말 = ("", "우리")

# 번호·글머리 표지만 있는 앞 토큰도 문장 맨 앞과 같다('26-09-28 5차 벤치 실측 — 조문의
# '① 회사가 …'·'1. 회사가 …'·'가. 회사는 …'이 표지 하나 때문에 막혀 한 문서 안에서
# '공사'와 '회사'가 섞였다). 표지 말고 다른 글자가 한 자라도 붙으면 여전히 막는다.
_번호표지_RX = re.compile(
    r"^(?:[①-⑳]|\d{1,2}[.)]|[가-하][.)]|\(\d{1,2}\)|\([가-하]\)|[-·•○◦□■※▶]|[(\[「『<])$")


def _앞말_허용인가(앞토큰):
    return 앞토큰 in _자기지칭_허용_앞말 or bool(_번호표지_RX.match(앞토큰))

# '회사'·'당사' 바로 뒤에 한글이 이어지면 다른 낱말이거나('당사자'의 '자'·'당사국'의
# '국'·'회사법'의 '법'·'회사원'의 '원'·'회사채'의 '채') 조사가 붙어 자기 지칭으로 쓰인
# 것이다('회사는'·'당사가'·'회사의' …) — 뒤가 아예 없거나(문장 끝) 한글이 아니면(공백·
# 문장부호) 조사 없이 자기 지칭으로 쓰인 것으로 보고, 한글이 이어지면 이 조사 허용목록
# 하나로 시작해 그 뒤가 다시 한글로 안 이어질 때만(조사 자체가 다른 낱말에 물리지 않을
# 때만) 자기 지칭으로 본다.
_뒤_조사_RX = re.compile(
    r"^(?:는|은|가|이|의|에서|에게|한테|으로|로|와|과|이랑|랑|부터|까지|조차|마저|밖에|뿐|도|만|를|을)"
    r"(?![가-힣])"
)

# 인용부호로 직접 옮긴 남의 말은 자기 호칭 통일 대상이 아니다 — 발언을 그대로 옮긴
# 것이지 문서 스스로의 서술이 아니다(검토 발견①, '"회사가 앞장서겠다"고 말했다' 재현).
_인용span_RX = re.compile(r'"[^"\n]*"|“[^”\n]*”|\'[^\'\n]*\'')

# '자회사'·'모회사'처럼 공백 없이 바로 붙는 복합어는 아래 정규식의 부정 전방탐색
# (?<![가-힣]) 하나로 걸러진다(앞 글자가 한글이면 애초에 안 문다).
_자기지칭_RX = re.compile(r"(?<![가-힣])(?:회사|당사)")


def _문서약칭(doc, 전체글):
    """이 문서가 스스로를 뭐라 부르는가 — 명시적 정의를 먼저 보고, 없으면 '기관명'
    필드의 기관 유형 접미로 물러난다. 둘 다 없으면 None(아무것도 안 바꾼다)."""
    for m in _약칭정의_RX.finditer(전체글):
        약칭 = (m.group(1) or "").strip()
        if 약칭 and 약칭 not in _자기지칭어:
            return 약칭
    기관명 = str((doc.get("기관명") if isinstance(doc, dict) else "") or "").strip()
    for 접미 in _기관유형_접미:
        if 기관명.endswith(접미):
            return 접미
    return None


def _자기지칭_뒤가_경계인가(뒤):
    """뒤(매치 다음 최대 4자)가 자기 지칭의 끝인가 — 문자열 끝이거나, 한글이 아니거나
    (공백·문장부호), 허용된 조사 하나로 시작해 그 조사 뒤가 다시 한글로 안 이어지면
    그렇다. 그 밖(다른 한글이 바로 이어짐)은 '당사자'·'회사법'처럼 다른 낱말이다."""
    if not 뒤:
        return True
    if not re.match(r"[가-힣]", 뒤[0]):
        return True
    return bool(_뒤_조사_RX.match(뒤))


def _인용문안인가(s, 위치):
    """s 안의 위치가 따옴표(직접 인용) 구간 안인가."""
    for m in _인용span_RX.finditer(s):
        if m.start() <= 위치 < m.end():
            return True
    return False


def _자기호칭_교정(경로, s, 약칭, 기록):
    if not any(w in s for w in _자기지칭어):
        return s
    바뀜 = []

    def _고쳐(m):
        if not _자기지칭_뒤가_경계인가(s[m.end():m.end() + 4]):
            return m.group(0)
        앞부분 = s[:m.start()].strip()
        앞토큰 = 앞부분.split()[-1] if 앞부분 else ""
        if not _앞말_허용인가(앞토큰):
            return m.group(0)
        if _인용문안인가(s, m.start()):
            return m.group(0)
        바뀜.append(m.group(0))
        return 약칭

    새 = _자기지칭_RX.sub(_고쳐, s)
    if not 바뀜:
        return s
    기록.append(f"{경로}: 자기 호칭 \"{바뀜[0]}\" → \"{약칭}\""
                + (f" 외 {len(바뀜) - 1}곳" if len(바뀜) > 1 else ""))
    return 새


def 교정(doc, 장르="") -> list:
    """doc 를 제자리에서 고치고, 사람이 읽을 변경 내역 목록을 돌려준다(바뀐 것 없으면
    빈 리스트). doc 가 dict 가 아니면 그대로 빈 리스트(호출부를 안 막는다).

    장르는 위 모듈 머리말 "호출 규약"의 두 어휘(등록부 이름 · doc.genre 값) 어느 쪽을
    줘도 된다 — ①(금액 단위)은 장르를 아예 안 본다."""
    if not isinstance(doc, dict):
        return []
    기록 = []
    약칭 = None
    if 장르 in _회사호칭_적용장르:
        나온다 = []
        _모든글(doc, 나온다)
        약칭 = _문서약칭(doc, "\n".join(나온다))

    def _고치기(경로, v):
        # 금액 단위 띄어쓰기(①)는 끈다('26-09-28 사장님 판정 — 재정경제부 실물은 '20만원'처럼
        # 붙여 쓴다(706회 대 5회), 맞춤법도 숫자와 어울린 단위 명사는 붙여 쓰기를 허용한다).
        # 함수(_금액단위_교정)는 남겨 둔다 — 기관 설정으로 띄어 쓰기를 고르게 할 때 쓴다.
        s = v
        if 약칭:
            s = _자기호칭_교정(경로, s, 약칭, 기록)
        return _따옴표_교정(경로, s, 기록)

    _문자열걷기(doc, _고치기)
    return 기록


# 문장 중간의 '회사'는 자기 호칭인지('직원은 회사가 지급한') 남인지('협력하는 회사가')
# 앞말만으로 못 가른다 — 고치지 않는다. 대신 이 문서가 이미 약칭으로 스스로를 부르는데
# (교정 뒤 기준) 그런 '회사'가 남아 있으면 한 문서 안에서 호칭이 섞인 것이라, 고칠
# 자리로 알리기만 한다('26-09-28 5차 벤치 M2 실측: 주요내용·제10조는 '공사', 제8조제1항은
# '회사가 지급한 노트북'). 모델 되먹임·편집기 표기 표지가 이 목록을 쓴다.
_남을가리키는_앞말 = frozenset({"민간", "다른", "해당", "모든", "여러", "협력", "관계", "동종", "경쟁",
                             "외부", "위탁", "용역", "계약", "참여", "입주", "상대", "거래", "각각"})
_약칭자기지칭_RX = lambda 약칭: re.compile(rf"(?<![가-힣]){re.escape(약칭)}(?:는|은|가|이|의|에서|에게|로|와|과|도|만|를|을)(?![가-힣])")


def 섞인호칭(doc, 장르="") -> list:
    """(경로, 곁글) 목록 — 교정() 을 부른 **뒤**에 부른다. 약칭을 못 정했거나, 문서가
    약칭을 자기 호칭으로 한 번도 안 쓰면(섞인 게 아니다) 빈 목록."""
    if not isinstance(doc, dict) or 장르 not in _회사호칭_적용장르:
        return []
    나온다 = []
    _모든글(doc, 나온다)
    전체 = "\n".join(나온다)
    약칭 = _문서약칭(doc, 전체)
    if not 약칭 or not _약칭자기지칭_RX(약칭).search(전체):
        return []
    남음 = []

    def _보기(경로, s):
        for m in _자기지칭_RX.finditer(s):
            if not _자기지칭_뒤가_경계인가(s[m.end():m.end() + 4]):
                continue
            if _인용문안인가(s, m.start()):
                continue
            앞부분 = s[:m.start()].strip()
            앞토큰 = 앞부분.split()[-1] if 앞부분 else ""
            # 쉼표·가운뎃점·쌍점으로 끝난 앞말('보고, 회사 지급 노트북')도 본다 — 자동 교정은
            # 안 한다('공공기관, 회사, 단체'처럼 남을 늘어놓는 나열일 수 있다), 알리기만 한다
            # ('26-09-28 7차 벤치 M2: 본문은 '공사'로 고쳐졌는데 주요내용의 이 자리는 알림도 없었다).
            앞토큰 = 앞토큰.rstrip(",·:;")
            # 한 글자 한정어(귀·타·각·그·이)·기호 이름(○○·△△) 뒤는 남이다 — 알리지도 않는다.
            if len(앞토큰) < 2 or not re.search(r"[가-힣]$", 앞토큰) or 앞토큰 in _남을가리키는_앞말:
                continue
            남음.append((경로, s[max(0, m.start() - 12):m.end() + 8]))
        return s

    _문자열걷기(doc, _보기)
    return 남음


