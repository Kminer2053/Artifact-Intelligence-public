# ③ 보도자료 초안 정리 — **새문서에서만** 부른다(저장은 사람이 고친 글이라 안 건드린다,
#    조번호꼴·붙임꼴과 같은 결). '26-09-28 5차 심사(front5-s5) 3인이 kordoc 과 견주어
#    짚은 것 가운데 기계가 확실히 고칠 수 있는 셋이다.
# ══════════════════════════════════════════════════════════════════════════
_보도장르 = frozenset({"press", "press-release"})
_빈자리표시_RX = re.compile(r"^[\s○.()·]*$")
_연월_RX = re.compile(r"(20\d{2})\s*\.\s*(\d{1,2})\s*\.")
_부제_여는표지 = ("-", "–", "—", "◇", "○", "□", "※", "·")
_직함 = ("사장", "부사장", "원장", "이사장", "청장", "장관", "차관", "본부장", "처장", "대표",
       "위원장", "회장", "단장", "센터장", "소장")


def _보도시점글(doc):
    v = doc.get("보도시점")
    if isinstance(v, dict):
        return " ".join(str(x) for x in v.values() if isinstance(x, str))
    return str(v or "")


def 보도초안정리(doc, 장르="") -> list:
    """① 배포가 비었거나 '○○'뿐이면 보도시점의 연·월로 날짜 꼴 자리표시를 둔다
    ('2026. 11. ○○.(○)' — 심사가 '날짜 형식 자리표시도 없음'을 짚었다, 날짜를 셈해
    넣지는 않는다). ② 부제가 붙임표 없이 시작하면 앞에 '- '를 붙인다(온톨로지
    press-release.구성.부제 — 부제가 붙임표로 연다). ③ 인용 머리의 '이름 기관
    직함' 어순을 관행('기관 이름 직함')으로 바꾼다 — 기관이 이 문서의 기관명과 같을
    때만. 바뀐 곳 설명 목록을 돌려준다."""
    if not isinstance(doc, dict) or 장르 not in _보도장르:
        return []
    기록 = []
    배포 = doc.get("배포")
    if isinstance(배포, str) or 배포 is None:
        if _빈자리표시_RX.match(str(배포 or "")):
            m = _연월_RX.search(_보도시점글(doc))
            if m:
                새 = f"{m.group(1)}. {int(m.group(2))}. ○○.(○)"
                doc["배포"] = 새
                기록.append(f"배포: 빈 칸 → 날짜 꼴 자리표시 \"{새}\"")
    부제 = doc.get("부제")
    if isinstance(부제, str) and 부제.strip() and not 부제.strip().startswith(_부제_여는표지):
        doc["부제"] = "- " + 부제.strip()
        기록.append("부제: 앞에 붙임표('- ')")
    기관 = str(doc.get("기관명") or "").strip()
    if 기관:
        rx = re.compile(rf"(○○○|[가-힣]{{2,4}})\s+{re.escape(기관)}\s+({'|'.join(_직함)})(?=[은는이가의])")

        def _어순(경로, s):
            새 = rx.sub(lambda m: f"{기관} {m.group(1)} {m.group(2)}", s)
            if 새 != s:
                기록.append(f"{경로}: 인용 머리 어순 '이름 기관 직함' → '기관 이름 직함'")
            return 새
        _문자열걷기(doc, _어순)
    return 기록
