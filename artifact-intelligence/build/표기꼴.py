#!/usr/bin/env python3
"""표기 교정층(구현자 B, '26-09-27 4차 벤치마크 후) — 조립 전 3층 JSON 문서를 훑어
표기 관행 두 가지를 **제자리에서** 고친다.

    def 교정(doc, 장르) -> list[str]      # 사람이 읽을 변경 내역(빈 리스트면 바꾼 것 없음)

왜 필요한가 — 4차 심사(내부 기록, front-s4·s5)가 kordoc 에게 지고 남긴 지적
가운데 둘은 **글의 뜻이 아니라 표기 규범**이었다: 금액 단위 '만원'을 붙여 쓰고(맞춤법은
'만 원'), 문서 스스로 정한 자기 호칭과 다른 낱말('회사')을 섞어 썼다. 지시문에 '띄어
써라·섞지 마라'를 아무리 적어도 작은 모델은 자주 놓친다(실측 — runs/M/s4 '통신비를
월 2만원 지원한다'·'회사가 지급한 노트북', runs/A/s1 '3,600만원'). 지시문(프롬프트)이
아니라 **규칙 코드**로 잡을 수 있는 표기는 규칙으로 잡는다 — 이미 커밋된 실물 표본에도
같은 흠이 있다(build/gongmun-docs.json 의 gm-task100-notice "우리 회사는 직제규정…",
build/samples-docs.json 의 '3,600만원'·'5,850만원' 등, 아래 시험에서 그대로 확인한다).

호출 규약 — '장르' 인자는 두 입구(workspace/api.py 의 새문서·저장)가 서로 다른 말을
준다:
  · 새문서(doc, 장르): 장르 = **등록부 이름**("samples"·"gongmun"·"press" … —
    build/genres.py 의 표 바깥 키, 그 파일이 "이름" 이라 부르는 값).
  · 저장(payload): doc.get("genre") 값 = **조립기가 심는 data-genre 값**
    ("onepage"·"gongmun"·"press-release" … — 같은 표의 "장르" 필드. gongmun·
    regulation 은 두 어휘가 우연히 같지만 press 는 "press"/"press-release" 로 갈린다).
이 모듈은 **둘 다** 받는다 — ①(금액 단위)은 장르와 무관하게 늘 하고, ②(자기 호칭)만
_회사호칭_적용장르(아래, 두 어휘를 다 담았다)로 규정·시행문·보도자료에만 좁힌다.

한계(적어 둔다, build/지어냈나.py 머리말과 같은 규율) —
  · ②는 doc["기관명"] 필드의 마지막 기관 유형 접미(공사·공단·…)나, 문서 글 안의 명시적
    '(이하 "X"라 한다)' 정의로만 약칭을 찾는다. 둘 다 없으면(기관명이 없거나 아는 접미로
    안 끝나면) **아무것도 안 바꾼다** — 잘못 짚느니 가만두는 쪽이 낫다.
  · ②의 '회사'·'당사' 교정 자체도 같은 원칙으로 **허용목록**을 쓴다('26-09-28, 검토
    발견① 되짚음 — 처음엔 "고치지 않을 낱말"만 몇 개 덴이리스트로 막았는데 '계약
    당사자'·'귀 회사'·'민간 회사'·인용문 속 발언까지 새 나갔다). 지금은 문장 맨 앞이거나
    '우리' 바로 뒤일 때만, 뒤에 조사 없이 다른 한글이 안 이어질 때만, 인용부호 밖일
    때만 고친다 — 그 밖의 모든 자리(다른 한정어 뒤·복합어·인용문)는 **아무것도 안
    바꾼다**. 그래서 "구축했다. 회사는 …"처럼 문장 맨 앞이 아닌 자리의 진짜 자기 지칭도
    놓칠 수 있다(못 잡는 쪽으로 치우친 트레이드오프, 의도한 것).
  · 약칭이 자음(받침)으로 끝나면('연구원'·'위원회' 등) 은/는·이/가 조사 호응이 안 맞을
    수 있다("연구원는"). 모음으로 끝나는 약칭(공사·재단 등, 실물 표본 전부 이 경우)엔
    문제없다.
  · 금액 단위는 '만·억·천·조'(와 겹친 '천만·백만') 뒤에 **공백 없이** 붙은 '원'만 본다 —
    이미 띄어 쓴 값은 이 정규식이 애초에 안 물어(요구사항 '이미 띄운 것은 그대로') 그대로
    남는다.
"""
import re

# 문서 구조·조립·렌더링 전용 메타 키 — 사람이 쓴 글이 아니다(build/지어냈나.py 의
# _메타키_제외 와 같은 목록·같은 이유로 그대로 맞춘다) — 이 칸 밑은 아예 들여다보지 않는다.
_메타키_제외 = frozenset({
    "filename", "plan_id", "genre", "_수정시각",
    "스타일", "레이아웃", "level", "type",
    "아이콘", "포인트색", "폭", "여백", "위계체계", "새번호시작",
    "x", "y", "w", "h", "purpose_type",
    # 제목 모양·보도 본문꼴('26-09-28) — 편집기 문서 설정이 고르는 열거값이지 글이 아니다
    "제목모양", "제목틀", "장모양", "절모양", "본문꼴",
})


def _URL파일코드꼴인가(s):
    """코드·파일명·URL 칸 제외(항목① 요구) — 키 이름만으로는 못 거르는 칸(예: 표 rows 는
    리스트라 칸마다 이름이 없다)도 있어, 값 자체의 꼴로 한 번 더 본다."""
    s = s.strip()
    if not s:
        return False
    if re.search(r"https?://|www\.[A-Za-z0-9]", s):
        return True
    if re.search(r"\.(pdf|hwpx?|docx?|xlsx?|pptx?|png|jpe?g|gif|svg|json|py|js|ts|html?|css|zip|csv|txt)$",
                 s, re.IGNORECASE):
        return True
    return False


def _문자열걷기(node, 함수, 경로=""):
    """doc 트리를 걸으며 문자열 리프마다 함수(경로, 문자열)을 불러 그 결과로 제자리에서
    바꾼다(결과가 원래 값과 같으면 아무 일도 안 한다 — 함수는 못 고쳤을 때 원래 값을
    그대로 돌려주면 된다, None 을 따로 챙길 필요가 없다)."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k in _메타키_제외:
                continue
            경로다음 = f"{경로}.{k}" if 경로 else str(k)
            if isinstance(v, str):
                새 = 함수(경로다음, v)
                if 새 != v:
                    node[k] = 새
            else:
                _문자열걷기(v, 함수, 경로다음)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            경로다음 = f"{경로}.{i}" if 경로 else str(i)
            if isinstance(v, str):
                새 = 함수(경로다음, v)
                if 새 != v:
                    node[i] = 새
            else:
                _문자열걷기(v, 함수, 경로다음)


def _모든글(node, 나온다):
    """(이하 "X"라 한다) 정의를 찾으려고 doc 전체 글을 한 뭉치로 모은다 — 어디인지는
    필요 없어(찾기만 하면 된다) 경로 없이 값만 쌓는다."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k in _메타키_제외:
                continue
            _모든글(v, 나온다)
    elif isinstance(node, list):
        for v in node:
            _모든글(v, 나온다)
    elif isinstance(node, str) and node:
        나온다.append(node)


