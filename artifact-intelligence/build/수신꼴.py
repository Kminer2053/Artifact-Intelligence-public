#!/usr/bin/env python3
"""시행문(gongmun) 두문 수신·결문 수신자란의 '단일수신 축약' 판정 — 공용 모듈
(assemble_gongmun.py·tomd.py 동일 판정, assemble:F11 '26-09-27 한 곳으로 합침).

구성.수신.단일수신(온톨로지) — 수신처가 한 곳뿐이면 '수신자 참조' 대신 그 기관명을
두문 '수신' 칸에 바로 적고, 결문의 수신자란도 비운다. '수신자 참조'는 수신처가 둘
이상일 때만 쓴다(편람 구-17과의 대구). 이 축약은 문서 내용을 정하는 '구성' 규칙이라
HTML·HWPX 뿐 아니라 MD 에도 똑같이 적용돼야 한다 — 화면 전용 로직이 아니다(tomd.py
의 옛 docstring이 '화면 전용이라 MD 는 원본 그대로 낸다'고 적었던 것은 이 규칙의
성격을 잘못 짚은 것이었다, assemble:F11 검토로 정정).

왜 따로 뺐나 — assemble_gongmun.py 를 tomd.py 가 그대로 import 하면, 그 파일을 다른
작업 묶음이 동시에 고칠 때 서로의 변경이 부딪힌다(assemble_regulation.py 번호매기기와
같은 사정, 그 파일 머리말 참조). 판정 로직만 작은 공용 모듈로 떼어 두 파일이 같이
쓴다.
"""
import re

_수신구분자 = re.compile(r"[,、·/\n]|\s{2,}")


def 수신정리(doc):
    """수신처가 한 곳뿐이면 '수신자 참조' 대신 그 기관명을 '수신' 칸에 바로 적는다 —
    결문의 수신자란도 비운다. '수신자 참조'는 수신처가 둘 이상일 때만 쓴다.

    돌려주는 값: (두문에 찍을 수신 텍스트, 결문 수신자란 텍스트, 두문 값의 출처 경로 —
    "수신" 또는 "수신자란"). 출처 경로는 편집기 왕복(data-path)에 쓰인다 — MD 호출자는
    보통 앞의 두 값만 쓴다.
    """
    수신 = (doc.get("수신") or "").strip()
    수신자란 = (doc.get("수신자란") or "").strip()
    if 수신 == "수신자 참조" and 수신자란:
        후보 = [x.strip() for x in _수신구분자.split(수신자란) if x.strip()]
        if len(후보) <= 1:
            return (후보[0] if 후보 else 수신자란), "", "수신자란"
    if 수신자란 and 수신 == 수신자란:
        return 수신, "", "수신"
    return 수신, 수신자란, "수신"
