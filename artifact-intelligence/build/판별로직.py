"""장르 판정 로직(규칙 부분) — 온톨로지 신호를 받아 등록부별 점수·까닭을 낸다.

이 파일은 **규칙**이라 배포 트리(전부-A1 스킬)에서 빠진다(배포준비 의 build/*.py 전량 제거).
A1 에만 산다. api.판정() 이 온톨로지에서 신호를 읽어 이 순수 함수에 넘긴다 — 여기엔
온톨로지 접근이 없다(신호는 인자로 들어온다). 가중치·1p↔풀버전 판별 문구·문턱이 크라운
주얼(유출 감사 2026-08-18: api.py detect 인라인 규칙)이라 코드에서 이 파일로 모아 뺀다.
"""
import re


def 점수매기기(글, 신호, 장르목록, 예시, 유형점수):
    """글·신호(온톨로지)·장르목록으로 등록부별 점수와 까닭을 낸다. 판별신호 자체는 신호
    인자(서버 온톨로지)에서 오고, 여기엔 그것을 **어떻게 세고 저울질하는가**의 규칙만 있다."""
    점수 = {g["등록부"]: {"등록부": g["등록부"], "이름": g.get("이름"),
                       "정본": g.get("정본"), "점": 0, "까닭": []} for g in 장르목록}

    def 세기(낱말들):
        n = 0
        for w in (낱말들 or []):
            s = str(w)
            s = s[1:] if s.startswith("~") else s
            if s and s in 글:
                n += 1
        return n

    def 더하기(등록부, 점, 까닭):
        t = 점수.get(등록부)
        if t and 점:
            t["점"] += 점
            t["까닭"].append(까닭)

    시 = 신호.get("시행문") or {}
    n시 = 세기(시.get("동사")) + 세기(시.get("명사")) + 세기(시.get("수신표기")) * 2 + 세기(시.get("결문")) * 2
    더하기("gongmun", n시, f"보내는 문서의 표현 {n시}곳")
    규 = 신호.get("규정") or {}
    n규 = 세기(규.get("구조")) * 2 + 세기(규.get("낱말"))
    더하기("regulation", n규, f"조문·제정 표현 {n규}곳")
    보 = 신호.get("보도자료") or {}
    n보 = 세기(보.get("머리표")) * 2 + 세기(보.get("낱말"))
    더하기("press", n보, f"언론 배포 표현 {n보}곳")
    슬 = 신호.get("발표슬라이드") or {}   # _서버전용 신호 — detect 는 점수·까닭만 반환(클라 미노출)
    n슬 = 세기(슬.get("낱말")) + 세기(슬.get("용도")) * 2   # 용도(스크린·빔·투영)는 강한 신호
    더하기("slides", n슬, f"발표·화면 투영 표현 {n슬}곳")

    # 1p ↔ 풀버전은 분량이 아니라 **독자가 무엇을 해야 하는가**로 가른다('26-08-04).
    빠름 = bool(re.search("결재|승인|판단|의사결정|경영진|보고드|검토 결과|권고|상신", 글))
    펴기 = bool(re.search("추진계획|세부 계획|배경부터|근거를 자세|절차를 모두|매뉴얼|전체 과정|장별", 글))
    더하기("samples", 2 + (3 if 빠름 else 0), "결재·판단을 받는 문서로 읽힘" if 빠름 else "기본값")
    if 펴기:
        더하기("fullreport", 4, "내용을 펴서 보여야 하는 문서로 읽힘")
    if 예시:
        b = 예시.get("뼈대") or {}
        절당 = b.get("절당_항목") or []
        if (b.get("조문수") or 0) >= 5:
            더하기("regulation", 6, "주신 예시가 조문 문서입니다")
        elif (b.get("절수") or 0) >= 5 and (sum(절당) / max(b.get("절수") or 1, 1)) >= 5:
            더하기("fullreport", 6, "주신 예시가 절마다 두터운 문서입니다")
        elif b.get("절수"):
            더하기("samples", 6, f"주신 예시가 절 {b['절수']}개짜리 한 장 문서입니다")
    나온 = sorted(점수.values(), key=lambda x: -x["점"])
    유형 = 유형점수(글) if (나온 and 나온[0]["등록부"] == "samples") else None
    return {"장르": 나온, "유형": 유형}


def 서식귀띔(뼈대):
    """예시 서식의 뼈대(절수·조문수·절당항목)를 보고 어느 장르에 가까운지 한 줄 귀띔.
    api.서식분석() 이 부른다. detect 의 예시 문턱(조문수·절수 ≥5)과 같은 규칙이라 여기 모은다."""
    절수 = 뼈대.get("절수") or 0
    조문수 = 뼈대.get("조문수") or 0
    절당 = 뼈대.get("절당_항목") or []
    귀띔 = []
    if 조문수 >= 5:
        귀띔.append("조문이 여럿이라 **규정**에 가깝습니다")
    elif 절수 >= 5 and sum(절당) / max(절수, 1) >= 5:
        귀띔.append("절이 많고 절마다 내용이 두터워 **풀버전**에 가깝습니다")
    elif 절수:
        귀띔.append(f"절 {절수}개에 위계 {뼈대.get('위계_깊이')}단 — **1페이지 보고서** 뼈대와 같습니다")
    if not 뼈대.get("절") and not 조문수:
        귀띔.append("글머리 위계가 안 보입니다 — 서술형 문서(보도자료·시행문)일 수 있습니다")
    return 귀띔
