                # 지워라"는 뜻이지 "칸 전체를 ○○ 하나로 뭉개도 된다"는 뜻이 아니다. 긴
                # 자유서술 칸(월표현·작성일자·인용)을 빈 글로 통째로 지우면 걸리지 않은
