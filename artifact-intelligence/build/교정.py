                if 종류표.get(경로) in _조문_종류:
                    거절.append({"경로": 경로, "이유": "조문은 지우지 않습니다 — 술어·시행일만 자료대로 고친 온 문장을 "
                                "다시 보내 주십시오(시행일이 자료에 없으면 '○○○○년 ○월 ○일'로 비운 문장)."})
                    continue
