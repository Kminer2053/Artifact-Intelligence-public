def _경로풀기(doc, 어디):
    """'어디' 표기 하나를 (담는곳, 키) 로 푼다 — 못 풀면 None(교정적용이 거절한다).

    두 표기를 받는다: ① 일반 dot-path(장.0.절.0.항목.2.text·붙임.0·메타.공개) —
    문서글()의 일반 경로가 그대로 이 꼴이다. ② 1p(samples) 옛 표기(절1 제목·절1
    항목2·title 처럼 스키마 키를 그대로 쓴 것, 지어냈나._문서글_1p 참고) — '표 머리'·
    '표 칸'은 열 위치가 안 실려(그 함수가 인덱스 없이 낸다) 어느 칸인지 특정할 수
    없으므로 여기서도 특정하지 않고 거절한다(모호한 자리를 짐작해 지우지 않는다)."""
    어디 = str(어디 or "")
    if 어디 in ("title", "byline", "summary", "attach"):
        return doc, 어디
    m = _1p_절제목_RX.match(어디)
    if m:
        si = int(m.group(1)) - 1
        sections = doc.get("sections")
        if isinstance(sections, list) and 0 <= si < len(sections) and isinstance(sections[si], dict):
            return sections[si], "heading"
        return None
    m = _1p_절항목_RX.match(어디)
    if m:
        si, ii = int(m.group(1)) - 1, int(m.group(2)) - 1
        sections = doc.get("sections")
        if isinstance(sections, list) and 0 <= si < len(sections) and isinstance(sections[si], dict):
            items = sections[si].get("items")
            if isinstance(items, list) and 0 <= ii < len(items) and isinstance(items[ii], dict):
                return items[ii], "html"
        return None
    if 어디 in ("표 머리", "표 칸"):
        return None    # 열 위치가 없어 특정 못 한다 — 아래 풀수있나() 가 이걸로 미리 거른다
    조각 = [x for x in 어디.split(".") if x != ""]
    if not 조각:
        return None
    node = doc
    for k in 조각[:-1]:
        if isinstance(node, list):
            if not k.isdigit():
                return None
            i = int(k)
            if not (0 <= i < len(node)):
                return None
            node = node[i]
        elif isinstance(node, dict):
            if k not in node:
                return None
            node = node[k]
        else:
            return None
    마지막 = 조각[-1]
    if isinstance(node, list):
        if not 마지막.isdigit():
            return None
        i = int(마지막)
        return (node, i) if 0 <= i < len(node) else None
    if isinstance(node, dict):
        return node, 마지막
    return None


def 풀수있나(doc, 경로) -> bool:
    """이 경로가 실제로 풀리는 자리인가만 본다 — api.교정지시 가 지시문·허용경로에 싣기
    전에 **아예 못 고칠 자리**('표 머리'·'표 칸' 같은 위치 모호한 1p 옛 표기)를 걸러낼 때
    쓴다(r9 검토자 발견, loop-channels LOW — 못 고칠 경로를 지시문에 실어도 교정적용 은
    늘 거절하니 모델의 시도만 헛수고가 된다)."""
    return _경로풀기(doc if isinstance(doc, dict) else {}, 경로) is not None


def 교정적용(doc, 고침, 허용경로, 종류표=None, 고칠꼴표=None, 남길글표=None):
    """고침(모델이 낸 [{경로,글}] 목록)을 **허용경로 안에서만** 적용한다.

    돌려주는 것: (새doc, 적용수, 거절목록). 거절 사유는 사람이 읽을 짧은 한글 —
    api.교정적용 이 이걸 로그에 그대로 보탠다. 빈 글은 **붙임·별첨** 목록 항목이면
    지우고, 그 밖의 칸(문자열이든 다른 목록 원소든)은 "○○"로 바꾼다(위 교정지시문
    규칙과 짝) — 조용히 아무 것도 안 하는 대신 자리표시를 남기고, 표 칸·항목처럼
    삭제하면 모양이 깨지는 목록 원소는 애초에 안 지운다(r9 검토자 발견, probe6).

    `고침` 은 [{경로,글}] 목록 말고도 받는다 — JSON 문자열(글로 온 경우, MCP·CLI가
    흔히 이렇게 보낸다)이나 {"고침":[...]} 봉투(모델이 지시문의 돌려줄 모양을 그대로
    따라 통째로 낸 경우)도 여기서 풀어 받는다(r9 검토자 발견, loop-channels LOW).

    `종류표`(선택, {경로: 검토하기() 의 '종류'})를 주면 자유서술 칸(월표현·작성일자·
    인용)에 한해 **걸리지 않은 나머지 문장이 그대로인지**(_조각밖유지되나) 확인하고,
    많이 달라졌으면 그 항목만 거절한다(r9 검토자 발견, loop-channels·regression HIGH —
    칸 전체를 갈아 끼워 같은 문단의 정상 내용까지 지우던 문제). 안 주면(기존 호출부·
    시험) 이 검사를 건너뛰어 예전과 같이 동작한다.

    `고칠꼴표`(선택, {경로: 검토하기() 의 '고칠꼴'})에서 '키지움'인 칸(지어낸 출처, W1 '26-09-30)은 글이 빈 문자열이거나
    자리표시뿐('○○'·'-')이면 ○○로 두지 않고 **그 키를 지운다**(담는 곳이 dict 일 때). 자료 이름 같은 진짜 글을 보내면
    그 글로 바꾼다 — 그 글이 자료에 있는지는 api.교정적용 이 다시 잰다. 안 주면 예전과 같다.
    fixup2(X3) — '없음'꼴 답('(출처 미상)'·'N/A'·'○○ 자료'·'해당 없음' …)도 지움으로 읽는다(_지움답인가). `남길글표`({경로: 맞는
    조각})에 있는 칸은 키를 지우는 대신 그 글(지은 조각을 뺀 출처)로 둔다.
    '요지장'인 칸(인용 장의 말한 사람, X1)은 지움 답이면 그 장을 요지 장(본문)으로 바꾸고, 진짜 글이면 그 글로 바꾼다.
    """
    고침 = 고침목록(고침)
    새doc = copy.deepcopy(doc) if isinstance(doc, dict) else {}
    허용 = {str(x) for x in (허용경로 or ())}
    종류표 = 종류표 or {}
    고칠꼴표 = 고칠꼴표 or {}
    남길글표 = 남길글표 or {}
    적용수 = 0
    거절 = []
    지울것 = {}   # {(id(컨테이너), 인덱스): 컨테이너} — 중복 경로를 자동으로 한 번만 지운다
    키지울것 = {}  # {(id(컨테이너), 키): 컨테이너} — 키지움 칸(dict 의 키)도 같은 경로가 두 번 와도 한 번만
    요지장들 = {}  # {id(장): 장} — 요지 장으로 바꿀 인용 장(같은 경로가 두 번 와도 한 번만)
    for 항목 in (고침 or []):
        if not isinstance(항목, dict):
            거절.append({"경로": None, "이유": "고침 항목이 객체가 아닙니다"})
            continue
        경로 = str(항목.get("경로") or "").strip()
        if not 경로:
            거절.append({"경로": 경로, "이유": "경로가 없습니다"})
            continue
        if 경로 not in 허용:
            거절.append({"경로": 경로, "이유": "이번에 걸리지 않은 칸이라 거절합니다"})
            continue
        풀림 = _경로풀기(새doc, 경로)
        if 풀림 is None:
            거절.append({"경로": 경로, "이유": "문서에서 그 경로를 찾지 못했습니다(자리가 모호하거나 이미 없습니다)"})
            continue
        컨테이너, 키 = 풀림
        글 = 항목.get("글")
        글값 = "" if 글 is None else str(글).strip()
