_범위인용 = re.compile(r"제\s*(\d+)\s*조\s*부터\s*제\s*(\d+)\s*조\s*까지")


def _범위번호들(inner):
    """괄호 안 범위 인용을 펼친 번호 집합(범위가 없으면 빈 집합)."""
    나온다 = set()
    for a, b in _범위인용.findall(inner):
        a, b = int(a), int(b)
        if a <= b <= a + 50:
            나온다.update(range(a, b + 1))
    return 나온다
_토큰 = re.compile(r"[가-힣A-Za-z0-9]+")
# 「」없이도 법령명 뒤에 오는 제N조는 타법 인용이다(예: "개인정보 보호법 제29조") — 회귀
# (jo_adv.py 실측, '26-09-27): 「」만 보면 이 꼴이 자기 문서 조로 오인돼 엉뚱한 번호로 바뀐다.
_타법힌트 = re.compile(r"(법률|법|령|규칙|조례|훈령|예규|지침)\s*$")


# 낱말 끝 조사 한 겹 — '운영과'·'인원의'·'재택근무의'를 '운영'·'인원'·'재택근무'로 본다
