_끝조사 = re.compile(r"(에서|으로|와|과|의|은|는|이|가|을|를|에|로|도|만)$")


def _토큰들(s):
    나온다 = []
    for t in _토큰.findall(s or ""):
        뗀 = _끝조사.sub("", t) if re.fullmatch(r"[가-힣]+", t) else t
        t = 뗀 if len(뗀) >= 2 else t
        if len(t) >= 2:
            나온다.append(t)
    return 나온다


def _조맵(doc):
    """조 번호 → {"제목", "본문"(제목+항·호·목 텍스트를 이어붙인 대조용 글)}.
    assemble_regulation.짜기() 가 실제로 매기는 번호와 **같은 계산**을 그대로 불러 쓴다
    (번호 체계를 여기서 새로 만들면 언젠가 어긋난다)."""
    items = doc.get("본문") or []
    자리표 = _reg.짜기(items)
    묶음 = {}
    현재 = None
    for i, it in enumerate(items):
        if not isinstance(it, dict):
            continue
        lv = it.get("level")
        if lv == "조":
            z = 자리표.get(i)
            if not z:
                continue
            현재 = z["번호"]
            묶음[현재] = {"제목": it.get("제목") or "", "글": [it.get("제목") or "", it.get("text") or ""]}
        elif lv in ("항", "호", "목") and 현재 is not None:
            묶음[현재]["글"].append(it.get("text") or "")
        elif lv in ("장", "절"):
            현재 = None  # 장·절 표제 자체는 조가 아니다 — 다음 조 전까지는 귀속 없음
    return {n: {"제목": v["제목"], "본문": " ".join(v["글"])} for n, v in 묶음.items()}


def _일반어(조맵, 후보토큰들):
    """조 전체의 절반 이상에 나오는 낱말은 이 규정이 뭘 다루든 다 걸리는 잡음이다
    (부분 문자열 포함으로 넓게 잡는다 — "재택근무자"의 "재택근무"까지 걸러야 한다)."""
    n = len(조맵) or 1
    일반 = set()
    for t in set(후보토큰들):
        어디 = sum(1 for v in 조맵.values() if t in (v["제목"] + v["본문"]))
        if 어디 * 2 >= n:
            일반.add(t)
    return 일반


def _점수(항목글, 조, 일반어집합):
    """이 조가 항목 글이 말하는 그 조일 가능성 점수(제목 통짜 일치=5 · 그 외엔 제목 낱말
    그대로 일치 낱말당 3 + 본문 낱말 그대로 일치 낱말당 1, 일반어는 뺀다).

    제목이 2자 이하면 제목 신호(통짜·토큰)를 아예 안 준다(_최소제목길이) — "보안"·"목적"
    류 짧은 제목은 문맥과 무관하게 항목 글 어디에나 우연히 나타나기 쉽다(회귀 근거는
    파일 머리 docstring)."""
    무공백_제목 = re.sub(r"\s+", "", 조["제목"])
    제목_신호있음 = len(무공백_제목) >= _최소제목길이
    if 제목_신호있음:
        무공백_항목 = re.sub(r"\s+", "", 항목글)
        if 무공백_제목 in 무공백_항목:
            return 5
    항목토큰 = set(_토큰들(항목글)) - 일반어집합
    제목토큰 = set(_토큰들(조["제목"])) if 제목_신호있음 else set()
    본문토큰 = set(_토큰들(조["본문"])) - 제목토큰
    return 3 * len(항목토큰 & 제목토큰) + 1 * len(항목토큰 & 본문토큰)


# 목적 조는 본문이 규정 전체를 한 문장으로 요약해('신청, 승인, 복무 및 보안 기준을 정함')
# 어느 항목과도 본문 낱말이 조금씩 겹친다 — 항목이 '목적'을 말할 때만 후보로 삼는다
# ('26-09-28, 낱말 조사 떼기 뒤 gemma-s4 회귀에서 '신청 및 승인 절차…'에 제1조가 딸려 붙음).
_요약조제목 = ("목적",)
# reg13('26-09-30 bench15 J7) — '목적 외 처리 금지'의 '목적'은 목적 조를 말하지 않는다. 전에는 제목 글자가 항목에 들어
# 있기만 하면 목적 조를 후보로 살려, 맞게 쓴 '(제9조·제10조)'를 '(제1조·제9조)'로 바꿨다(bench15 M2 s4e 재현).
_목적외_RX = re.compile(r"목적\s?(?:외|밖|이외)")


def _어간같음(t, u):
    return t == u or (min(len(t), len(u)) >= 2 and (t.startswith(u) or u.startswith(t)))


def _어간지지(항목글, 조, 일반어집합):
    """실재하는 인용 조를 항목 글이 활용형으로라도 가리키는가(reg13 fixup, review_checks M4 — 정밀도 우선).
    점수(_점수)는 토큰이 **그대로** 같아야 해서 '이용을 제한할'↔제목 '이용 제한'(A17)·'회의실·예약자·이용 제한의 뜻'↔정의 조
    호(A01)처럼 맞게 쓴 인용이 문턱에 못 미치고, 다른 조 제목이 항목에 통째로 들면(5점) 그 조로 바뀌었다. 둘 중 하나면 지지:
      · 제목(공백 빼고 3자 이상) 낱말이 모두 항목 낱말과 어간이 같고, 그중 하나 이상이 일반어가 아니다.
      · 일반어가 아닌 항목 낱말 둘 이상이 그 조(제목·본문) 낱말과 어간이 같다.
    gemma-s4 의 틀린 인용(어간 겹침 0~1)은 여전히 지지받지 못해 고쳐진다."""
    항목토큰 = set(_토큰들(항목글))
    제목토큰 = set(_토큰들(조["제목"]))
    if len(re.sub(r"\s+", "", 조["제목"])) >= _최소제목길이 and 제목토큰 and all(
            any(_어간같음(t, u) for u in 항목토큰) for t in 제목토큰) and (제목토큰 - 일반어집합):
        return True
    조토큰 = 제목토큰 | set(_토큰들(조["본문"]))
    겹침 = {t for t in 항목토큰 - 일반어집합 if any(_어간같음(t, u) for u in 조토큰)}
    return len(겹침) >= 2


def _요약조언급(제목, 항목글):
    return 제목 in _목적외_RX.sub("", 항목글)


def _후보들(항목글, 조맵, 일반어집합):
    점수표 = [(n, _점수(항목글, 조, 일반어집합)) for n, 조 in 조맵.items()
            if not (re.sub(r"\s+", "", 조["제목"]) in _요약조제목
                    and not _요약조언급(re.sub(r"\s+", "", 조["제목"]), 항목글))]
    점수표 = [(n, s) for n, s in 점수표 if s >= _문턱]
    점수표.sort(key=lambda x: (-x[1], x[0]))
    return [n for n, _ in 점수표[:_최대후보]]


def _괄호로(번호들):
    return "(" + ", ".join(f"제{n}조" for n in sorted(번호들)) + ")"


def _괄호치환(inner, 후보):
    """번호만 갈아 끼우고 나머지 글은 그대로 둔다("안 제5조"의 "안", "제3조제2항"의
    "제2항", "제2조 신설"의 "신설" 같은 한정어가 살아남는다) — 인용 개수와 후보 개수가
    같을 때만. 다르면(범위 인용 "…부터…까지" 등, 안전하게) 통짜로 다시 짓는다."""
    번호들 = _조인용.findall(inner)
    if len(번호들) == len(후보) and 후보:
        새번호 = iter(sorted(후보))
        치환글 = _조인용.sub(lambda mo: f"제{next(새번호)}조", inner)
        return f"({치환글})"
    return _괄호로(후보)


def _타법인용인가(inner):
    """괄호 안이 이 문서 자기 조가 아니라 다른 법령을 인용하는가. 「」로 법령명을
    직접 인용하면 확실하고, 「」없이도 "…법·…령·…규칙·…조례" 같은 법령명이 "제N조"
    바로 앞에 오면(예: "개인정보 보호법 제29조") 타법으로 본다 — 회귀 근거는 파일 머리
    docstring(jo_adv.py 실측)."""
    if "「" in inner:
        return True
    for mo in _조인용.finditer(inner):
        앞 = inner[: mo.start()].strip()
        if 앞 and _타법힌트.search(앞):
            return True
    return False


# 부칙 조 인용 — '(부칙 제2조)'·'(안 부칙 제2조)'·'(부칙 제1조·제2조)'·'(제5조, 부칙 제2조)'. 부칙의 조 번호는 본문 조
# 번호와 따로 센다(부칙 제1조는 본문 제1조가 아니다). 예전엔 괄호 안 '제N조'를 모두 본문 조로 읽어 bench9 C1-s4b 의
# '(안 부칙 제2조)'를 '(안 부칙 제6조)'로 — 부칙에 없는 조로 — 바꿨다('26-09-29 reg10 3차 H2). 부칙 인용이 섞인 괄호는
# 통째로 건드리지 않는다(부칙 조 수로 따로 맞추는 일은 하지 않는다 — 틀리게 고치는 것보다 안 고치는 게 낫다).
_부칙인용 = re.compile(r"부\s*칙")


def _부칙인용인가(inner):
    return bool(_부칙인용.search(inner or ""))


def 맞추기(doc) -> list[str]:
    """규정 doc 의 주요내용 항목 끝 조 인용을 실제 본문 조 번호·제목과 맞춘다. doc 를
    제자리에서 고치고, 사람이 읽을 변경 내역(list[str], 안 바뀌면 빈 리스트)을 돌려준다."""
    바뀜 = []
    if not isinstance(doc, dict):
        return 바뀜
    주요내용 = doc.get("주요내용")
    if not isinstance(주요내용, list) or not 주요내용:
        return 바뀜
    조맵 = _조맵(doc)
    if not 조맵:
        return 바뀜
    N = max(조맵)

    전체토큰 = []
    for x in 주요내용:
        전체토큰 += _토큰들(str(x))
    for 조 in 조맵.values():
        전체토큰 += _토큰들(조["제목"]) + _토큰들(조["본문"])
    일반어집합 = _일반어(조맵, 전체토큰)

    for i, raw in enumerate(주요내용):
        원문 = str(raw)
        m = _꼬리괄호.search(원문)
        if m:
            inner = m.group(1)
            if _타법인용인가(inner):
                continue  # 타법 인용(법령명 뒤 제N조) — 건드리지 않는다
            if _부칙인용인가(inner):
                continue  # 부칙 조 인용('(부칙 제2조)'·'(안 부칙 제2조)') — 본문 조가 아니다, 건드리지 않는다
            인용번호 = sorted(set(int(x) for x in _조인용.findall(inner)))
            if not 인용번호:
                continue  # 조 인용이 아닌 다른 괄호(예산 메모 등) — 건드리지 않는다
            본문글 = 원문[: m.start()]
            꼬리점 = m.group(2) or ""
            범위 = _범위번호들(inner)
            if 범위:
                인용번호 = sorted(set(인용번호) | 범위)
            범위밖번호 = [n for n in 인용번호 if n < 1 or n > N]
            # 범위 인용은 본문에 실재하고, 범위 안 조 가운데 하나라도 항목 글과 맞으면 그대로 둔다 —
            # 범위는 '이 조들을 묶어 말한다'는 뜻이라 끝 조 하나의 점수가 낮다고 범위를 줄이면 틀린
            # 범위가 된다(적대검토 H3). 범위 안 어느 조도 안 맞을 때만 아래로 가서 다시 고른다.
            if 범위 and not 범위밖번호 and any(
                    _점수(본문글, 조맵[n], 일반어집합) >= _문턱 for n in 인용번호 if n in 조맵):
                continue
            각각통과 = (not 범위밖번호) and all(
                _점수(본문글, 조맵[n], 일반어집합) >= _문턱 for n in 인용번호
            )
            if 각각통과:
                continue  # 이미 본문과 맞다 — 안 건드린다
            # reg13 fixup(review_checks M4) — 인용이 모두 본문에 실재하고 각 조를 항목이 활용형으로라도 가리키면(_어간지지) 애매한
            # 것이다 — 고치지 않는다(맞게 쓴 인용 30건 중 4건이 다른 조 제목 통째 일치로 바뀌었다).
            if not 범위밖번호 and all(_점수(본문글, 조맵[n], 일반어집합) >= _문턱 or _어간지지(본문글, 조맵[n], 일반어집합)
                                  for n in 인용번호):
                continue
            후보 = _후보들(본문글, 조맵, 일반어집합)
            # 후보 중 **원래 인용에 없던 번호가 하나라도 있어야** 교체한다(diff, '26-09-27
            # 재진단). bench2 A/s4 실측: 인용 [8, 11] 중 11("비용 지원")은 점수가 충분해
            # 각각통과가 아니라 8("보안", 2자라 제목 신호가 빠졌다)만 문턱을 못 넘었는데,
            # 후보들() 이 [11] 만 돌려주면(이미 인용에 있던 번호뿐, 새 번호가 없다) 이건
            # "더 나은 조를 찾은" 게 아니라 "일부를 확인 못 했을 뿐"이다 — 그런데 지우면
            # 맞을 수도 있는 인용(8)을 근거 없이 잃는다. 후보가 원래 집합의 부분집합이면
            # 손대지 않는다(아래 else 로 빠진다) — 정말 다른 번호를 찾았을 때만 바꾼다.
            새후보있음 = bool(set(후보) - set(인용번호))
            # reg13('26-09-30 bench15 J7, 정밀도 우선) — 인용이 모두 본문에 **실재하면**, 새로 들일 번호가 하나같이 확신
            # 점수(제목 통째 일치 5 이상)일 때만 바꾼다. 제목 낱말 하나(3점)로는 맞게 쓴 인용을 못 이긴다 — bench15 M1 s4e 의
            # '위탁·수탁자·재위탁의 뜻을 정함(제2조)'(정의 조, 제목 '정의'는 2자라 신호가 없다)가 '재위탁의 제한'(제7조)의
            # 낱말 하나에 밀려 '(제7조)'로 바뀌었다. 애매하면 고치지 않는다. 범위 밖 인용은 예전대로(문턱 이상이면 고른다).
            if 새후보있음 and not 범위밖번호:
                새후보있음 = all(_점수(본문글, 조맵[n], 일반어집합) >= _확신점수
                             for n in set(후보) - set(인용번호))
            if 후보 and 새후보있음:
                # 범위 인용을 고칠 때는 '부터 …까지' 글을 살려 두 번호만 갈면 가운데 조를 잘못 묶는다 —
                # 고른 조를 나열로 다시 쓴다.
                치환 = _괄호로(후보) if 범위 else _괄호치환(inner, 후보)
                고침 = 본문글 + 치환 + 꼬리점
                주요내용[i] = 고침
                바뀜.append(
                    f"주요내용[{i}]: {원문!r} → {고침!r} "
                    f"(인용 {인용번호} 이 본문과 안 맞거나 범위 밖이라 실제 조로 바꿨다)"
                )
            elif 범위밖번호:
                # 존재하지 않는 조(제9조인데 본문은 제8조까지)를 대신할 후보도 못 찾았다 —
                # 틀린 번호보다 없는 게 낫다(설계 지시). 실재하는 조만 인용됐다면(아래
                # else) 대안이 없어도 **지우지 않는다** — 점수가 낮다고 실제로 존재하는
                # 조 인용을 지우면 맞는 인용까지 함께 잃는다(회귀 근거는 파일 머리 docstring,
                # "지급 노트북만 사용하도록 의무화(제5조)" 실측).
                고침 = 본문글.rstrip() + 꼬리점
                주요내용[i] = 고침
                바뀜.append(
                    f"주요내용[{i}]: {원문!r} → {고침!r} "
                    f"(인용 {범위밖번호} 이 본문에 없는 조라 대신할 조도 못 찾아 괄호를 지웠다)"
                )
            # else: 범위 안인데 점수만 낮고 더 나은 후보도 없다 — 그대로 둔다(안 건드린다).
        else:
            # 항목 어디에든 이미 조 인용('제N조')이 있으면 붙이지 않는다(F0-2) — 꼬리 괄호
            # 꼴로 못 읽은 인용이 있는데 하나 더 붙이면 인용이 두 벌이 된다.
            if _조인용.search(원문):
                continue
            # 괄호가 아예 없던 항목 — 조 제목이 항목 글에 통짜로 있는 조가 **하나뿐일 때만**
            # 붙인다(붙이는 쪽은 지우는 쪽보다 확신 문턱이 높아야 한다, 설계 지시). 2자 이하
            # 제목("보안"류)은 여기서도 신호로 안 쓴다 — bench2 M/s4 실측(파일 머리 docstring):
            # 무관한 항목("보안 업무 담당자 재택근무 제외")에 "보안"이 우연히 걸려 틀린 조가
            # 붙었다.
            정확후보 = [
                n
                for n, 조 in 조맵.items()
                if len(re.sub(r"\s+", "", 조["제목"])) >= _최소제목길이
                and re.sub(r"\s+", "", 조["제목"]) in re.sub(r"\s+", "", 원문)
            ]
            if len(정확후보) == 1:
                # '26-09-27 재진단(bench4 front-s4 M4) — "적용 대상과 정기·수시 유형
                # 규정"처럼 통짜 일치한 조(제3조) 말고도 짧은 제목 낱말("유형", 2자)로만
                # 걸리는 형제 조(제4조)를 더 담아 보려 _후보들()(점수 기반)로 넓혀 봤으나,
                # bench2 M/s4 회귀 시험(정당한_추가)이 바로 그 자리에서 걸렸다 — "적용
                # 대상을 …정하고 … 제외"(조2 대상)에 "적용"이라는 흔한 낱말 하나로 전혀
                # 다른 조("적용 제한", 조5)가 딸려 붙었다. "유형"과 "적용" 둘 다 **한
                # 낱말짜리 제목 토큰 일치**로 점수가 똑같이 3(문턱)이라 threshold 로는
                # 둘을 못 가른다 — 우연한 낱말 하나로 엉뚱한 조를 붙이는 사고가 더 크므로
                # (bench2_m_s4.정당한_추가 가 바로 이 사고를 막으려고 있는 시험이다) 넓히는
                # 시도를 접고 **통짜 일치 하나만** 붙이는 원래 보수적 규칙을 지킨다. M4의
                # "유형→제4조" 같은 형제 조 누락은 이 헤리스틱의 알려진 한계로 남긴다 —
                # 앞으로는 ontology.json 주요내용 뜻(2번 항목)이 모델에게 애초에 맞는
                # 인용을 쓰게 하는 쪽이 정공법이다.
                # 끝 마침표가 있으면 괄호를 그 앞에 넣는다('…함.' → '…함(제2조).').
                끝점 = _끝마침표.search(원문)
                고침 = (원문[: 끝점.start()] + _괄호로(정확후보) + 끝점.group(1)
                      if 끝점 else 원문 + _괄호로(정확후보))
                주요내용[i] = 고침
                바뀜.append(f"주요내용[{i}]: {원문!r} → {고침!r} (조 제목이 그대로 있어 확신 높음)")
    return 바뀜
