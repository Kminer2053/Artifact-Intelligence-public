_문턱 = 3      # 이 점수 이상이어야 "이 항목이 그 조를 말한다"고 본다(제목 낱말 1개 이상 그대로 일치)
_최대후보 = 2  # 괄호 하나에 최대 몇 개 조까지 묶는가(설계 지시)
_확신점수 = 5  # 실재하는 조 인용을 다른 조로 바꿀 때 새 조가 넘어야 할 점수(제목 통째 일치) — reg13 J7, 맞추기() 참고
