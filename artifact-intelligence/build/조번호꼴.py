# 괄호 뒤 마침표('…하도록 함(제2조).')도 꼬리 괄호로 읽는다('26-09-28 규정 처방 F0-2,
# 내부 기록) — 예전 `\s*\(([^()]*)\)\s*$`는 마침표를 못 받아 괄호 없는
# 항목 갈래로 빠졌고, 제목 통짜 일치로 괄호를 한 번 더 붙여 '(제2조).(제2조)'가 됐다.
