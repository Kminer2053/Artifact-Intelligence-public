def 옮기기(읽은것, *, 가드=None, 문서이름=None):
    """화면에서 읽은 트리 전체를 명령 목록으로. 미지정 역할·구멍을 같이 돌려준다."""
    명령, 미지정 = [], []
    앞쪽 = None
    for 마디 in 읽은것["마디"]:
        if 마디.get("쪽") and 앞쪽 is not None and 마디["쪽"] != 앞쪽:
            명령.append({"종류": "쪽나눔"})
        앞쪽 = 마디.get("쪽")

        종류 = 마디["종류"]
        # **종류가 먼저다.** 역할로 먼저 고르면, 표 안에 든 문단이 `data-ent="표"` 를
        # 물려받아 표 옮김이로 가서 터진다(2026-08-05 보도자료·풀보고서에서 실제로 났다).
        if 종류 == "표":
            명령.extend(_표(마디))
            continue
        if 종류 == "가로줄":
            명령.extend(_가로줄(마디))
            continue
        if 종류 == "그림":
            명령.extend(_그림(마디))
            continue
        if 종류 == "장식":
            명령.extend(_장식(마디))
            continue

        f = 찾기(마디.get("역할")) if 마디.get("역할") else None
        if f in (_표, _장식, _그림, _가로줄):
            f = None                      # 역할 이름은 맞아도 모양이 문단이면 문단으로 쓴다
        if f is None:
            # **버리지 않는다.** 잰 값 그대로 내보내고 고발한다.
            # 다만 고발은 **처음 보는 이름**에만 한다:
            #  · 역할이 없는 마디(그냥 문단) — 정상이다. 매번 고발하면 목록이 소음이 된다.
            #  · 등록은 됐는데 모양이 달라 문단으로 온 것(예: data-ent="표" 안의 설명글)
            #    — 이미 아는 이름이다.
            이름 = 마디.get("역할")
            if 이름 and 이름 not in 옮김:
                미지정.append({"역할": 이름, "반": 마디.get("반"),
                             "글": (마디.get("글") or "")[:40], "종류": 종류})
            f = _보통문단
        명령.extend(f(마디))

    _여백겹치기(명령)

    문서 = {
        "여백mm": 읽은것["쪽"]["여백mm"],
        "크기mm": 읽은것["쪽"]["크기mm"],
        "제목": 읽은것.get("제목") or "",
        "장르": 읽은것.get("장르"),
    }

    # 가드는 **명령을 만든 뒤**에 건다. 구멍이 있어도 명령은 돌려준다 — 대조기처럼
    # "옮기는 쪽 규칙" 만 빌려 쓰는 곳이 있어서다. 세우는 것은 부르는 쪽 몫이고,
    # HWPX 를 만드는 길(tohwpx)은 `ok` 가 거짓이면 파일을 안 쓴다.
    구멍 = []
    if 가드켬 if 가드 is None else 가드:
        import 카탈로그
        구멍 = 카탈로그.가드읽기().검사(
            읽은것, 문서이름 or (읽은것.get("제목") or "(문서)"))["구멍"]

    return {"ok": not 구멍, "구멍": 구멍,
            "문서": 문서, "명령": 명령, "미지정": 미지정,
            "지면글": 읽은것.get("지면글", "")}
