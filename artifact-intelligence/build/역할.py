def _겉접기(칸선, 표선):
    """표 요소의 겉선을 가장자리 칸에 접는다 — HWPX 셀 테두리는 변마다 하나라
    화면처럼 겉선·속선을 겹쳐 못 그린다. 굵은 쪽(눈에 띄는 겉선)이 이긴다."""
    if not 표선:
        return 칸선
    if not 칸선 or (표선.get("굵기mm") or 0) > (칸선.get("굵기mm") or 0):
        return 표선
    return 칸선


@역할("표", en="table")
def _표(마디):
    t = 마디["표"]
    # 겉선은 <table> 요소에 걸린다(기본표 상·하 0.4mm) — 셀 실측 전이(4-A)만 하면
    # 겉선이 통째로 사라진다(2026-08-13 한글 뷰어 육안 실측). 가장자리 칸에 접는다.
    표테 = t.get("테두리") or [None] * 4          # [상, 우, 하, 좌]
    n행 = len(t["행"])
    n열 = max(sum(c.get("가로병합") or 1 for c in r["칸"]) for r in t["행"])
    # 점유 그리드 — 세로병합이 덮은 열을 건너뛰어야 **진짜 열 번호**가 나온다.
    # 목록 순번(ci)으로 가장자리를 재면 병합 표에서 행1 첫 칸을 왼끝으로 오판한다
    # (2026-08-14 괘선 대조 축이 잡음: a1-03 결재란 — 빈 서명란이라 글자 검사도
    # 못 보던 잠복 결함).
    덮임 = set()
    행들 = []
    for ri, r in enumerate(t["행"]):
        열 = 0
        칸들 = []
        for c in r["칸"]:
            while (ri, 열) in 덮임:
                열 += 1
            가로 = c.get("가로병합") or 1
            세로 = c.get("세로병합") or 1
            for dr in range(세로):
                for dc in range(가로):
                    if (dr, dc) != (0, 0):
                        덮임.add((ri + dr, 열 + dc))
            cs = c.get("서식") or {}
            테 = list(cs.get("테두리") or [None] * 4)
            if ri == 0:
                테[0] = _겉접기(테[0], 표테[0])
            if ri + 세로 - 1 == n행 - 1:
                테[2] = _겉접기(테[2], 표테[2])
            if 열 == 0:
                테[3] = _겉접기(테[3], 표테[3])
            if 열 + 가로 - 1 == n열 - 1:
                테[1] = _겉접기(테[1], 표테[1])
            열시작 = 열
            열 += 가로
            칸들.append({
                "글": c.get("글") or "",
                "가로병합": c.get("가로병합") or 1, "세로병합": c.get("세로병합") or 1,
                "머리칸": bool(c.get("머리칸")),
                "바탕": cs.get("바탕"), "pt": cs.get("pt"),
                "굵게": (cs.get("굵기") or 400) >= 600,
                "색": cs.get("색"), "글꼴": cs.get("글꼴"),
                "줄간격": cs.get("줄간격"),
                "정렬": {"center": "CENTER", "right": "RIGHT",
                        "justify": "JUSTIFY"}.get(cs.get("정렬"), "LEFT"),
                "폭mm": c.get("폭mm"), "높이mm": r.get("높이mm"),
                "안여백mm": cs.get("안들여mm") or 0,
                "테두리": (테 if any(테) else None),
                # 진짜 열 번호 — 쓰기가 이 자리에 놓아야 병합 표에서 안 밀린다
                "열": 열시작,
            })
        행들.append({"칸": 칸들, "높이mm": r.get("높이mm")})
    return [{"종류": "표", "행": 행들, "폭mm": t.get("폭mm"), "정렬": t.get("정렬", "LEFT"),
             "역할": 마디.get("역할"), "반": 마디.get("반")}]


@역할("그림", "도형", "이미지", en="figure")
def _그림(마디):
    """SVG 도형·그림 — 글로 못 옮기니 화면에서 찍은 PNG 를 그대로 넣는다.

    화면에서 잰 mm 크기로 넣는다. 찍기에 실패했으면 명령을 내되 png 를 비워 보내고,
    쓰는 쪽이 "도형을 못 옮겼다" 고 고발한다. **조용히 빈 자리로 두지 않는다** —
    2026-08-05 풀보고서 관공서본에서 도형 안 글자 212자가 그렇게 사라졌다.
    """
    return [{"종류": "그림", "png": 마디.get("png"),
             "폭mm": 마디.get("폭mm"), "높이mm": 마디.get("높이mm"),
             "글": 마디.get("글") or "",
             "정렬": (마디.get("서식") or {}).get("정렬"),
             "역할": 마디.get("역할"), "반": 마디.get("반")}]


@역할("가로줄", "두문결문", en="row")
def _가로줄(마디):
    """칸이 나뉜 한 줄 — 시행문 두문(수신·경유·제목)·결재란·결문.

    화면에서는 CSS grid 로 칸을 나눈다. HWPX 에는 그런 문단이 없으니 **괘선 없는 표**
    한 줄로 옮긴다. 한 문단으로 뭉개면 '수신수신자 참조' 처럼 라벨과 값이 붙는다
    (2026-08-05 한글 뷰어로 직접 보고 알았다 — 글자는 다 있어서 값 대조는 통과했다).
    """
    칸들 = []
    for c in 마디.get("칸") or []:
        cs = c.get("서식") or {}
        칸들.append({
            "글": c.get("글") or "", "가로병합": 1, "세로병합": 1,
            "바탕": cs.get("바탕"), "pt": cs.get("pt"),
            "굵게": (cs.get("굵기") or 400) >= 600,
            "색": cs.get("색"), "글꼴": cs.get("글꼴"), "줄간격": cs.get("줄간격"),
            "정렬": {"center": "CENTER", "right": "RIGHT"}.get(cs.get("정렬"), "LEFT"),
            "폭mm": c.get("폭mm"), "높이mm": (마디.get("서식") or {}).get("높이mm"),
            "안여백mm": cs.get("안들여mm") or 0, "테두리": None,
        })
    if not 칸들:
        return [_문단명령(마디)]
    # 표 폭은 **칸 폭의 합**이어야 한다. 줄 상자 폭을 쓰면 합과 어긋나고,
    # 라이브러리가 남는 폭을 칸에 나눠 넣어 글자가 밀린다(2026-08-05 결문 4mm).
    합 = round(sum(c.get("폭mm") or 0 for c in 칸들), 2)
    return [{"종류": "표", "괘선없음": True,
             "행": [{"칸": 칸들, "높이mm": (마디.get("서식") or {}).get("높이mm")}],
             "폭mm": 합 or (마디.get("서식") or {}).get("폭mm"),
             "정렬": "LEFT", "역할": 마디.get("역할"), "반": 마디.get("반")}]


@역할("장식", en="rule")
def _장식(마디):
    """글이 없고 배경만 있는 띠 — 1p 제목 위아래 청색 막대, 시행문 회색 띠.

    HWPX 에 "빈 문단 + 배경색 + 높이" 로 넣는다. 이걸 버리면 문서 얼굴이 달라진다.
    """
    s = 마디.get("서식") or {}
    if not s.get("바탕"):
        return []
    return [{"종류": "띠", "바탕색": s["바탕"], "높이mm": s.get("높이mm") or 1.0,
             "역할": 마디.get("역할"), "반": 마디.get("반")}]


_문단역할들 = {n for n, f in 옮김.items() if f not in (_표, _장식, _그림, _가로줄)}


# ── 걷기 ────────────────────────────────────────────────────────────────────
def _여백겹치기(명령):
    """이웃한 문단의 아래여백·위여백을 **CSS 처럼 겹친다.**

    화면(CSS)은 맞닿은 세로 여백을 **큰 쪽 하나로 합치고**, 한글은 **둘을 더한다.**
    그래서 문단 사이마다 작은 값이 하나씩 더 붙어 아래로 갈수록 밀린다.
    2026-08-06 실측(a2-03-plan, 한글 PDF): 같은 지점이 화면보다
        본관 -1.2 → 공공부문 +0.3 → 고효율 +2.6 → 청사 +4.6 → 향후계획 +4.8
        → 연차 사업비 **+6.6mm**
    문단 사이 0.49mm 가 두 번 붙어 한 칸에 0.5mm 씩 쌓인 것이다. 1p 보고서가
    그 누적으로 한 줄을 못 담고 2쪽이 됐다.

    맞닿은 것만 겹친다 — 표·그림·쪽나눔이 사이에 끼면 그건 별개 상자라 안 겹친다.
    """
    앞 = None
    for c in 명령:
        if c.get("종류") != "문단":
            앞 = None
            continue
        문 = c.get("문단") or {}
        if 앞 is not None:
            아래 = 앞.get("아래여백mm") or 0
            위 = 문.get("위여백mm") or 0
            겹친 = round(max(아래, 위), 2)
            # 겹친 여백을 어느 쪽에 실을지 — 한글은 문단 **배경을 여백까지 칠한다**
            # (2026-08-14 육안+XML 실측: 요약박스 next=1130HU 가 회색으로 늘어나
            # '빈 엔터 한 줄'로 보이고 다음 문단과의 간격은 먹혔다). CSS 배경은
            # margin 을 안 덮으므로, 배경 있는 문단은 여백을 무배경 이웃에게 넘긴다.
            if (앞.get("바탕색") and not 문.get("바탕색")):
                앞["아래여백mm"] = 0
                문["위여백mm"] = 겹친
            else:
                앞["아래여백mm"] = 겹친
                문["위여백mm"] = 0
        앞 = 문


