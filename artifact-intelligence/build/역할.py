#!/usr/bin/env python3
"""화면에서 읽은 마디를 **HWPX 에 쓸 명령**으로 옮기는 등록부.

핵심은 하나다 — **기본이 "옮김" 이다.**
지금까지는 기본이 "건너뜀" 이었다. 전환기가 아는 역할만 옮기고 모르는 것은 조용히
버렸다. 그래서 풀버전 보고서 HWPX 에 제목 한 줄만 남았다(표지·목차·본문 여섯 장이
전부 "모르는 것" 이라 버려졌다). 없어져도 아무도 말해 주지 않는다는 게 이 함정의 본질이다.

뒤집은 뒤의 규칙:
  · 등록부에 있는 역할 → 그 옮김이가 맡는다.
  · 등록부에 **없는** 역할 → 잰 값 그대로 일반 문단으로 나간다. 그리고 `미지정` 에 실어
    고발한다. 검사가 그 목록이 비었는지 본다.
  · 장르 이름은 이 파일 어디에도 없다. 열쇠는 **역할**(data-ent)이다. 새 장르가 기존 역할만
    쓰면 이 파일은 한 줄도 안 바뀐다.

빌린 것 — CSS 속성 ↔ 문서 속성 사상은 html4docx(MIT)의 표를 참고했다. 그쪽이 안 옮기는
margin·padding·line-height 는 우리에게 필수라(개조식 위계가 그것으로 산다) 더 넣었다.
"""
옮김 = {}
_별명 = {}


def 역할(*이름들, en=None):
    """옮김이를 등록한다. **등록하는 길은 여기 하나뿐이다.**"""
    def 감싸기(f):
        for n in 이름들:
            옮김[n] = f
        if en:
            _별명[en] = 이름들[0]
        return f
    return 감싸기


def 찾기(이름):
    return 옮김.get(_별명.get(이름, 이름))


# ── 서식 옮기기 (공통) ──────────────────────────────────────────────────────
def 글자서식(조각, 바탕서식):
    """조각 하나의 글자 속성. 조각에 없는 값은 문단 값을 물려받는다."""
    def 집(k, 기본=None):
        v = 조각.get(k)
        return 바탕서식.get(k, 기본) if v is None else v
    return {
        "pt": 집("pt"), "굵게": (집("굵기", 400) or 400) >= 600,
        "기울임": bool(집("기울임", False)), "밑줄": bool(집("밑줄", False)),
        "취소선": bool(집("취소선", False)),
        "색": 집("색") or "#000000",
        "형광": 조각.get("바탕"),
        # 조각 글꼴 우선, 없으면 문단 상속 — 종전엔 문단 값을 강제 상속해 gov 강조
        # (고딕 b·.lb)가 명조로 나갔다(2026-08-14 걷힌 _떨어뜨림 '조각·글꼴')
        "글꼴": 집("글꼴"),
        # 자간은 **꼭 날라야 한다.** 자간사냥(jachigan.js)이 줄바꿈을 맞추려고 -6% 까지
        # 좁혀 놓은 것이 여기서 빠지면, 한글은 더 넓게 그려서 어절 하나씩 아래로 민다.
        # 그게 "조판 엔진이 다르다" 로 보였던 것의 정체다(2026-08-06 보도자료 실측 —
        # 화면이 -2%·-2.5%·-2.5% 를 건 세 문단이 정확히 세 곳 다 어긋났다).
        "자간": 집("자간em", 0) or 0,
    }


def 문단서식(서식, *, 마커있나=False, 판면폭mm=None):
    """문단 속성.

    왼여백 = 문단 상자가 판면에서 들어온 만큼 + 안쪽 padding.
    내어쓰기(intent)는 음수다 — 조문 번호·글머리가 첫 줄에서 왼쪽으로 나오는 그것이다.
    화면에서 잰 그대로 넣는다. **여기서 다시 계산하지 않는다** — 계산하면 화면과 갈린다.

    `판면폭mm` 를 주면 **판면보다 좁은 가운데 정렬 상자**의 자리를 상자 가운데로 잡는다
    (아래 '가운데 상자' 주석). 안 주면(대조의 한 문단짜리 폴백 등) 예전과 한 글자도 같다.
    """
    안들여 = 서식.get("안들여mm") or 0
    내어 = 서식.get("내어mm") or 0
    # 글머리표가 아닌 문단(리터럴 마커·안 마커 둘 다)의 왼쪽 자리 — **음수 내어쓰기일 때는
    # 안들여를 그대로 더하면 안 된다.** 한글은 음수 intent를 "첫 줄은 hc:left, 둘째 줄부터
    # hc:left+|intent|"로 그린다(화면의 text-indent:음수가 첫 줄을 당기는 것과 반대다) —
    # kordoc reflowPara·실물 규정 말뭉치(제N조 왼여백 0)·저장소 2026-08-06 한컴 뷰어 실측이
    # 모두 같은 의미를 가리킨다. 그래서 hc:left 는 "둘째 줄이 설 자리"가 아니라
    # "첫 줄이 설 자리"로 미리 당겨 둬야 한다 — 왼여백+안들여+min(내어,0) 로 |내어| 만큼
    # 미리 빼면, 한글이 그 값에 다시 |내어| 를 더해 만드는 둘째 줄 자리가 화면의 안들여
    # 위치(왼여백+안들여)로 돌아온다. 조·□·붙임처럼 안들여==|내어| 인 마커는 첫 줄이 0 으로
    # 떨어지고(화면과 일치), ○ 처럼 안들여>|내어| 인 마커는 첫 줄이 그 차이만큼 남는다
    # (화면 그대로) — 값을 다시 계산하는 게 아니라 **한글의 좌표계로 옮겨 적을 뿐**이다
    # (2026-09-26/27, r2 벤치마크 진단 hwpx.findings[0] — 조·□·붙임 회귀, ○·※ 사다리 오채움).
    왼 = (서식.get("왼여백mm") or 0) + 안들여 + min(내어, 0)
    # 마커가 **HWPX 글머리표(set_list_format bullet)로 갈 때만** 안들여를 더하지 않는다.
    # 화면에서 안들여(padding-left)는 마커가 앉을 자리인데, 한글은 글머리표 자리를
    # **스스로 계산해서 더한다**(글머리 1em + textOffset 50% = 13pt 에서 6.88mm).
    # 그래서 우리가 또 더하면 줄이 통째로 5.5mm 오른쪽으로 밀린다.
    #
    # **마커가 있다고 다 이 갈래는 아니다.** 예전엔 "마커가 있으면"(만든것 여부와
    # 무관하게) 무조건 취소했는데, 보도자료·규정의 □○-※·조 마커는 DOM 리터럴 글자라
    # (마커가_글자냐=True, _hwpx_write.문단() 이 글머리표가 아니라 run 으로 그대로
    # 박는다) 한글이 자리를 대신 계산해 주지 않는다 — 그런데도 안들여를 지우니
    # □(1.5ch)·○(2.5ch)·-(4.5ch) 로 다르던 들여쓰기 사다리가 전부 같은 자리로
    # 뭉쳐 하위 항목 들여쓰기가 사라졌다(2026-09-26, 벤치마크 진단 hwpx.findings[4]).
    # 호출부(_문단명령)가 "만든것"(CSS ::before 생성 마커)일 때만 True 를 넘긴다.
    #
    # 2026-08-06 넘침 시험 표본 를 한컴 뷰어에서 PDF 로 뽑아 잰 값:
    #   화면            1쪽 · 줄 31.88 ~ 181.17mm (판면 오른끝 185, 여유 3.8)
    #   한글(고치기 전)   2쪽 · 줄 37.38 ~ 186.15mm  ← 5.5mm 밀려 판면을 넘었다
    #   한글(고친 뒤)     1쪽 · 모든 줄이 한 줄에 든다
    # 폭 자체는 거의 같았다(149.30 vs 148.77mm) — **밀린 것은 시작 위치였다.**
    #
    # 내어쓰기(intent)로 당기는 길은 **안 통한다.** -5.5mm 를 넣어도 한글이 무시하고
    # 자기 autoIndent 를 쓴다(글머리표를 떼고 마커를 글자로 넣어도 같았다 — 둘 다
    # 37.38mm 그대로였다).
    if 마커있나:
        왼 = 서식.get("왼여백mm") or 0
    # **가운데 상자** — flex 세로 줄(align-items: center)에 든 가운데 정렬 문단은 상자가
    # 글자 폭으로 줄어들고(shrink-to-fit) 그 상자가 가운데에 앉는다. 풀버전 표지의 부제·
    # 제목·날짜가 이 모양이다(제목 상자 왼 52.9mm·폭 64.2mm, 2026-09-27 4차 E2E s2 실측).
    # 그 상자의 **왼쪽 끝**을 한글 왼여백으로 옮기면 한글은 [왼여백, 판면 오른끝] 가운데에
    # 글을 놓아 글이 (판면-왼-폭)/2 만큼 오른쪽으로 쏠린다(제목 26mm — 한컴 뷰어 확인).
    # 가운데 정렬 글의 자리를 정하는 것은 왼끝이 아니라 **상자의 가운데**다. 그래서 상자
    # 가운데를 중심으로 판면 안에서 가장 넓게 대칭인 구간을 왼·오른여백으로 준다 — 상자
    # 폭 그대로 좁히면 한글 글꼴이 조금만 넓어도 줄이 꺾이는데, 대칭 구간은 상자보다
    # 넓어(상자는 늘 그 구간 안에 든다) 그 위험이 없다. 판면 전폭 상자(대부분의 제목)는
    # 이 갈래를 안 탄다 — 조건이 "판면보다 2mm 넘게 좁거나 왼쪽이 1mm 넘게 들어왔다" 라서
    # 옛 값이 그대로 나간다. 마커가 글머리표로 가는 문단은 한글이 자리를 스스로 더하므로
    # 손대지 않는다.
    오른 = None
    상자폭 = 서식.get("폭mm")
    if (판면폭mm and 상자폭 and 서식.get("정렬") == "center" and not 마커있나):
        상자왼 = 서식.get("왼여백mm") or 0
        if 판면폭mm - 상자폭 > 2 or abs(상자왼) > 1:
            가운데 = 상자왼 + 상자폭 / 2
            반폭 = max(0.0, min(가운데, 판면폭mm - 가운데))
            왼 = 가운데 - 반폭
            오른 = max(0.0, 판면폭mm - (가운데 + 반폭))
    return {
        "왼여백mm": round(max(왼, 0), 2),
        # 가운데 상자일 때만 싣는다 — 없으면 _hwpx_write.자리잡기 가 예전 길(_상자오른여백)을 탄다
        **({"오른여백mm": round(오른, 2)} if 오른 is not None else {}),
        "내어쓰기mm": round(내어, 2),
        "위여백mm": round(서식.get("위여백mm") or 0, 2),
        "아래여백mm": round(서식.get("아래여백mm") or 0, 2),
        "줄간격": 서식.get("줄간격") or 160,
        "정렬": {"center": "CENTER", "right": "RIGHT", "justify": "JUSTIFY",
                "start": "LEFT", "left": "LEFT"}.get(서식.get("정렬"), "LEFT"),
        "바탕색": 서식.get("바탕"),
        "테두리": 서식.get("테두리"),
        # 상자 자신의 렌더 폭 — **배경 없이 테두리만 있는 좁은 상자**(보도자료 '보 도 자
        # 료' 표제, gov 목차 제목, gov 표지 점선 태그)의 오른여백을 못 박는 데만 쓴다.
        # 한글 문단 테두리는 ignoreMargin=0 이면 왼·오른 여백 사이 전체에 그려져,
        # 화면의 작은 가운데 상자가 판면 오른끝까지 늘어난 큰 틀이 된다(2026-09-26/27,
        # r2 벤치마크 진단 hwpx.findings[1], H1). _hwpx_write.자리잡기() 가 이 값과
        # 판면 폭으로 hc:right 를 역산한다 — 여기서는 잰 값만 그대로 싣는다.
        "상자폭mm": round(서식.get("폭mm"), 2) if 서식.get("폭mm") else None,
        # 배경 박스의 세로 안쪽 여백 — 쓰기가 border offsetTop/Bottom 으로 못 박는다
        # (배경 없는 문단에선 쓰기가 무시한다)
        "위안들여mm": round(서식.get("위안들여mm") or 0, 2),
        "아래안들여mm": round(서식.get("아래안들여mm") or 0, 2),
        "어절분리": 서식.get("어절분리", "break"),
        "자간em": 서식.get("자간em") or 0,
        # 줄 높이를 **mm 로도 실어 보낸다.** 퍼센트만 보내면 한글이 자기 글꼴 줄높이에
        # 곱해서 화면보다 6.2% 벌어진다(2026-08-06 실측). 옮기는 쪽이 이 값을
        # `FIXED` 로 못 박는다 — 표를 담은 문단은 뺀다(줄 높이가 고정되면 표가 겹친다).
        "줄높이mm": (round((서식.get("pt") or 11) * (서식.get("줄간격") or 160)
                        / 100 * 25.4 / 72, 3) if 서식.get("pt") else None),
    }


def _문단명령(마디, *, 마커=None):
    s = 마디.get("서식") or {}
    조각들 = []
    for x in 마디.get("속") or []:
        if x.get("줄바꿈"):
            조각들.append({"줄바꿈": True})
        elif x.get("빈자리mm"):
            조각들.append({"빈자리mm": x["빈자리mm"]})
        elif (x.get("글") or "").strip() or x.get("글"):
            조각들.append({"글": x["글"], **글자서식(x, s)})
    if not 조각들 and (마디.get("글") or "").strip():
        조각들 = [{"글": 마디["글"], **글자서식({}, s)}]
    mk = 마디.get("마커")
    return {
        "종류": "문단",
        "마커": 마커 if 마커 is not None else (mk and mk.get("글자")),
        "마커가_글자냐": bool(mk and not mk.get("만든것")),
        # 실글자 마커(.mk)의 제 서식 — 쓰는 쪽이 첫 글 조각 서식 대신 이것을 입힌다
        # (P0-4: 규정 '제1조' 굵게). 화면읽기가 서식을 안 실은 옛 트리면 None 이다.
        "마커서식": (글자서식(mk["서식"], s)
                  if (mk and not mk.get("만든것") and mk.get("서식")) else None),
        "조각": 조각들,
        # 안들여 취소는 "마커가 있나" 가 아니라 "그 마커가 HWPX 글머리표로 가나"
        # (=CSS ::before 로 만든 것)로 좁힌다 — 위 문단서식() 주석 참고.
        # 판면폭은 옮기기() 가 마디 사본에 실어 준다(가운데 상자 — 문단서식() 주석).
        "문단": 문단서식(s, 마커있나=bool(mk and mk.get("만든것")),
                     판면폭mm=마디.get("_판면폭mm")),
        "역할": 마디.get("역할"), "반": 마디.get("반"), "경로": 마디.get("경로"),
    }


