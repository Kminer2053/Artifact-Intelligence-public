def _세로배치옮기기(명령, 판높이):
    """화면에서 **배치가 정한 세로 자리**를 한글 문단 위 여백으로 옮긴다.

    규칙 하나로 표지(부제·제목·날짜 묶음과 기관명 묶음)와 시행문 결문(쪽 바닥 붙임)을
    함께 푼다 — "흐름이 아니라 배치가 자리를 정한 블록(화면읽기 세로.배치: 자신·조상이
    절대배치이거나 조상이 세로 flex) 앞에서, 화면의 윗끝과 한글이 흐름대로 놓을 자리의
    차이만큼 빈칸을 준다."

    한글이 놓을 자리는 **쪽마다 흉내 낸다** — 판면 위끝에서 시작해 명령 차례대로
    (앞 아래여백 + 제 위여백) 을 더하고 화면에서 잰 제 키만큼 내려간다. 앞 블록이
    화면과 다른 자리에 앉는 경우(표지의 절대배치 태그는 화면에선 흐름 밖인데 한글에선
    흐름 안에 든다, 버려진 빈 div 는 한글에 없다)도 이 흉내가 그 어긋남을 다음 배치
    블록에서 저절로 메운다. 흐름 블록(본문)에는 손대지 않는다 — 1p·보도자료·규정처럼
    배치 블록이 없는 장르는 한 글자도 안 바뀐다.

    빈칸이 쪽 바닥까지 닿으면(결문처럼) 한글이 조금만 길어도 넘친다 — 위 '넘침 여유'
    만큼을 큰 빈칸들에서 크기 비례로 덜어 낸다(화면 자신이 바닥에 남긴 틈이 그 여유를
    이미 채우면 안 덜어 낸다). 이 여유의 하한(2×최대줄높이, hwpx:F1)은 시행문 결문
    같은 '아래 붙임' 블록(_넘침여유_최대줄높이_적용역할)에만 걸린다 — 표지는 6차와
    같은 식으로 남는다(hwpx:R7-2, _세로배치옮기기 안 '붙임형' 판정 참고).
    """
    쪽들 = [c["세로"]["쪽"] for c in 명령
          if c.get("세로") and c["세로"].get("쪽") is not None]
    if not 쪽들:
        return
    첫쪽 = min(쪽들)
    보탤것 = []
    # 쪽나눔이 쪽을 가른다 — 명령을 차례대로 한 번 훑으며 쪽마다 흉내를 새로 시작한다.
    무리, 지금 = [], []
    for i, c in enumerate(명령):
        if c.get("종류") == "쪽나눔":
            무리.append(지금)
            지금 = []
            continue
        지금.append(i)
