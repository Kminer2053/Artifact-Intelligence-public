@역할("가로줄", "두문결문", en="row")
def _가로줄(마디):
    """칸이 나뉜 한 줄 — 시행문 두문(수신·경유·제목)·결재란·결문·풀버전 목차/인포박스.

    화면에서는 CSS grid/flex 로 칸을 나눈다. HWPX 에는 그런 문단이 없으니 **괘선 없는
    표** 한 줄로 옮긴다. 한 문단으로 뭉개면 '수신수신자 참조' 처럼 라벨과 값이 붙는다
    (2026-08-05 한글 뷰어로 직접 보고 알았다 — 글자는 다 있어서 값 대조는 통과했다).
    """
    칸들데이터 = 마디.get("칸") or []
    n = len(칸들데이터)
    # 컨테이너 자신의 테두리 — `.fr-infobox`(border:0.3mm solid, 칸이 아니라 감싼 틀에
    # 걸린다)·`.gm-subject`(border-bottom, 제목줄 밑줄)처럼 선이 칸이 아니라 **줄 전체를
    # 감싼 요소**에 걸리는 자리가 있다. 예전엔 이 값을 아예 안 실어(칸마다 "테두리":
    # None 하드코딩) 인포박스 테두리·시행문 제목줄 밑줄·목차 채움선(점선)이 통째로
    # 사라졌다(2026-09-26, 벤치마크 진단 hwpx.findings[1]). _표() 의 _겉접기 와 같은
    # 방식으로 가장자리 칸에 접는다 — 위·아래는 한 줄이라 모든 칸이 같이 물려받고,
    # 좌·우는 첫·끝 칸만 받는다. 칸 자신의 테두리(예: 목차 점선 칸의 border-bottom,
    # 인포박스 칸 사이 border-left)는 그대로 살아 있다가 컨테이너 값과 겨룬다.
    겉 = (마디.get("서식") or {}).get("테두리") or [None] * 4     # [상, 우, 하, 좌]
    칸들 = []
    for i, c in enumerate(칸들데이터):
        cs = c.get("서식") or {}
        테 = list(cs.get("테두리") or [None] * 4)
        테[0] = _겉접기(테[0], 겉[0])
        테[2] = _겉접기(테[2], 겉[2])
        if i == 0:
            테[3] = _겉접기(테[3], 겉[3])
        if i == n - 1:
            테[1] = _겉접기(테[1], 겉[1])
        칸들.append({
            "글": c.get("글") or "", "가로병합": 1, "세로병합": 1,
            "바탕": cs.get("바탕"), "pt": cs.get("pt"),
            "굵게": (cs.get("굵기") or 400) >= 600,
            "색": cs.get("색"), "글꼴": cs.get("글꼴"), "줄간격": cs.get("줄간격"),
            "정렬": {"center": "CENTER", "right": "RIGHT"}.get(cs.get("정렬"), "LEFT"),
            "폭mm": c.get("폭mm"), "높이mm": (마디.get("서식") or {}).get("높이mm"),
            "안여백mm": cs.get("안들여mm") or 0,
            "테두리": (테 if any(테) else None),
        })
    if not 칸들:
        return [_문단명령(마디)]
    # 표 폭은 **칸 폭의 합**이어야 한다. 줄 상자 폭을 쓰면 합과 어긋나고,
    # 라이브러리가 남는 폭을 칸에 나눠 넣어 글자가 밀린다(2026-08-05 결문 4mm).
    합 = round(sum(c.get("폭mm") or 0 for c in 칸들), 2)
    # 칸 폭은 **첫 칸의 left 부터** 잰다(위 칸: 서식(el))라 컨테이너 자신의 왼여백·안들여
    # (예: `.fr-toc-row.sec { padding-left: 8mm }`)는 어디에도 안 실린다. 그 값이 빠지면
    # 표를 담는 문단이 paraPrIDRef 0(왼여백 0)으로 나가 절 행의 8mm 들여쓰기(장·절 위계)가
    # 사라지고, 칸 폭 합만으로는 우측 정렬 쪽번호도 장 행보다 8mm 짧게 끝난다
    # (2026-09-26/27, r2 벤치마크 진단 hwpx.findings[2]). 표를 앉히는 문단의 왼여백으로
    # 옮겨 실어, 표 자체는 그대로 두고 자리만 오른쪽으로 민다(_hwpx_write.표() 가 이
    # 문단에 자리잡기를 건다).
    # 셈은 문단서식() 한 곳에서만 한다(verify_all check_marker_indent_single_site — 마커 들여쓰기
    # 이중 계산 5.5mm 밀림 함정). 가로줄 컨테이너는 마커가 없으니 마커있나=False 갈래와 같은 값이다.
    컨왼 = 문단서식(마디.get("서식") or {}, 마커있나=False)["왼여백mm"]
    # 표 앵커 문단의 위·아래 여백 — 컨테이너 자신(이 가로줄 마디)이 CSS 로 잰
    # margin-top/bottom 을 그대로 옮긴다. gov 목차의 장(ch) 행(margin-top: calc(6mm×lhs))
    # 이 이 값을 낸다 — _hwpx_write.표() 가 이 값을 안 받고 위·아래 0을 박아, 장 묶음
    # 사이 간격이 통째로 사라졌었다(3차 수정, "목차 표 앵커" low 결함 + still_partly[4]
    # 재확인). 절(sec) 행처럼 CSS 에 margin 이 없으면 0 그대로라 달라지는 것이 없다.
    서식 = 마디.get("서식") or {}
    return [{"종류": "표", "괘선없음": True,
             "행": [{"칸": 칸들, "높이mm": 서식.get("높이mm")}],
             "폭mm": 합 or 서식.get("폭mm"),
             "정렬": "LEFT", "컨왼여백mm": 컨왼,
             "위여백mm": round(서식.get("위여백mm") or 0, 2),
             "아래여백mm": round(서식.get("아래여백mm") or 0, 2),
             "역할": 마디.get("역할"), "반": 마디.get("반")}]


@역할("장식", en="rule")
def _장식(마디):
    """글이 없고 배경만 있는 띠 — 1p 제목 위아래 청색 막대, 시행문 회색 띠.

    HWPX 에 "빈 문단 + 배경색 + 높이" 로 넣는다. 이걸 버리면 문서 얼굴이 달라진다.
    """
    s = 마디.get("서식") or {}
    if not s.get("바탕"):
        return []
    # 띠 자신의 위·아래 여백도 싣는다. 예전엔 높이만 싣고 여백은 버려, 1p 제목 위 청색 띠
