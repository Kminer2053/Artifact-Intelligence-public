        쪽 = next((명령[i]["세로"].get("쪽") for i in 차례 if 명령[i].get("세로")), None)
        if 쪽 is None:
            continue
        y, 앞, 내용, 후보 = 0.0, None, 0.0, []
        최대줄높이mm = 0.0
        for i in 차례:
            c = 명령[i]
            # 이 쪽 흐름 문단 가운데 **가장 큰 줄 높이** — 아래 여유의 하한을 잡는 데
            # 쓴다(hwpx:F1). 표를 담은 문단은 줄높이mm 이 없다(_줄높이못박기 주석 — FIXED
            # 로 못 박으면 표가 겹친다), 그런 문단은 자연히 빠진다.
            if c.get("종류") == "문단":
                줄높이 = (c.get("문단") or {}).get("줄높이mm")
                if 줄높이 and 줄높이 > 최대줄높이mm:
                    최대줄높이mm = 줄높이
