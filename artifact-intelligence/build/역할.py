# 배선만 한다. 규칙이 두 곳에 있으면 반드시 갈린다.
#
# 끄는 자리는 하나뿐이다 — **카탈로그를 만드는 중**. 그때 디스크의 카탈로그는 지금
# 만들고 있는 것보다 낡아서, 그걸로 가드를 걸면 재생성이 스스로를 막는다.
