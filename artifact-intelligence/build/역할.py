#!/usr/bin/env python3
"""화면에서 읽은 마디를 **HWPX 에 쓸 명령**으로 옮기는 등록부.

핵심은 하나다 — **기본이 "옮김" 이다.**
지금까지는 기본이 "건너뜀" 이었다. 전환기가 아는 역할만 옮기고 모르는 것은 조용히
버렸다. 그래서 풀버전 보고서 HWPX 에 제목 한 줄만 남았다(표지·목차·본문 여섯 장이
전부 "모르는 것" 이라 버려졌다). 없어져도 아무도 말해 주지 않는다는 게 이 함정의 본질이다.

뒤집은 뒤의 규칙:
  · 등록부에 있는 역할 → 그 옮김이가 맡는다.
  · 등록부에 **없는** 역할 → 잰 값 그대로 일반 문단으로 나간다. 그리고 `미지정` 에 실어
    고발한다. 검사가 그 목록이 비었는지 본다.
  · 장르 이름은 이 파일 어디에도 없다. 열쇠는 **역할**(data-ent)이다. 새 장르가 기존 역할만
    쓰면 이 파일은 한 줄도 안 바뀐다.

빌린 것 — CSS 속성 ↔ 문서 속성 사상은 html4docx(MIT)의 표를 참고했다. 그쪽이 안 옮기는
margin·padding·line-height 는 우리에게 필수라(개조식 위계가 그것으로 산다) 더 넣었다.
"""
옮김 = {}
_별명 = {}


def 역할(*이름들, en=None):
    """옮김이를 등록한다. **등록하는 길은 여기 하나뿐이다.**"""
    def 감싸기(f):
        for n in 이름들:
            옮김[n] = f
        if en:
            _별명[en] = 이름들[0]
        return f
    return 감싸기


def 찾기(이름):
    return 옮김.get(_별명.get(이름, 이름))


# ── 서식 옮기기 (공통) ──────────────────────────────────────────────────────
def 글자서식(조각, 바탕서식):
    """조각 하나의 글자 속성. 조각에 없는 값은 문단 값을 물려받는다."""
    def 집(k, 기본=None):
        v = 조각.get(k)
        return 바탕서식.get(k, 기본) if v is None else v
    return {
        "pt": 집("pt"), "굵게": (집("굵기", 400) or 400) >= 600,
        "기울임": bool(집("기울임", False)), "밑줄": bool(집("밑줄", False)),
        "취소선": bool(집("취소선", False)),
        "색": 집("색") or "#000000",
        "형광": 조각.get("바탕"),
        # 조각 글꼴 우선, 없으면 문단 상속 — 종전엔 문단 값을 강제 상속해 gov 강조
        # (고딕 b·.lb)가 명조로 나갔다(2026-08-14 걷힌 _떨어뜨림 '조각·글꼴')
        "글꼴": 집("글꼴"),
        # 자간은 **꼭 날라야 한다.** 자간사냥(jachigan.js)이 줄바꿈을 맞추려고 -6% 까지
        # 좁혀 놓은 것이 여기서 빠지면, 한글은 더 넓게 그려서 어절 하나씩 아래로 민다.
        # 그게 "조판 엔진이 다르다" 로 보였던 것의 정체다(2026-08-06 보도자료 실측 —
        # 화면이 -2%·-2.5%·-2.5% 를 건 세 문단이 정확히 세 곳 다 어긋났다).
        "자간": 집("자간em", 0) or 0,
    }


def 문단서식(서식, *, 마커있나=False):
    """문단 속성.

    왼여백 = 문단 상자가 판면에서 들어온 만큼 + 안쪽 padding.
    내어쓰기(intent)는 음수다 — 조문 번호·글머리가 첫 줄에서 왼쪽으로 나오는 그것이다.
    화면에서 잰 그대로 넣는다. **여기서 다시 계산하지 않는다** — 계산하면 화면과 갈린다.
    """
    안들여 = 서식.get("안들여mm") or 0
    왼 = (서식.get("왼여백mm") or 0) + 안들여
    내어 = 서식.get("내어mm") or 0
    # 마커가 HWPX 글머리표로 갈 때는 **안들여를 더하지 않는다.**
    # 화면에서 안들여(padding-left)는 마커가 앉을 자리인데, 한글은 글머리표 자리를
    # **스스로 계산해서 더한다**(글머리 1em + textOffset 50% = 13pt 에서 6.88mm).
    # 그래서 우리가 또 더하면 줄이 통째로 5.5mm 오른쪽으로 밀린다.
    #
    # 2026-08-06 a5-14-overflow 를 한컴 뷰어에서 PDF 로 뽑아 잰 값:
    #   화면            1쪽 · 줄 31.88 ~ 181.17mm (판면 오른끝 185, 여유 3.8)
    #   한글(고치기 전)   2쪽 · 줄 37.38 ~ 186.15mm  ← 5.5mm 밀려 판면을 넘었다
    #   한글(고친 뒤)     1쪽 · 모든 줄이 한 줄에 든다
    # 폭 자체는 거의 같았다(149.30 vs 148.77mm) — **밀린 것은 시작 위치였다.**
    #
    # 내어쓰기(intent)로 당기는 길은 **안 통한다.** -5.5mm 를 넣어도 한글이 무시하고
    # 자기 autoIndent 를 쓴다(글머리표를 떼고 마커를 글자로 넣어도 같았다 — 둘 다
    # 37.38mm 그대로였다).
    if 마커있나:
        왼 = 서식.get("왼여백mm") or 0
    return {
        "왼여백mm": round(max(왼, 0), 2),
        "내어쓰기mm": round(내어, 2),
        "위여백mm": round(서식.get("위여백mm") or 0, 2),
        "아래여백mm": round(서식.get("아래여백mm") or 0, 2),
        "줄간격": 서식.get("줄간격") or 160,
        "정렬": {"center": "CENTER", "right": "RIGHT", "justify": "JUSTIFY",
                "start": "LEFT", "left": "LEFT"}.get(서식.get("정렬"), "LEFT"),
        "바탕색": 서식.get("바탕"),
        "테두리": 서식.get("테두리"),
        # 배경 박스의 세로 안쪽 여백 — 쓰기가 border offsetTop/Bottom 으로 못 박는다
        # (배경 없는 문단에선 쓰기가 무시한다)
        "위안들여mm": round(서식.get("위안들여mm") or 0, 2),
        "아래안들여mm": round(서식.get("아래안들여mm") or 0, 2),
        "어절분리": 서식.get("어절분리", "break"),
        "자간em": 서식.get("자간em") or 0,
        # 줄 높이를 **mm 로도 실어 보낸다.** 퍼센트만 보내면 한글이 자기 글꼴 줄높이에
        # 곱해서 화면보다 6.2% 벌어진다(2026-08-06 실측). 옮기는 쪽이 이 값을
        # `FIXED` 로 못 박는다 — 표를 담은 문단은 뺀다(줄 높이가 고정되면 표가 겹친다).
        "줄높이mm": (round((서식.get("pt") or 11) * (서식.get("줄간격") or 160)
                        / 100 * 25.4 / 72, 3) if 서식.get("pt") else None),
    }


def _문단명령(마디, *, 마커=None):
    s = 마디.get("서식") or {}
    조각들 = []
    for x in 마디.get("속") or []:
        if x.get("줄바꿈"):
            조각들.append({"줄바꿈": True})
        elif x.get("빈자리mm"):
            조각들.append({"빈자리mm": x["빈자리mm"]})
        elif (x.get("글") or "").strip() or x.get("글"):
            조각들.append({"글": x["글"], **글자서식(x, s)})
    if not 조각들 and (마디.get("글") or "").strip():
        조각들 = [{"글": 마디["글"], **글자서식({}, s)}]
    mk = 마디.get("마커")
    return {
        "종류": "문단",
        "마커": 마커 if 마커 is not None else (mk and mk.get("글자")),
        "마커가_글자냐": bool(mk and not mk.get("만든것")),
        "조각": 조각들,
        "문단": 문단서식(s, 마커있나=bool(mk)),
        "역할": 마디.get("역할"), "반": 마디.get("반"), "경로": 마디.get("경로"),
    }


