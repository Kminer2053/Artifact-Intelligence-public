def 옮기기(읽은것, *, 가드=None, 문서이름=None):
    """화면에서 읽은 트리 전체를 명령 목록으로. 미지정 역할·구멍을 같이 돌려준다."""
    명령, 미지정 = [], []
    앞쪽 = None
    쪽 = 읽은것.get("쪽") or {}
    여백 = 쪽.get("여백mm") or [25, 25, 20, 25]
    크기 = 쪽.get("크기mm") or [210, 297]
    # 판면(내용) 폭 — _테두리박스_대상인가() 가 상자가 판면보다 좁은지 잴 때 쓴다.
    # _hwpx_write.붓.__init__ 의 판면폭mm 계산과 같은 식이다(정본을 두 곳에 서로
    # 다르게 두지 않는다).
    판면폭mm = (크기[0] or 210) - (여백[1] or 0) - (여백[3] or 0)
    for 번호, 마디 in enumerate(읽은것["마디"]):
        if 마디.get("쪽") and 앞쪽 is not None and 마디["쪽"] != 앞쪽:
            명령.append({"종류": "쪽나눔"})
        앞쪽 = 마디.get("쪽")
        나온 = _마디명령(마디, 판면폭mm, 미지정)
        # 쪽 안 세로 자리·나란히 칸 자리를 명령에 붙여 둔다 — 아래 _나란히묶기()·
        # _세로배치옮기기() 가 읽는다. 쓰는 쪽(_hwpx_write)은 모르는 키를 안 읽는다.
        # 마디번호 — 이 명령을 낸 마디의 차례. 대조.py 가 화면 마디와 옮긴 명령을
        # data-path 없이도 정확히 짝짓는 열쇠다(경로가 없는 문단도 있다).
        세로 = 마디.get("세로")
        for c in 나온:
            c["마디번호"] = 번호
            if 세로:
                c["세로"] = {**세로, "쪽": 마디.get("쪽")}
            if 마디.get("나란히"):
                c["나란히"] = 마디["나란히"]
        명령.extend(나온)

    _나란히묶기(명령)
    _여백겹치기(명령)
    _띠여백빼기(명령)
    _세로배치옮기기(명령, {i + 1: (x or {}).get("판높이mm")
                          for i, x in enumerate(읽은것.get("쪽정보") or [])})

    문서 = {
        "여백mm": 읽은것["쪽"]["여백mm"],
        "크기mm": 읽은것["쪽"]["크기mm"],
        "제목": 읽은것.get("제목") or "",
        "장르": 읽은것.get("장르"),
        # 쪽마다 화면이 실제로 찍은 쪽번호·숨김 여부 — _hwpx_write.붓 이 이 값과
        # 다음 쪽의 값을 비교해 한글 꼬리말 구역(section)을 새로 열지 정한다
        # (3차 수정, "꼬리말 쪽번호" high 결함. 화면읽기.py 쪽정보 참고).
        "쪽정보": 읽은것.get("쪽정보") or [],
        # 화면을 그대로 못 옮겨 근사한 자리 — 쓰는 쪽이 '알려진 차이'로 알린다(P0-6,
        # 화면읽기 근사목록 · _hwpx_write._근사알리기)
        "근사": 읽은것.get("근사") or [],
    }

    # 가드는 **명령을 만든 뒤**에 건다. 구멍이 있어도 명령은 돌려준다 — 대조기처럼
    # "옮기는 쪽 규칙" 만 빌려 쓰는 곳이 있어서다. 세우는 것은 부르는 쪽 몫이고,
    # HWPX 를 만드는 길(tohwpx)은 `ok` 가 거짓이면 파일을 안 쓴다.
    구멍 = []
    if 가드켬 if 가드 is None else 가드:
        import 카탈로그
        구멍 = 카탈로그.가드읽기().검사(
            읽은것, 문서이름 or (읽은것.get("제목") or "(문서)"))["구멍"]

    return {"ok": not 구멍, "구멍": 구멍,
            "문서": 문서, "명령": 명령, "미지정": 미지정,
            "지면글": 읽은것.get("지면글", "")}
