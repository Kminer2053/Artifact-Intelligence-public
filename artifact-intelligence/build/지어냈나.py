def _경로문자열모으기(node, 나온다, 경로="", 키="", 배열안=False, 표행=False, 그림안=False):
    # 어디(경로)를 '본문' 하나로 뭉개지 않고 실제 키 경로로 남긴다 — 되물음을 읽는 사람이
    # 어느 자리인지 알고, 작성일 자리(배포·보고일·시행일 …, _작성일자리)의 오늘 날짜를
    # 가려낼 수 있게 한다(최종 점검 s5). `키` 는 이 값에 가장 가까운 dict 키(배열 원소는 그 배열의 키).
    # `표행` — 표 rows 배열 안의 dict 행: 열 이름 키가 무엇이든 그 값은 칸 글이다(fixup4 ⑦).
    # `그림안` — "이미지" 키 아래(그림 스펙): _그림메타키 칸은 모으지 않는다.
    if isinstance(node, dict):
        행 = 표행 or (배열안 and 키 in _표칸키)
        for k, v in node.items():
            if k in _메타키_제외 or (그림안 and k in _그림메타키):
                continue
            if k == "이미지" and isinstance(v, str):
                continue          # 문자열 이미지 칸(시행문 관인.이미지)은 파일 경로다
            _경로문자열모으기(v, 나온다, f"{경로}.{k}" if 경로 else str(k), k, False, 행,
                         그림안 or k in ("이미지", "붙임사진"))   # 붙임사진 = 보도자료 끝 사진('26-09-30)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            _경로문자열모으기(v, 나온다, f"{경로}.{i}" if 경로 else str(i), 키, True, 표행, 그림안)
    elif isinstance(node, str):
        s = 민글(node)
        if s:
            나온다.append((경로 or "본문", s))
    elif (키 in _수값키 or 표행 or (배열안 and 키 in _배열수키)
          or (not 배열안 and 키 in _머리스칼라키)):
        s = _수값글(node)
        if s is not None:
            나온다.append((경로 or "본문", s))


def _문서글_1p(doc) -> list[tuple[str, str]]:
    """1p(samples) 옛 스키마 전용 — title/byline/summary/attach/sections/table 만
    본다(그대로 유지, 회귀 없음). doc 에 'genre' 가 없거나 'samples' 일 때 쓴다."""
    나온다 = []
    for k in ("title", "byline", "summary", "attach"):
        if doc.get(k):
            나온다.append((k, 민글(str(doc[k]))))
    for si, s in enumerate(doc.get("sections") or []):
        나온다.append((f"절{si+1} 제목", 민글(s.get("heading"))))
        for ii, it in enumerate(s.get("items") or []):
            나온다.append((f"절{si+1} 항목{ii+1}", 민글(it.get("html"))))
    t = doc.get("table")
    if isinstance(t, dict):
        # 표꼴.정규화 가 그리는 꼴을 그대로 읽는다(fixup4 ⑦, verify3 Q10·Q11) — 목록 아닌 header 는 [hdr],
        # dict 행은 값들, 목록 아닌 행은 [행]. 예전엔 dict 행의 열 이름(키)만 읽어 값 29 가 PDF 까지 나갔다.
        hdr = t.get("header")
        for c in (hdr if isinstance(hdr, list) else ([] if hdr is None else [hdr])):
            나온다.append(("표 머리", 민글(str(c))))
        for r in (t.get("rows") or []):
            칸들 = r if isinstance(r, list) else (list(r.values()) if isinstance(r, dict) else [r])
            for c in 칸들:
                나온다.append(("표 칸", 민글(str(c))))
    return [(a, b) for a, b in 나온다 if b]


def 문서글(doc) -> list[tuple[str, str]]:
    """(어디, 글) 목록. 1p(samples) 는 스키마별 추출, 그 밖 장르는 doc 전체를
    걷는 일반 경로(메타 키만 제외). 자리표시 토큰(OOO·YYYY·00. 00. …)은 가린다(fixup4 ⑥ — 위 자리표시 꼴)."""
    genre = doc.get("genre") if isinstance(doc, dict) else None
    if genre in (None, "samples"):
        나온다 = _문서글_1p(doc)
    else:
        나온다 = []
        _경로문자열모으기(doc, 나온다)
    나온다 = [(a, 자리표시가림(b).strip()) for a, b in 나온다]
    return [(a, b) for a, b in 나온다 if b]


