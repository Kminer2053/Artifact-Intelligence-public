_바이라인_날짜_YY_RX = re.compile(r"'(\d{2})\.\s*(\d{1,2})\.\s*(\d{1,2})\.?")
_바이라인_날짜_YYYY_RX = re.compile(r"(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\.?")


def _바이라인_날짜_지우기(글, 날짜):
    """자리 안의 날짜 표기가 **주어진 날짜**와 같으면 지운다(오늘이 아니라 임의 기준일).

    재기() 는 이 아래 얇은 래퍼(_바이라인_오늘날짜_지우기)로 늘 '오늘'을 기준으로 쓴다
    (하위호환, 행동 변화 없음). 검토하기() 는 이 함수를 doc 자신의 생성 시각(_수정시각)
    기준으로 불러 — "오늘 다시 재도" 날짜가 바뀌어 골든이 깨지는 일이 없게 한다(r9,
    아래 _작성일자_새월표현 참고)."""
    def _yy(m):
        if (int(m.group(1)), int(m.group(2)), int(m.group(3))) == (날짜.year % 100, 날짜.month, 날짜.day):
            return " "
        return m.group(0)

    def _yyyy(m):
        if (int(m.group(1)), int(m.group(2)), int(m.group(3))) == (날짜.year, 날짜.month, 날짜.day):
            return " "
        return m.group(0)

    글 = _바이라인_날짜_YY_RX.sub(_yy, 글)
    글 = _바이라인_날짜_YYYY_RX.sub(_yyyy, 글)
    return 글


def _바이라인_오늘날짜_지우기(글):
    return _바이라인_날짜_지우기(글, _dt.date.today())


