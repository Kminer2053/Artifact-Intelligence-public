#!/usr/bin/env python3
"""초안이 **원문에 없는 사실을 지어냈는지** 잰다.

    python3 build/지어냈나.py <원문.txt> <문서키>

test/ 에서 시험을 마치고 2026-08-08 build/ 로 승격했다(WP-S6, 출시계획 3-5 확정
2026-08-07). 제품 흐름에서는 api.py 의 `지어냈나` 작업이 이 모듈의 `재기`·`물음말`
을 부른다 — 초안(3층 JSON)이 등록된 직후, 사용자가 준 자료 원문과 대조한다.

왜 필요한가 — 파일을 던져 초안을 짓게 하면 제일 무서운 것이 **그럴듯한 거짓**이다.
빠진 것은 눈에 띄지만 더한 것은 안 띈다. 사람이 읽어서는 못 잡는다 —
원문 1,900자와 초안을 한 글자씩 맞대볼 수 없기 때문이다.

무엇을 재는가 — **수치와 고유명사**만 본다. 문장은 다시 쓰는 것이 일이지만,
숫자와 이름은 **원문에 없으면 지어낸 것**이다.
  · 수치: 12, 1만, 5천, 2.4억, 25%, 6/11, 7. 17. 같은 것 — 원문에 **독립된 수
    토큰**으로 있거나 정당한 표기 변환(억/만 확장·연도 약칭)일 때만 통과.
  · 고유명사: 한글 2자 이상 덩어리 **그리고** 라틴 고유명사(Microsoft 처럼 대문자로
    시작하는 다글자 낱말·NVIDIA·KEPCO 처럼 전부 대문자인 약어) 중 원문에 없는 것.
    단위·굳은 약어(AI·GB·MWh…)는 이름으로 안 본다(정본 오탐 0 — _라틴제외 주석).

한계(적어 둔다):
  · 원문을 요약·환언한 표현은 못 가린다 — 이 자는 **더한 것**만 본다.
  · 표기가 달라진 것(6/11 → 6월 11일)은 지어낸 것이 아니다. 수 토큰으로 견준다.
  · 소문자로만 쓴 영어(iphone)·숫자 섞인 토큰(B2B)은 라틴 감지 밖이다 — 우연 일치를
    줄이려 좁게 잡았다(되묻기라 놓쳐도 하드블록이 안 풀린다).
"""
from __future__ import annotations

import html as htmlmod
import json
import re
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent
ROOT = 여기.parent


def 민글(s):
    return re.sub(r"\s+", " ", htmlmod.unescape(re.sub(r"<[^>]+>", "", s or ""))).strip()


def 문서글(doc) -> list[tuple[str, str]]:
    """(어디, 글) 목록."""
    나온다 = []
    for k in ("title", "byline", "summary", "attach"):
        if doc.get(k):
            나온다.append((k, 민글(str(doc[k]))))
    for si, s in enumerate(doc.get("sections") or []):
        나온다.append((f"절{si+1} 제목", 민글(s.get("heading"))))
        for ii, it in enumerate(s.get("items") or []):
            나온다.append((f"절{si+1} 항목{ii+1}", 민글(it.get("html"))))
    t = doc.get("table")
    if t:
        for c in (t.get("header") or []):
            나온다.append(("표 머리", 민글(str(c))))
        for r in (t.get("rows") or []):
            for c in r:
                나온다.append(("표 칸", 민글(str(c))))
    return [(a, b) for a, b in 나온다 if b]


_숫자 = re.compile(r"\d[\d,.]*")
# 한글 덩어리 — 조사를 떼려고 뒤에서 흔한 조사를 깎는다
_조사 = re.compile(r"(은|는|이|가|을|를|와|과|의|에|에서|으로|로|도|만|까지|부터|및|등)$")
_한글덩어리 = re.compile(r"[가-힣]{2,}")

# 라틴(영문) 덩어리 — 자음·모음 섞인 순수 알파벳 낱말만 본다. 숫자 섞인 토큰
# (B2B·3M)은 우연 일치가 늘어 뺀다(고유명사 감지는 되묻기라 넓힐 필요가 없다).
_라틴덩어리 = re.compile(r"[A-Za-z]{2,}")

# 이름이 아니라 **단위·흔한 약어**인 것들 — 정본 공공문서에 흔히 박히는 낱말이라
# 이름으로 오인하면 되묻기가 과하게 울린다(정본 실물 오탐 0 이 하드 기준).
#
# 근거(실측 2026-08-09, build/samples 38건·5등록부): 문서에 실제로 든 대문자 라틴
# 토큰은 AI 13·IP 9·PC 4·B2 2·LED 2·CSAP 2·GB 2·BEMS 1·SSD 1·MWh 1 뿐이었다.
# 이 중 단위(GB·MWh)와 외래어처럼 굳은 기술 약어(AI·IP·PC·LED·SSD)를 뺀다 —
# 여기에 표준 물리단위와 그 형제 약어를 더해 목록을 짓는다. CSAP·BEMS 같은 진짜
# 시스템·기관 약어는 굳이 안 뺀다: ① 은 하드블록이 아니라 되묻기라 "이거 실제로
# 있는 겁니까"를 물어도 되는 것들이다(정본 오탐은 자기 원문 대조로 0 — 아래 재기).
# 대문자로 정규화해 담고, 대조도 대문자로 한다(kW·MWh 처럼 대소문자 섞인 단위까지 잡게).
_라틴제외 = {
    # 외래어처럼 쓰이는 기술·업무 약어
    "AI", "IT", "IP", "PC", "OS", "DB", "API", "URL", "URI", "PDF", "HTML",
    "CSS", "JS", "XML", "JSON", "USB", "CPU", "GPU", "RAM", "ROM", "SSD",
    "HDD", "LED", "LCD", "OLED", "TV", "CCTV", "GPS", "QR", "VPN", "DNS",
    "HTTP", "HTTPS", "AR", "VR", "XR", "IOT", "ICT", "GIS", "UI", "UX",
    "CD", "DVD", "SW", "HW", "FAQ", "OK", "NO",
    # 물리·계량 단위(대문자 정규화 — kW→KW, MWh→MWH 등)
    "GB", "MB", "KB", "TB", "PB", "WH", "KWH", "MWH", "GWH", "TWH",
    "KW", "MW", "GW", "TW", "KM", "CM", "MM", "NM", "KG", "MG", "TON",
    "HZ", "KHZ", "MHZ", "GHZ", "DB", "LX", "LM", "KL", "ML", "CC", "B2",
}


def 라틴이름들(t):
    """지어냈는지 볼 만한 **라틴 고유명사**만 고른다.

    대문자로 시작하는 다글자 낱말(Microsoft)·전부 대문자 약어(NVIDIA·KEPCO)를 본다.
    소문자로만 된 흔한 영어 낱말(and·the…)은 애초에 대문자 시작이 아니라 안 걸리고,
    단위·굳은 약어는 _라틴제외 로 뺀다(정본 오탐 0). 이름 감지의 존재 이유가
    '그럴듯한 외국 기업·기관명 지어내기'를 잡는 것인데 [가-힣] 만 보면 표본 밖이었다.
    """
    나온다 = set()
    for m in _라틴덩어리.finditer(t):
        w = m.group(0)
        if not w[0].isupper():                 # 대문자로 시작하는 것만(고유명사·약어)
            continue
        if w.upper() in _라틴제외:
            continue
        나온다.add(w)
    return 나온다


def 숫자들(t):
    """표기 차이를 견디려고 **숫자만** 뽑는다(쉼표·마침표 제거)."""
    나온다 = set()
    for m in _숫자.finditer(t):
        v = m.group(0).strip(".,")
        if v:
            나온다.add(v.replace(",", ""))
    return 나온다


# 정당한 표기 차이를 **값**으로 견주기 위한 배수 — 초안이 380000000, 원문이 3.8억
# (또는 그 반대)일 때 둘을 같은 수로 본다(적대리뷰 ②). 부분열이 아니라 값을 견주므로
# 무관한 3.8억의 '38' 이 지어낸 38% 로 새지 않는다. 배수는 한글 수 단위만 — 좁게 잡아
# 우연 일치를 막는다(넓히면 원리가 흐려진다).
_배수 = {"조": 10**12, "억": 10**8, "만": 10**4, "천": 10**3}
_수단위 = re.compile(r"(\d[\d,.]*)\s*([조억만천]?)")


def 수값들(t):
    """(원시숫자, 크기값) 목록 — 크기값은 바로 뒤 한글 수 단위(조·억·만·천) 배수를 곱한 것.

    '3.8억' → ('3.8', 380000000.0) · '380,000,000' → ('380000000', 380000000.0).
    두 크기값이 같으면 같은 수로 본다(수단위 확장 관용). 단위가 없으면 배수 1.
    """
    나온다 = []
    for m in _수단위.finditer(t):
        raw = m.group(1).strip(".,").replace(",", "")
        if not raw:
            continue
        try:
            base = float(raw)
        except ValueError:
            continue
        나온다.append((raw, base * _배수.get(m.group(2), 1)))
    return 나온다


def _값같은가(v, 값집합):
    """크기값 v 가 원문 크기값 중 하나와 사실상 같은가(부동소수 오차 흡수)."""
    for x in 값집합:
        if abs(v - x) <= 1e-3 + 1e-9 * abs(x):
            return True
    return False


_연도4 = re.compile(r"20\d{2}")
_연도2 = re.compile(r"\d{2}")


def _연도표기같은가(d, 토큰집합):
    """연도 약칭 관용 — '26 ↔ 2026. 2000~2099 만 본다(넓히면 우연 일치가 는다).

    초안 '2026' 은 원문에 '26' 이 독립 수로 있으면 통과, 초안 '26' 은 '2026' 이 있으면 통과.
    """
    if _연도4.fullmatch(d):
        return d[2:] in 토큰집합
    if _연도2.fullmatch(d):
        return ("20" + d) in 토큰집합
    return False


# 이름이 아니라 **풀어 쓴 말**인 것들 — 용언 활용형은 지어낸 사실이 아니다.
# ('확인할', '정리하여', '맞는지', '대조하여' … 원문을 요약하면 당연히 나온다)
_용언끝 = re.compile(r"(하여|하고|하는|한다|할|함|했|하며|되어|되는|된다|될|됨|"
                    r"있는|없는|같은|맞는|맞는지|는지|려면|으로써|로써|"
                    r"이며|이고|이나|거나|면서|아야|어야|여야|"
                    r"[가-힣]*(?:하다|되다|이다))$")


def 이름들(t):
    """지어냈는지 볼 만한 **이름**만 고른다 — 한글 고유명사 + 라틴 고유명사.

    한글은 용언 활용형을 빼고, 라틴은 단위·굳은 약어를 뺀다(각 함수 주석 참고).
    원문·초안 양쪽을 같은 함수로 뽑으므로, 원문에 있는 이름은 초안에서도 그대로 걸러진다.
    """
    나온다 = set()
    for m in _한글덩어리.finditer(t):
        w = _조사.sub("", m.group(0))
        if len(w) < 2 or _용언끝.search(w):
            continue
        나온다.add(w)
    나온다 |= 라틴이름들(t)
    return 나온다


# 원문에 없어도 지어낸 것이 **아닌** 말들 — 정본이 주는 것이다.
#  · 절 제목: 12유형 표준시퀀스에서 온다(원문의 절 이름과 다른 게 정상이다).
#  · 요약 종결: 규칙이 '보고드림/요청드림/요청함' 중 하나를 강제한다.
def _정본말(시퀀스=()):
    # 절 제목은 **판정된 이 유형의 시퀀스**에서 온다 — 판정(detect)·조립(compose) 때 이미
    # 확보한 이 문서용 시퀀스를 호출자가 넘긴다(온톨로지 통째를 로컬에서 다시 읽지 않는다,
    # 2026-08-13). 시퀀스는 이 문서 유형 하나뿐이라 완성 프롬프트에 이미 실렸던 것과 같은
    # 노출 수준이다. doc 의 heading 을 그대로 신뢰하면 **지어낸 절 제목까지 통과**하므로 안 쓴다.
    말 = {"보고드림", "요청드림", "요청함"}
    for 시 in (시퀀스 or []):
        말.add(시)                          # '주요현황·동향' 은 한 이름이다
        for 조각 in re.split(r"[·/ ]", str(시)):
            if len(조각) >= 2:
                말.add(조각)
    return 말


def 재기(원문: str, doc: dict, 시퀀스=()):
    원숫자 = 숫자들(원문)                    # 원문의 **독립 수 토큰** 집합(부분열 아님)
    원수값 = {v for _, v in 수값들(원문)}     # 크기값 집합(억/만 확장 관용용)
    원이름 = 이름들(원문)
    원민 = re.sub(r"\s+", "", 원문)
    정본말 = _정본말(시퀀스)

    더한숫자, 더한이름 = [], []
    for 어디, 글 in 문서글(doc):
        본것 = set()
        for v, 값 in 수값들(글):
            if v in 본것:
                continue
            본것.add(v)
            # ① 원문에 **독립된 수 토큰**으로 있으면 통과. (예전엔 원문 숫자를 한 줄로
            #    이어 붙여 부분열을 봤다 — 무관한 3.8억의 '38' 에서 온 지어낸 38% 가
            #    통과했다. 경계 있는 토큰 대조로 그 새는 자리를 막는다. 적대리뷰 ②.)
            if v in 원숫자:
                continue
            # ② 정당한 표기 차이 — 수단위 확장: 크기값이 같은 원문 수가 있으면 통과
            #    (초안 380000000 ↔ 원문 3.8억, 또는 그 반대). '값'을 견주므로 관용은
            #    **같은 수**에만 열리고 부분열엔 안 열린다.
            if _값같은가(값, 원수값):
                continue
            # ③ 정당한 표기 차이 — 연도 약칭: '26 ↔ 2026.
            if _연도표기같은가(v, 원숫자):
                continue
            더한숫자.append((어디, v, 글[:40]))
        if 어디.endswith("제목") and 어디.startswith("절"):
            # 절 제목은 정본 시퀀스에서 오는 게 보통이라 원문에 없어도 정상이다.
            # 처음에는 "정본 시퀀스에 없으면 지어낸 것"으로 봤는데, 정본 문서 실측
            # (2026-08-08, 5장르 38건)에서 6건·17개 절 이름이 시퀀스 밖이었다 —
            # '검토배경·쟁점'·'대안비교' 같은 병합·변형 제목이 정상 문서에 흔하다.
            # 오탐 나는 게이트는 곧 꺼지므로(구현계획.md §0), 정본에도 없고
            # **자료에도 안 닿는** 절 이름만 묻는다 — 그 실측 뒤 오탐 0.
            if 글 in 정본말:
                continue
            낯선 = [w for w in 이름들(글)
                   if not (w in 원이름 or w in 원민 or w in 정본말
                           or any(w in x for x in 원이름))]
            if 낯선:
                더한이름.append((어디, 글, "정본 시퀀스에도 자료에도 없는 절 이름"))
            continue
        for w in 이름들(글):
            if w in 원이름 or w in 원민 or w in 정본말:
                continue
            # 원문 어딘가에 **부분으로** 들어 있으면 조사·활용 차이다(사와 ← IP사와의)
            if any(w in x for x in 원이름):
                continue
            더한이름.append((어디, w, 글[:40]))
    return 더한숫자, 더한이름


def 물음말(더한숫자, 더한이름):
    """사람에게 보일 되묻는 말 — **지우라고 명령하지 않고 묻는다**(어긋남.물음말과
    같은 결). 원문에 없다 ≠ 반드시 거짓이다: 사용자가 머릿속으로 아는 사실일 수
    있다. 그래서 게이트는 서되, 판단은 사람이 한다 — 맞다고 답하면 그대로 가고,
    아니면 고친다. 조용히 통과시키는 것만이 금지다(구현계획.md 규칙 3)."""
    if not 더한숫자 and not 더한이름:
        return ""
    줄 = ["초안에 **주신 자료에 없는** 숫자·이름이 있습니다. 지어낸 것은 아닌지 봐 주십시오.", ""]
