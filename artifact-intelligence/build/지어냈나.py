def 물음말(더한숫자, 더한이름):
    if not 더한숫자 and not 더한이름:
        return ""
    줄 = ["초안에 **주신 자료에 없는** 숫자·이름이 있습니다. 지어낸 것은 아닌지 봐 주십시오.", ""]
    for 어디, v, 글 in 더한숫자[:20]:
        줄.append(f"· {어디}의 「{v}」 — 자료 어디에서 온 숫자입니까?   (…{글}…)")
    for 어디, w, 글 in 더한이름[:20]:
        if 글 == "정본 시퀀스에도 자료에도 없는 절 이름":
            줄.append(f"· {어디}의 「{w}」 — 정본 목차에도 주신 자료에도 없는 절 이름입니다. 의도하신 것입니까?")
            continue
        줄.append(f"· {어디}의 「{w}」 — 자료에 없는 이름입니다. 실제로 있는 것입니까?   (…{글}…)")
    남은 = max(0, len(더한숫자) - 20) + max(0, len(더한이름) - 20)
    if 남은:
        줄.append(f"· … 외 {남은}곳")
    줄.append("")
    줄.append("맞는 값이면 그렇다고 알려 주십시오 — 그대로 씁니다. 아니면 고치기에서 지우거나 바로잡아 주십시오.")
    return "\n".join(줄)


