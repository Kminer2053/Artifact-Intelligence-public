def _자료마디들(원문, 낱말):
    return [x for x in _자료마디_RX.findall(str(원문 or "")) if 낱말 in x]


def _앞목적어(글, 끝):
    """초안에서 행위 낱말 바로 앞 낱말(조사 뗌) — 자료 마디를 좁히는 데 쓴다."""
    m = re.search(r"([가-힣]{1,})\s$", 글[:끝])
    if not m:
        return ""
    w = _목적어조사_RX.sub("", m.group(1))
    return w if len(w) >= 1 else ""


def _술어강도걸림(어디, 글, 원문):
    if not re.match(r"^본문\.\d+\.text$", str(어디)):
        return None
    원문 = str(원문 or "")
    for m in _금지술어_RX.finditer(글):
        v = next(x for x in m.groups() if x)
        문장앞 = re.split(r"[.。]", 글[:m.start()])[-1]
        if _조건금지_RX.search(문장앞):
            continue
        마디 = _자료마디들(원문, v)
        # reg12 fixup(verify.md 변이 U1b·D6) — '열람은 제한한다'·'대출은 제한한다'처럼 은·는·이·가 가 붙은 제한도 같은 제한이다
        약 = [x for x in 마디 if re.search(re.escape(v) + r"\s?(?:을|를|의|은|는|이|가)?\s?제한", x)]
        강 = [x for x in 마디 if re.search(r"금지|불가|할\s?수\s?없|못\s?한|아니\s?된|안\s?된", x)]
        if 약 and not 강:
            # reg12('26-09-30 판정 B-H4) — 교정 문구도 11차 ②(강도는 양쪽 모두 자료대로)를 따른다: 옛 문구 '…제한할 수
            # 있다'처럼 쓴다'는 되시도 때 모델에게 재량으로 내리라고 시켰다(12차 심사 '제한' 재량화 지적 24/24 와 같은 쪽).
            return {"어디": 어디, "값": 글[:60], "곁": m.group(0), "종류": "술어강도",
                    "설명": f"자료는 '{v} 제한'인데 조문은 '{m.group(0)}'(금지)로 올렸다 — 자료의 술어 강도대로 권한자를 "
                           f"주어로 세워 '○○장은 …에 대하여 {v}을(를) 제한한다'처럼 쓴다('할 수 없다'로 올리지도 '제한할 수 "
                           f"있다'로 내리지도 않는다. 대상자를 주어로 '…는 {v}을(를) 제한한다'로 쓰면 제한하는 쪽이 뒤바뀐다). "
                           "금지가 맞는지는 사용자에게 확인한다"}
    for m in _의무술어_RX.finditer(글):
        v = m.group(1)
        if v in _약한동사:
            continue
        목적어 = _앞목적어(글, m.start())
        자리들 = []           # (마디, 약한가)
        for 마디 in _자료마디들(원문, v):
            for p in re.finditer(re.escape(v), 마디):
                뒤 = 마디[p.end():p.end() + 8]
                약 = bool(_약한붙음_RX.match(뒤)) or (v in _권고말 and not re.match(r"\s?(?:하여야|해야)", 뒤))
                자리들.append((마디, 약))
        if 목적어 and any(목적어 in x for x, _약 in 자리들):
            자리들 = [(x, 약) for x, 약 in 자리들 if 목적어 in x]
        if 자리들 and all(약 for _x, 약 in 자리들) and not any(
                re.search(r"하여야|해야|의무|반드시|필수", x) for x, _약 in 자리들):
            return {"어디": 어디, "값": 글[:60], "곁": m.group(0), "종류": "술어강도",
                    "설명": f"자료는 '{v}'을(를) 권고·재량으로 적었는데 조문은 '{m.group(0)}'(의무)로 올렸다 — "
                           f"자료의 술어 강도대로 쓴다(자료가 '할 수 있음'이면 '{v}할 수 있다', '권고'면 '{v}을(를) 권고할 수 "
                           "있다'). 의무가 맞는지는 사용자에게 확인한다"}
    return _술어내림걸림(어디, 글, 원문)


