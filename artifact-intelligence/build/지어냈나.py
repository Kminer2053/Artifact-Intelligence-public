_범위뒤날_RX = re.compile(r"(?<![\d.])(\d{1,2})\s*\.\s*(\d{1,2})\s*\.\s*([~∼–])\s*(\d{1,2})\s*\.(?!\s*\d)")


def _원날짜조각(원문):
    t = str(원문 or "")
    연도 = {int(y) for y in re.findall(r"(?<!\d)(20\d{2})(?!\d)", t)}
    연도 |= {2000 + int(y) for y in re.findall(r"[’'‘](\d{2})(?!\d)", t)}
    월일 = set()
    for m in _원월일_RX.finditer(t):
        a, b = int(m.group(1)), int(m.group(2))
        if 1 <= a <= 12 and 1 <= b <= 31:
            월일.add((a, b))
    for m in _ISO날짜_RX.finditer(t):                  # 자료의 ISO '2026-05-15'도 (월, 일)로 읽는다(F3 2차)
        a, b = int(m.group(2)), int(m.group(3))
        if 1 <= a <= 12 and 1 <= b <= 31:
            월일.add((a, b))
    return 연도, _원문월번호들(t), 월일


def _집날짜가림(글, 조각):
    연도, 월, 월일 = 조각
    if not (연도 or 월 or 월일):
        return 글

    def _풀(mo):
        y, m, d = 2000 + int(mo.group(1)), int(mo.group(2)), int(mo.group(3))
        return " " * len(mo.group(0)) if y in 연도 and (m, d) in 월일 else mo.group(0)

    def _연월(mo):
        y, m = 2000 + int(mo.group(1)), int(mo.group(2))
        return " " * len(mo.group(0)) if y in 연도 and m in 월 else mo.group(0)

    def _월일(mo):
        return " " * len(mo.group(0)) if (int(mo.group(1)), int(mo.group(2))) in 월일 else mo.group(0)

    def _연월범위(mo):
        y = int(mo.group(1)[-2:]) + 2000 if not mo.group(1).isdigit() else int(mo.group(1))
        return " " * len(mo.group(0)) if y in 연도 and int(mo.group(2)) in 월 and int(mo.group(3)) in 월 else mo.group(0)

    def _월범위(mo):
        return " " * len(mo.group(0)) if int(mo.group(1)) in 월 and int(mo.group(2)) in 월 else mo.group(0)
    # F3('26-09-30) — 자료의 연·월을 다른 꼴로 옮긴 것: '2026.5'·'2026. 5.'(자료 '2026년 5월'), '2026. 1.~6.'·''26. 1.~6.'
    # (자료 ''26. 1. 1.~6. 30.'), '3~5월'(자료 '3월 2일~5월 31일'). 연도·달이 자료에 있을 때만 가린다(달은 자료 쪽 기간 사이
    # 달까지 — _원문월번호들). '2026.5억'·'2026.5%'처럼 뒤에 배율·단위가 붙은 소수는 날짜가 아니라 가리지 않는다.
    def _iso(mo):
        y, m, d = int(mo.group(1)), int(mo.group(2)), int(mo.group(3))
        return " " * len(mo.group(0)) if y in 연도 and (m, d) in 월일 else mo.group(0)

    def _범위뒤날(mo):
        m, d, d2 = int(mo.group(1)), int(mo.group(2)), int(mo.group(4))
        if (m, d) in 월일 and (m, d2) in 월일:
            return " " * len(mo.group(0))
        return mo.group(0)
    글 = _연월범위_RX.sub(_연월범위, 글)
    # 2차 — 달 범위('2026. 1~3월')를 연.월보다 먼저 가린다(연.월이 '2026. 1'을 먼저 먹어 '~3월'의 3이 남았다)
    글 = _월범위수_RX.sub(_월범위, 글)
    글 = _연점월_RX.sub(_연월, 글)
    글 = _ISO날짜_RX.sub(_iso, 글)
    글 = _범위뒤날_RX.sub(_범위뒤날, 글)
    글 = _집풀날짜_RX.sub(_풀, 글)
    글 = _집연월_RX.sub(_연월, 글)
    글 = _물결월일_RX.sub(_월일, 글)
    # 본문 날짜 붙여쓰기 '12.1.'(표기 규칙 "'26.7.23." 의 연도 뺀 꼴) — 자료 '12. 1.'과 같은 날이면 수 12.1 로 읽지 않는다
    # (bench14 A s5). 자료에 없는 날('12.3.')은 그대로 둬 숫자 대조가 계속 본다. 끝 점이 있어야 한다('12.1%'는 수).
    return _붙임월일_RX.sub(_월일, 글)


# 초안 쪽 칸 나눔 단위(fixup8 K4c, verify7 B2″) — 슬라이드 v2 는 새문서가 등록 전에 '2억 원'을 값 '2'·단위 '억 원'으로
