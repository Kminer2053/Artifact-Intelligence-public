def _분수가려내기(글, 원숫자, 원수값, 원분수=None, 과반=False):
    """(분수를 지운 글, 값이 원문과 안 맞는 분수 글 목록). 지운 자리는 공백 — 분수 속 숫자가
    다시 낱낱으로 대조되지 않게 한다(분자 글자 일치로 새는 길을 막는다).
    원분수는 _원문분수값들() 의 비율 집합(퍼센트는 '%'·'퍼센트'가 붙은 수만), 과반은 원문에 '과반수'가 있는가."""
    틀림 = []
    원분수 = 원분수 or set()

    def _가려(m):
        분모, 분자 = _분수값(m)
        if not 분모:
            return m.group(0)
        분모글 = re.sub(r"[\s,]", "", m.group(1)).replace("천", "000").replace("만", "0000")
        맞음 = (_값같은가(분자 / 분모 * 100, 원수값)
               or _값같은가(분자 / 분모, {x for x in 원수값 if x >= 0.01})
               or (m.group(2) in 원숫자 and 분모글 in 원숫자))
        if not 맞음:
            틀림.append(re.sub(r"\s+", " ", m.group(0)))
        return " "

    def _일반(m):
        분모, 분자 = int(m.group(1)), int(m.group(2))
        if not 분모:
            return m.group(0)
        v = 분자 / 분모
        if _값같은가(v, 원분수):
            return " "
        # '과반수' ↔ '2분의 1 초과'(을 초과하는)만 같은 값이다 — '2분의 1 이상'은 정족수가 다르다
        if 과반 and 분모 == 2 * 분자 and re.match(r"\s?(?:을|를)?\s?초과", m.string[m.end():]):
            return " "
        return m.group(0)
    return _일반분수_RX.sub(_일반, _분수_RX.sub(_가려, 글)), 틀림


_산출식_RX = re.compile(r"[^0-9.+\-*/()]")
_장경로_RX = re.compile(r"^장\.(\d+)\.")


def _산출식계산(식):
    """'(42−26)÷42' 같은 산출 식을 사칙연산으로만 푼다(ast — 이름·호출은 받지 않는다). 못 풀면 None."""
    import ast
    import operator as _op
    글 = str(식 or "").replace("−", "-").replace("–", "-").replace("×", "*").replace("÷", "/").replace(",", "")
    글 = _산출식_RX.sub("", 글)
    연산 = {ast.Add: _op.add, ast.Sub: _op.sub, ast.Mult: _op.mul, ast.Div: _op.truediv}

    def _풀기(n):
        if isinstance(n, ast.Expression):
            return _풀기(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)):
            return float(n.value)
        if isinstance(n, ast.BinOp) and type(n.op) in 연산:
            return 연산[type(n.op)](_풀기(n.left), _풀기(n.right))
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return -_풀기(n.operand)
        raise ValueError("산출 식 밖의 꼴")
    try:
        return _풀기(ast.parse(글, mode="eval")) if 글 else None
    except Exception:
        return None


def _슬라이드산출허용(doc, 원숫자, 원수값):
    """슬라이드 v2 의 장별 '산출' 등록(과정메모_v2 — {값: 화면 글, 식})을 읽어, **식의 모든 수가
    자료에 있고 식을 풀면 값과 맞는** 산출 값만 그 장 안에서 통과시킨다('26-09-28 v2 통합 E2E:
    38−21=17명·4.5−3.9=0.6점처럼 규칙대로 등록한 차이값이 지어냄으로 되물어지던 것). 식이 없거나,
    식의 수가 자료에 없거나, 계산이 안 맞으면 통과시키지 않는다(등록만으로 새 수를 들일 수 없게).
    돌려주는 것: {장 번호: {숫자 글, …}}."""
    허용 = {}
    if not (isinstance(doc, dict) and doc.get("판형") == "v2" and isinstance(doc.get("장"), list)):
        return 허용
    for 번호, 장 in enumerate(doc["장"]):
        for 산 in ((장 or {}).get("산출") or []) if isinstance(장, dict) else []:
            if not isinstance(산, dict):
                continue
            값글, 식 = str(산.get("값") or ""), str(산.get("식") or "")
            식수 = 숫자들(식)
            # 백분율 식의 상수 100(나머지 몫을 100 에서 빼는 식, 비율에 100 을 곱하는 식)은 자료 수가 아니라 셈의 상수다 — 값이 %일 때만 받는다
            # (round3 적대 검토 L04: 게이트가 권한 대로 산출[]에 등록해도 식의 100 을 자료에서 찾아 막혔다)
            백분 = "%" in 값글 or "%" in 식
            if not 식수 or not all(x in 원숫자 or _값같은가(float(x), 원수값) or (백분 and x == "100")
                                  for x in 식수 if x.replace(".", "", 1).isdigit()):
                continue
            결과 = _산출식계산(식)
            값들 = [raw for raw, _ in 수값들(값글)]
            if 결과 is None or not 값들:
                continue
            대상 = float(값들[0])
            자리 = len(값들[0].split(".")[1]) if "." in 값들[0] else 0
            오차 = 0.5 * 10 ** (-자리) + 1e-9
            if not any(abs(abs(후보) - 대상) <= 오차 for 후보 in (결과, 결과 * 100)):
                continue
            허용.setdefault(번호, set()).update(값들)
    return 허용


