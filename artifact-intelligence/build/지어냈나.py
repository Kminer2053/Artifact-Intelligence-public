#   · 끝 낱말이 문서 종류가 아니면(기관·부서 이름뿐인 출처 '○○공사 사회공헌처') 이 검사 밖이다 — 그 이름은 재기가 본다.
#   · 끝의 '참고·재구성·가공·발췌·기준·인용·종합·정리'와 연도·날짜 토막은 떼고 끝 낱말을 찾는다. '○○'만인 앞 이름은 빈칸이다.
# 자료 전체에 '조사'·'통계' 같은 낱말 하나만 있어도 검사를 끄는 길은 두지 않는다(슬라이드 4차 C01·C02·C07b·C09 샘).
_출처_끝낱말 = tuple(sorted((
    "보고서", "보도자료", "요청서", "계획서", "자료집", "결과보고", "통계", "조사", "결과", "계획", "자료", "현황", "평가",
    "점검", "실적", "분석", "대장", "기록", "설문", "집계", "공시", "백서", "명부", "목록", "결산", "일지", "보고", "지표",
    "연보", "편람", "공고", "공지", "안내", "지침", "데이터", "명세", "내역", "추이", "동향", "전망", "진단", "문서", "서류"),
    key=len, reverse=True))
_출처_꼬리말 = frozenset({"참고", "재구성", "가공", "발췌", "기준", "인용", "종합", "정리", "등"})
_출처_덧말 = frozenset({"자료", "문서", "서류", "데이터"})
_출처_날짜토막_RX = re.compile(r"^[\d'’‘.~∼\-–]+(?:년|월|일|분기|반기)?$|^(?:상|하)반기$|^\d+분기$")
_출처_구절끝_RX = re.compile(r"(?<!\d)[.。](?!\d)|\n|;|다\s")
_출처_짧은구절끝_RX = re.compile(r"(?<!\d)[.。](?!\d)|\n|;|다\s|[,，、]")


def _출처끝낱말(토막):
    """토막(띄어쓰기 없는 낱말 하나)의 끝이 문서 종류 낱말이면 (앞 글, 끝 낱말), 아니면 None. '계획안'은 '계획'으로 본다."""
    w = 토막[:-1] if 토막.endswith("안") and len(토막) > 2 else 토막
    for k in _출처_끝낱말:
        if w.endswith(k):
            return w[:-len(k)], k
    return None


def _띄어도(s):
    """글자 사이 띄어쓰기를 따지지 않는 정규식 조각('고객만족도' ↔ 자료 '고객 만족도')."""
    return r"\s*".join(re.escape(ch) for ch in s)


# 2차('26-09-30 fixup, r2/fabq verify_precision §1-b) — '함께'를 띄어쓰기만 허용한 붙어 있음으로 읽어, 자료가 조사·용언꼴·낱말 하나를
# 끼워 적은 맞는 출처가 새로 걸렸다(자료 '민원 내역을 분석한 결과' → '민원 내역 분석', 'ESG 경영 백서' → 'ESG 백서', '민원 처리
# 대장' → '민원대장', 'VOC 분석(고객지원처, 2025)' → '고객지원처 분석'). 앞 이름 뒤에 조사 하나와 낱말 하나(8자 안, 같은 줄)까지
# 끼워도, 끝 낱말 바로 뒤 괄호 안에 앞 이름이 있어도 함께로 본다. 앞 이름 머리의 라틴·붙임표('e-나라')는 떼고도 본다.
_출처_사이_RX = r"[ \t]*(?:을|를|의|에|이|가|은|는|에서|으로|로)?[ \t]*(?:[가-힣A-Za-z0-9·]{1,8}[ \t]*)?"


def _기관약칭풀이(w, 원문):
    """기관 약칭('행안부' ↔ 자료 '행정안전부', '국토부' ↔ '국토교통부') — w 가 자료에 그대로 없고 기관 접미로 끝나면, 첫 글자와
    기관 접미가 같고 w 의 글자가 차례대로 든 더 긴 자료 낱말들."""
    접미 = _매치된_접미(w, _기관접미_긴순)
    if not 접미 or w in re.sub(r"\s+", "", str(원문 or "")):
        return []
    꼴 = ".*?".join(re.escape(ch) for ch in w)
    return [x for x in set(re.findall(r"[가-힣]{3,12}", str(원문 or "")))
            if x.endswith(접미) and x[0] == w[0] and len(x) > len(w) and re.fullmatch(꼴, x)]


def _출처함께있나(앞, 끝, 원문):
    앞들 = [앞]
    라 = re.sub(r"^[A-Za-z0-9]+[-‐–]?", "", 앞)
    if 라 != 앞 and len(라) >= 2:
        앞들.append(라)
    for a in 앞들:
        if re.search(_띄어도(a) + _출처_사이_RX + _띄어도(끝), 원문):
            return True
        if re.search(_띄어도(끝) + r"[ \t]*[(（][^)）\n]{0,24}?" + _띄어도(a), 원문):
            return True
    접미 = _매치된_접미(앞, _기관접미_긴순)
    if not 접미:
        # 기관 이름이 아닌 앞 이름도 같은 짧은 구절 안(12자, 쉼표·문장·줄 끝 전)에서 끝 낱말이 뒤따르면 함께다 — 자료 '경영정보
        # 공개(알리오) 공시' → '경영공시'(verify_precision §1-b)
        for m in re.finditer(_띄어도(앞), 원문):
            구절 = _출처_짧은구절끝_RX.split(원문[m.end():m.end() + 12], 1)[0]
            if 끝 in 구절:
                return True
        return False
    꼬리들 = [앞[i:] for i in range(len(앞)) if len(앞) - i >= len(접미) + 2] + _기관약칭풀이(앞, 원문)
    for 꼬리 in 꼬리들:
        for m in re.finditer(_띄어도(꼬리), 원문):
            구절 = _출처_구절끝_RX.split(원문[m.end():m.end() + 24], 1)[0]
            if 끝 in 구절:
                return True
    return False


# 2차('26-09-30 fixup) — 뭉뚱그린 끝 낱말과 목록 밖 끝 낱말.
#   · 끝 낱말이 자료·문서·서류·데이터이고 앞 이름('제공'은 뗀다)이 자료의 **출처 표지 줄**('출처:'·'※ 출처 -'·'자료:'·'제공:'·
#     줄 끝 '… 제공')에 있으면 통과한다 — 자료가 출처를 밝혔다(verify_precision §1-a '※ 출처: ○○공사 고객지원처' → '고객지원처
#     자료'가 걸리고 교정지시가 맞는 출처 키를 지우라고 시켰다). 앞말에 '내부·자체·사내·자사'가 있으면 이 길을 타지 않는다.
#   · 끝 낱말이 문서 종류가 아니면(목록 밖) 통과시키지 않고 **출처의 낱말이 모두 자료에 있을 때만** 통과한다 — 목록 밖이면 검사
#     밖이라 '○○공사 내부 기준'·'자체 추정'·'고객지원처 제출'(자료에 없는 말)이 새던 길(verify_recall §2-2, 목록 밖 꼴이 차수마다
#     새면 목록을 넓히지 않고 방향을 바꾼다). 기관·부서 이름뿐인 출처는 자료에 그 이름이 있으면 그대로 통과한다.
#   · 낱말 끝 부호 '.'·'*'·괄호 조각도 뗀다('…보고서.'·md 기울임 '…자료*'가 끝 낱말을 못 찾아 검사 밖이 되던 것, verify_precision §5).
_출처_뭉뚱말 = frozenset({"내부", "자체", "사내", "자사", "내부자료", "자체자료", "사내자료", "자사자료"})
# 출처 표지 조각 — 표지 뒤('출처: ○○공사 고객지원처'·'※ 출처 - …'·'자료: …'·'제공: …', 줄·문장 끝까지) 또는 '… 제공'의 앞(줄 끝이나
# 닫는 괄호 앞). 줄 전체가 아니라 조각만 본다 — 자료가 한 문단이면 줄 하나에 온갖 이름이 다 든다.
# fixup2('26-09-30 주관 판정 X3) — 자료 쪽 표지 꼴을 넓힌다: '[출처]'·'〈출처〉'·'【출처】'·'출처 ▶'·'Source:'·'자료원:'·'근거:'(wire_verify
# §3-2 — 표지 꼴이 달라 맞는 '고객지원처 자료' 6/30 이 지은 출처로 걸려 키가 지워졌다). 자료를 읽는 쪽만 넓힌다 — 초안 쪽 표시는 늘리지 않는다.
_출처표지뒤_RX = re.compile(r"(?:출처|자료원|자료|제공|근거|[Ss]ource|SOURCE)\s*[:：]\s*([^\n;]{1,60})"
                         r"|출처\s*(?:[-–]|[▶►▷→⇒])\s*([^\n;]{1,60})"
                         r"|[\[［〈<《【]\s*출처\s*[\]］〉>》】]\s*[:：]?\s*([^\n;]{1,60})")
_출처표지앞_RX = re.compile(r"([^\n;:：.,]{2,40}?)\s*제공\s*(?=[)\]］]|$)", re.M)
_출처_낱말부호 = "「」『』\"'“”‘’·,.*()[]［］（）"


def _출처표지줄들(원문):
    t = str(원문 or "")
    조각 = [next((g for g in m.groups() if g), "") for m in _출처표지뒤_RX.finditer(t)]
    조각 = [re.split(r"(?<!\d)[.。](?!\d)", x, 1)[0] for x in 조각]      # 문장 끝까지(날짜 속 점은 넘는다)
    조각 += [m.group(1) for m in _출처표지앞_RX.finditer(t)]
    return [re.sub(r"\s+", "", x) for x in 조각 if x and x.strip()]


def _출처표지이름있나(이름낱말, 원문):
    """뭉뚱그린 끝 낱말(자료·문서 …) 앞 이름이 자료의 출처 표지 줄에 있나 — '○○공사 고객지원처'면 '고객지원처'만으로도 본다."""
    이름 = [w for w in 이름낱말 if w and w != "제공" and not _출처_날짜토막_RX.match(w)]
    if not 이름 or any(w in _출처_뭉뚱말 for w in 이름):
        return False
    줄들 = _출처표지줄들(원문)
    if not 줄들:
        return False
    for k in range(len(이름)):
        후보 = "".join(이름[k:])
        if len(re.sub(r"[○〇]+", "", 후보)) >= 2 and any(후보 in 줄 for 줄 in 줄들):
            return True
    return False


def _출처낱말다있나(낱말, 원문):
    """목록 밖 끝 낱말 출처 — 날짜 토막·자리표시를 뺀 낱말이 모두 자료에 있나(띄어쓰기 무관, 라틴은 대소문자 무관)."""
    원민 = re.sub(r"\s+", "", str(원문 or ""))
    원소 = 원민.lower()
    # 가운뎃점·빗금으로 이은 낱말('만족도·민원')은 조각마다 본다(bench14 A s6 '민원 만족도·민원 처리 기간(올해 상반기)')
    for w in [x for w0 in 낱말 for x in re.split(r"[·/・]", w0) if x]:
        if _출처_날짜토막_RX.match(w):
            continue
        w2 = re.sub(r"[○〇]+", "", w)
        if not w2:
            continue
        if w2.lower() in 원소 or (_조사떼기(w2) and _조사떼기(w2) in 원민):
            continue
        if _기관약칭풀이(w2, 원문):
            continue                   # 기관 약칭('행안부' ↔ 자료 '행정안전부')
        return False
    return True


def _출처조각_지어냄인가(본, 원문):
    낱말 = [w.strip(_출처_낱말부호) for w in 본.split()]
    낱말 = [w for w in 낱말 if w]
    while 낱말 and (낱말[-1] in _출처_꼬리말 or _출처_날짜토막_RX.match(낱말[-1])
                  # '교통량 통계 자료' — 문서 종류 뒤에 덧붙인 일반 말은 떼고 본다('○○공사 내부 자료'는 앞이 종류가 아니라 그대로)
                  or (낱말[-1] in _출처_덧말 and len(낱말) >= 2 and _출처끝낱말(낱말[-2]) is not None)):
        낱말.pop()
    if not 낱말:
        return False
    갈 = _출처끝낱말(낱말[-1])
    if 갈 is None:
        # 문서 종류로 끝나지 않는다 — 낱말이 모두 자료에 있어야 통과한다(기관·부서 이름뿐인 출처는 자료에 그 이름이 있으면 통과)
        # '○○공사 고객지원처 제공'은 자료의 출처 표지 줄이 그 이름을 밝혔으면 통과한다('제공'이 자료에 없어도)
        if 낱말[-1] == "제공" and _출처표지이름있나(낱말[:-1], 원문):
            return False
        return not _출처낱말다있나(낱말, 원문)
    앞, 끝 = 갈
    이름낱말 = 낱말[:-1] + ([앞] if 앞 else [])
    if not 앞:
        # 바로 앞 낱말 — 연도·날짜 토막('2025 결산'의 2025)은 이름이 아니라 건너뛴다(날짜는 재기·월표현이 본다)
        앞 = 낱말[-2] if len(낱말) >= 2 and not _출처_날짜토막_RX.match(낱말[-2]) else ""
    if not 앞:
        return 끝 not in 원문          # 끝 낱말 하나뿐('통계'·'2025 결산') — 자료에 그 말이 있어야 한다
    if not re.sub(r"[○〇]+", "", 앞):
        # '○○ 통계('25년)'·'○○ 현황' — 이름 자리가 자리표시뿐인 출처는 출처가 아니다(fixup2 X3: 예전엔 빈칸으로 보고 통과시켜
        # 꼬리말에 '○○ 통계'가 그대로 남았다 — wire_verify §3-3). 자료에 그 글이 그대로 적혔을 때만 받는다.
        return re.sub(r"\s+", "", 본) not in re.sub(r"\s+", "", 원문)
    # 자료 쪽은 괄호 덧말·낫표를 걷은 판과 괄호 부호만 걷은 판으로도 본다 — 자료 '설문(응답 320명) 결과'·'「만족도 조사」 결과'·
    # '고객의 소리(VOC) 분석'
    부호 = r"[「」『』\"“”‘’]"
    판들 = (원문, re.sub(부호, "", re.sub(r"\([^)]*\)|（[^）]*）", " ", 원문)), re.sub(부호 + r"|[()（）]", " ", 원문))
    if any(_출처함께있나(앞, 끝, 판) for 판 in 판들):
        return False
    if 끝 in _출처_덧말 and _출처표지이름있나(이름낱말, 원문):
        return False                   # '고객지원처 자료' — 자료의 출처 표지 줄('※ 출처: ○○공사 고객지원처')이 그 이름을 밝혔다
    return True


# ── 출처 조각('26-09-30 주관 판정 X3) — 한 칸에 출처가 둘 이상('A 통계; B 조사')이면 지어낸 조각만 뺀다 ─────────────────
# wire_verify §3-1: 앞은 맞고 뒤만 지은 5꼴이 칸째 걸려 교정적용이 키째 지웠고 맞는 조각까지 잃었다. 괄호 밖의 ' · '·쌍반점·
# 쉼표(뒤 띄움)·빗금(앞뒤 띄움)·' 및 '에서 가른다. 붙인 가운뎃점('만족도·민원')은 한 이름 안의 나열일 수 있어 가르지 않는다.
# fixup3 Z4-③('26-10-01 주관 판정) — **분명한 구분자에서만** 가른다: 쉼표(띄움 무관, 수 속 쉼표 '2,900'은 뺀다)·쌍반점·줄바꿈·
# 'ㆍ'·'•'·'|'·' 및 '·' 외 '. 가운뎃점(·, 띄운 ' · '도)과 빗금은 한 이름 안의 나열('만족도·민원')이거나 표지 글('출처: A / 자료: B')일
# 수 있어 가르지 않는다 — 그 칸은 칸째 판정한다(맞는 조각도 함께 지운다. 헛남김보다 칸째 지움).
_출처가름_RX = re.compile(r"[ \t]*(?:(?<!\d)[,，]|[,，](?!\d))[ \t]*|[ \t]*[;；\n|ㆍ•][ \t]*|[ \t]+(?:및|외)[ \t]+")
_출처가름_정본 = {";": "; ", "；": "; ", ",": ", ", "，": ", ", "및": " 및 ", "외": " 외 ", "|": " | ", "ㆍ": "ㆍ", "•": " • ",
               "": "; "}


def _출처꼴인가(조각):
    """조각 하나가 따로 출처 꼴인가 — 끝 낱말이 문서 종류('현황'·'결과'·'통계' …)거나 덧말('자료')이거나 기관·부서 이름('고객지원처')이다.
    '시설'·'장비 점검'처럼 끝 낱말이 없는 조각은 따로는 출처가 아니다(한 이름의 앞·뒤 토막)."""
    낱말 = [w.strip(_출처_낱말부호) for w in re.sub(r"\([^)]*\)|（[^）]*）", " ", str(조각 or "")).split()]
    낱말 = [w for w in 낱말 if w]
    while 낱말 and (낱말[-1] in _출처_꼬리말 or _출처_날짜토막_RX.match(낱말[-1])):
        낱말.pop()
    if not 낱말:
        return False
    끝 = 낱말[-1]
    return _출처끝낱말(끝) is not None or 끝 in _출처_덧말 or bool(_말한이_조직끝_RX.search(끝))


# fixup4 G2('26-10-01 주관 판정) — 'ㆍ'·' 및 '·' 외 '로 이은 **한 이름**('시설ㆍ장비 점검 결과'·'안전 점검 및 보수 실태조사')은 가르지 않는다:
# 앞·뒤 조각 가운데 하나라도 따로는 출처 꼴이 아니면(_출처꼴인가) 그 가름표에서 붙여 둔다. 예전엔 '시설ㆍ장비 점검 결과ㆍ총무처 문서 관리
# 현황'을 교정하면 등록본 출처가 '시설'로 남았다(wire_fixup3_verify §3-3). '「」'·'『』' 안의 쉼표도 가르지 않는다.
_출처_약한가름 = frozenset({"ㆍ", " 및 ", " 외 "})


def _출처조각들(글):
    """[(조각, 뒤 가름표)] — 괄호·낫표 안의 쉼표('('23~'25년, 잠정)'·'「시설 점검, 보수 실태조사」')에서는 가르지 않는다.
    'ㆍ'·' 및 '·' 외 '는 앞·뒤가 모두 따로 출처 꼴일 때만 가른다(G2)."""
    out = _출처조각들_날(글)
    i = 0
    while i < len(out) - 1:
        (a, 가), (b, 뒤) = out[i], out[i + 1]
        if 가 in _출처_약한가름 and not (_출처꼴인가(a) and _출처꼴인가(b)):
            out[i:i + 2] = [(a + 가 + b, 뒤)]
            continue
        i += 1
    return out


def _출처조각들_날(글):
    s = str(글 or "")
    out, 깊이, 시작, i = [], 0, 0, 0
    while i < len(s):
        ch = s[i]
        if ch in "(（[［「『":
            깊이 += 1
        elif ch in ")）]］」』":
            깊이 = max(0, 깊이 - 1)
        elif 깊이 == 0:
            m = _출처가름_RX.match(s, i)
            if m and m.end() > i and s[시작:i].strip():
                out.append((s[시작:i].strip(), _출처가름_정본.get(m.group(0).strip(), m.group(0))))
                시작 = i = m.end()
                continue
        i += 1
    if s[시작:].strip():
        out.append((s[시작:].strip(), ""))
    return out


def 출처남길글(글, 원문):
    """지어낸 조각만 뺀 출처 글 — 지어낸 것이 없으면 None, 모두 지어냈으면 '', 일부만이면 맞는 조각을 이은 글.
    교정적용(키지움 칸)과 약한 경로 출처비우기가 이 글을 남기고 나머지만 지운다."""
    글 = str(글 or "").strip()
    if not 글 or not _출처_지어냄인가(글, 원문):
        return None
    조각 = _출처조각들(글)
    if len(조각) <= 1:
        return ""
    남 = [(a, b) for a, b in 조각 if not _출처_지어냄인가(a, 원문)]
    if not 남 or len(남) == len(조각):
        return ""                      # 조각마다는 맞는데 통째로는 걸린다(가르는 자가 다르다) — 칸째 지운다
    # 따로는 출처 꼴이 아닌 조각('시설'·'2025')은 남기지 않는다 — 남길 것이 없으면 칸째 지운다(G2: 헛남김보다 칸째 지움)
    남 = [(a, b) for a, b in 남 if _출처꼴인가(a)]
    if not 남:
        return ""
    가름 = next((b for _, b in 조각 if b), " · ")
    return 가름.join(a for a, _ in 남)


# ── 인용 장의 출처 = 말한 사람('26-09-30 주관 판정 X1) ───────────────────────────────────────────────────────────
# 옛 판형 슬라이드 '인용' 레이아웃의 `출처` 는 바닥 출처 줄이 아니라 말한 사람이다(assemble_slides._인용 → sl-quote-src, 게이트가
# 비면 막는다). 문서 이름으로 재어 키를 지우면 새문서·교정적용·저장이 깨졌다(wire_verify §1). 말한 사람은 **이름 낱말이 모두 자료에
# 있어야** 맞다 — 자료에 없으면 '말한 사람' 걸림(지우지 않는다: 교정은 자료의 말한 사람으로 고치거나 요지 장으로 바꾼다).
_인용레이아웃 = frozenset({"인용", "quote", "testimonial"})


def _인용장출처인가(doc, 어디):
    m = re.fullmatch(r"슬라이드\.(\d+)\.출처", str(어디 or ""))
