_자기참조조_RX = re.compile(r"제\s*(\d{1,3})\s*조")


def _문서조번호범위(doc) -> set:
    items = doc.get("본문") if isinstance(doc, dict) else None
    if not isinstance(items, list):
        return set()
    조수 = sum(1 for it in items if isinstance(it, dict) and it.get("level") == "조")
    return set(range(1, 조수 + 1)) if 조수 else set()


# 문서가 스스로 지은 정의 용어 — 규정의 '"정기 재택근무"란 …을 말한다'·'(이하
# "재택근무자"라 한다)'('26-09-28 5차 벤치 실측: 따옴표 명칭 규칙이 이 셋을 '자료에 없는
# 이름'으로 걸어, 모델이 정의 조항을 풀어 쓰고 뒤 조문은 정의 없이 용어를 쓰게 됐다).
# 정의 문형 안에 있고 **낱말 조각이 모두 자료에 있는**(끝 한 글자 파생 '-자'·'-제' 허용)
# 용어만 뺀다 — 자료에 없는 시설·사업 이름을 정의 꼴로 들여오면 여전히 걸린다.
_정의어_RX = re.compile(r'["“]\s*([^"”\n]{2,20}?)\s*["”]\s*(?:이?란|이?라고?\s*한다|이?라\s*함)')


def _정의어들(doc, 원민):
    전체 = "\n".join(g for _, g in 문서글(doc))
    나온다 = set()
    for m in _정의어_RX.finditer(전체):
        용어 = m.group(1).strip()
        조각 = [_조사떼기(x) for x in re.findall(r"[가-힣]{2,}", 용어)]
        if not 조각 or re.search(r"[A-Za-z0-9]", 용어):
            continue
        if all(x in 원민 or (len(x) >= 3 and x[:-1] in 원민) for x in 조각):
            나온다.add(re.sub(r"\s+", "", 용어))
    return 나온다


# 법령식 비율 '100분의 30'·'1천분의 25'·'1,000분의 5'의 **분모**(10의 거듭제곱) —
# 원문 '30%'를 조문 표기로 옮긴 것이라 분모는 자료에 없어도 지어낸 수치가 아니다
# ('26-09-28 규정 처방 F0-1, 내부 기록 원문 '정원의 30% 이내' + 초안
# '정원의 100분의 30 이내'에서 '100'이 걸려, 교정지시 루프가 핵심 6번 규칙('100분의 N')을
# '30%'로 되돌렸다). 원문 20% + 초안 '100분의 30'이면 값(30%)이 원문에 없어 여전히 걸린다.
# 분모가 10의 거듭제곱이 아니면('3분의 2') 비율 옮김이 아니라 새 수치일 수 있어 이 길을 안 탄다
# (낱낱 숫자로 기존 대조를 받는다).
#
# **값으로만** 면제한다('26-09-28 적대검토 H4) — 예전엔 분모를 지운 뒤 분자를 **글자로** 원문
# 숫자와 견줘, 원문 '30%' + 초안 '1,000분의 30'(=3%)·원문 '3%' + 초안 '10분의 3'(=30%)처럼 값이
# 10배 틀린 비율도 분자 글자만 같으면 통과했다. 이제 분수 하나를 통째로 값(분자/분모)으로 읽어
# ×100 이 원문 수값(퍼센트)에 있거나, 값 자체가 원문 수값(비율 '0.3')에 있거나, 분자·분모가 둘 다
# 원문에 글자로 있을 때(원문에 이미 '100분의 30'이 적힌 경우)만 통과시킨다. 아니면 분수 전체를
# 한 수치로 걸어 알린다. 분모 '10,000'(0과 쉼표가 섞인 꼴)도 받는다(적대검토 F12).
_분수_RX = re.compile(r"(?<![\d.,])(1(?:0{0,2}(?:,000)+|0+)|1\s*[천만])\s*분의\s*(\d+(?:\.\d+)?)")


def _분수값(m):
    분모글 = re.sub(r"[\s,]", "", m.group(1))
    분모 = float(분모글.replace("천", "000").replace("만", "0000"))
    try:
        분자 = float(m.group(2))
    except ValueError:
        return None, None
    return 분모, 분자


# 분모가 10의 거듭제곱이 아닌 분수('2분의 1'·'3분의 2')도 **값이 원문과 같으면** 지운다('26-09-28
# bench9 reg10 R2): 원문 '외부 전문가를 절반 이상' + 초안 '위원의 2분의 1 이상'(법제 표기로 옮긴 것,
# 조문꼴 R2 교정이 하는 일)에서 원문에 '1'·'2'가 없으면 낱낱 숫자로 걸려 교정지시 루프가 법제 표기를
# '절반'으로 되돌린다. 원문 쪽 값은 '절반·반수'(0.5)·'N분의 M'·한글 수 분수('삼분의 이')·퍼센트에서
# 모은다. 값이 안 맞으면 지우지 않는다 — 예전처럼 분자·분모 숫자가 낱낱으로 원문과 대조된다.
_일반분수_RX = re.compile(r"(?<![\d.,])(\d{1,3})\s*분의\s*(\d{1,3})(?![\d.,])")
_한글수_지 = {"일": 1, "이": 2, "삼": 3, "사": 4, "오": 5, "육": 6, "칠": 7, "팔": 8, "구": 9, "십": 10}
_한글분수_지_RX = re.compile(r"(?<![가-힣])([이삼사오육칠팔십])\s?분의\s?([일이삼사오육칠팔구])(?![가-힣]{2})")  # '구분의'(區分) 제외


# reg10 적대검토('26-09-28) 두 구멍을 막는다 —
#  ① '과반수'(2분의 1 **초과**)를 0.5 로 읽어, 자료의 '과반수'를 초안이 '2분의 1 이상'(정족수를 낮춘 것)으로 바꿔도
#     통과했다(H-1). '과반수'는 값 집합에 넣지 않고, 초안이 '2분의 1 초과'로 쓴 경우만 따로 면제한다.
#  ② 일반 분수의 퍼센트 대조가 원문의 **아무 수**('50명'·'25일'·'40점')와 맞으면 분수를 지워, 1p 에서 지어낸
