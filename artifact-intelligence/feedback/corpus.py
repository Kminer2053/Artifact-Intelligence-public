#   오인해 **과하게** 가릴 수 있다. 사생활 쪽으로 기울여 과잉가림을 택했다(놓치는 것보다
#   낫다). 2자 보통명사(예: 문체 용어 "설치"·"구축")는 규칙상 이름으로 안 걸린다 —
#   실제로 남겨야 할 용어 신호를 먹지 않게 이름 규칙을 3자 이상 또는 호칭 경계로 좁혔다.

# 메일·링크 — @·http:// 표식이 있어 오탐이 없다. 이름·숫자·기관보다 **먼저** 가린다
# (뒤 규칙이 메일/URL 안의 숫자·기관꼬리 조각을 먼저 집어 덩어리를 깨뜨리지 않도록).
