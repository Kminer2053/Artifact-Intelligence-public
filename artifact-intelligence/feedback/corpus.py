# 이름 뒤에 붙는 조사(맨이름을 경계로 잡을 때 뒤가 한글이라도 이름으로 끊게).
_조사 = ("은", "는", "이", "가", "을", "를", "와", "과", "에게", "에서", "에", "의", "으로",
        "로", "도", "만", "부터", "까지", "보다", "처럼", "한테", "께")

_성군 = "(?:" + "|".join(_복성) + r"|[" + _성 + r"])"
# ① 성+이름(1~2자) + 호칭 → "<이름>" + 호칭(직함은 PII 가 아니라 맥락으로 남긴다)
_이름_호칭 = re.compile(_성군 + r"[가-힣]{1,2}(\s?(?:" + "|".join(_호칭) + r"))")
# ② 성+이름(2자) 맨이름 — 앞이 한글이름 경계가 아니고, 뒤가 조사·비한글·끝일 때만.
#    3자 이상으로 좁혀 2자 보통명사(문체 용어)를 안 먹는다.
_이름_맨 = re.compile(
    r"(?<![가-힣])(?:" + "|".join(_복성) + r"[가-힣]{2}|[" + _성 + r"][가-힣]{2})"
    r"(?=(?:" + "|".join(_조사) + r")(?![가-힣])|[^가-힣]|$)")


def _한줄(s):
    """여러 줄·과한 공백을 한 줄로 — 최소 스팬의 첫 단계. None 은 None."""
    if s is None:
        return None
    return re.sub(r"\s+", " ", str(s)).strip()


def 비식별_지시(글):
    """내용이 섞이는 자유 텍스트(지시문·용어)에서 식별자를 가린다.

    순서가 중요하다 — 메일·링크(@·http:// 표식)를 맨 먼저 통째로 가리고, 그다음
    기관·이름을 가린 뒤 숫자를 마지막에 가린다(기관·이름·숫자 패턴이 메일/URL 안의
    조각을 먼저 집으면 덩어리가 깨진다. 숫자를 먼저 <수> 로 바꿔도 기관·이름 패턴이
    안 맞는다). 가린 뒤에도 완벽하지 않다는 것을 숨기지 않는다(모듈 머리 주석의 '못 가리나').
    """
    글 = _한줄(글)
    if not 글:
        return 글
    글 = _메일.sub("<메일>", 글)
    글 = _링크.sub("<링크>", 글)
    글 = _기관.sub("<기관>", 글)
    글 = _이름_호칭.sub(r"<이름>\1", 글)
    글 = _이름_맨.sub("<이름>", 글)
    글 = _숫자.sub("<수>", 글)
    return 글


def _값비식별(값, 가림):
    """중첩 델타(딕트·리스트·문자열)의 문자열 알맹이만 정돈한다.

    가림=True → 비식별_지시(자유 내용: 목차 제목 등)로 이름·숫자·기관을 가린다.
    가림=False → _한줄(구조 라벨: 유형·배치·양식)으로 공백만 정돈, 내용은 그대로.
    숫자·불리언 같은 비문자열(예: 요약박스 포함=True·위치 인덱스)은 손대지 않는다 —
    구조 신호라 그대로 남아야 관리자가 "무엇을 어떻게 바꿨나"를 읽는다.
    """
    함수 = 비식별_지시 if 가림 else _한줄
    if isinstance(값, str):
        return 함수(값)
    if isinstance(값, list):
        return [_값비식별(x, 가림) for x in 값]
    if isinstance(값, dict):
        return {k: _값비식별(v, 가림) for k, v in 값.items()}
    return 값


def _델타비식별(델타):
    """델타를 저장용으로 정돈한다 — 내용(용어·목차 제목)만 비식별, 구조 라벨은 그대로.

    왜 구조를 그대로 두나 — 구간·순서·유형·양식·배치는 저-PII 구조 신호이고, 그대로
    남아야 관리자가 "어디를 어떻게 바꿨나"를 읽는다(구현계획.md WP-S10). 여기서 가리면
    구조 델타까지 지워져 코퍼스가 쓸모를 잃는다. 다만 **목차 절 제목**은 사용자가 자유로
    짓는 자리라(자유내용열쇠) 그 문자열 알맹이는 가린다 — 구조(목록 모양·통제 라벨)는
    남고 자유 제목의 PII 만 지워진다. 유형·배치·양식은 중첩 딕트라도 통제 어휘라 공백만.
    """
    if not isinstance(델타, dict):
        return {}
    out = {}
    for k, v in 델타.items():
        if k in 용어열쇠 and isinstance(v, str):
            out[k] = 비식별_지시(v)              # 문체 용어(내용) — 가린다
        elif k in 자유내용열쇠:
            out[k] = _값비식별(v, 가림=True)      # 목차 제목 등 자유 내용 — 가린다
        elif isinstance(v, str):
            out[k] = _한줄(v)                    # 구조 라벨 — 공백만 정돈, 내용은 그대로
        else:
            out[k] = _값비식별(v, 가림=False)     # 유형·배치·양식 중첩 구조 — 공백만 정돈
    return out


# ── 문체 경로: 리터칭 diff → 주목할 변경 판정 → 항목 ────────────────────────

def _평(s):
    """구두점·공백을 걷어낸 알맹이 — '조를 만한가'를 잴 때 쓴다."""
    return re.sub(r"[\s\.,·:;!?…“”\"'()\[\]{}<>／/\\|~\-—]+", "", str(s or ""))


def _사소한오타(a, b):
    """두 낱말이 **오타 고침** 수준인가(조를 것이 아님). 휴리스틱 — 2차에서 다듬는다.

    같은 길이에서 한 글자만 다르거나, 아주 비슷하면(difflib 비율 ≥ 0.85) 오타로 본다.
    '설치'↔'구축' 은 겹치는 글자가 없어 비율 0 → 오타 아님 → 주목할 변경.
    **1차의 한계(정직하게)**: '충전기→충전소' 처럼 한 글자만 바뀐 **뜻 있는** 치환도
    오타로 접어 안 조른다. 사전 없이 오타와 못 가르므로, 덜 조르는(과잉 프롬프트를
    피하는) 쪽으로 기울였다 — 조를 것을 놓치는 편이 매번 조르는 것보다 낫다.
    """
    import difflib
    if a == b:
        return True
    if len(a) == len(b) and sum(x != y for x, y in zip(a, b)) == 1:
        return True
    return difflib.SequenceMatcher(a=a, b=b).ratio() >= 0.85


def 낱말변경(before, after):
    """before→after 에서 **바뀐 낱말 스팬만** 뽑는다 (전, 후) 목록으로.

    왜 낱말 단위인가 — backtrace 는 **항목 단위** diff 를 낸다(한 문단 통째로 before/
    after). 문단 통째로 비교하면 "시설을 설치한다→시설을 구축한다" 는 대부분이 같아
    '오타처럼' 보이지만, 실제 신호는 설치→구축 한 낱말이다. difflib 로 낱말 열을
    맞대 **바뀐 스팬만** 남기면, 그게 곧 조를 신호이자 **최소 스팬**(문맥 낱말은
    버린다 — 구현계획 WP-S10 'A=최소')이다.
    """
    import difflib
    bw = (_한줄(before) or "").split()
    aw = (_한줄(after) or "").split()
    쌍 = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=bw, b=aw).get_opcodes():
        if tag == "equal":
            continue
        쌍.append((" ".join(bw[i1:i2]), " ".join(aw[j1:j2])))
    return 쌍


def _주목쌍(diff):
    """이 diff 에서 **조를 만한** 낱말 치환 쌍 하나를 고른다(없으면 None).

    · 통짜 추가/삭제(before 나 after 가 빔)는 이번 슬라이스의 문체 용어 신호가 아니다.
    · 스팬 한쪽이 비었으면(순수 낱말 추가·삭제) 치환이 아니라 건너뛴다.
    · 공백·구두점만 다르거나 사소한 오타면 제외("사소한 오타 제외" — 명세).
    """
    b = _한줄(diff.get("before"))
    a = _한줄(diff.get("after"))
    if not b or not a:
        return None
    for 전, 후 in 낱말변경(b, a):
        n전, n후 = _평(전), _평(후)
        if not n전 or not n후:
            continue
        if n전 == n후 or _사소한오타(n전, n후):
            continue
        return (전, 후)
    return None


def 주목할변경인가(대상):
    """리터칭 diff(문체) 또는 구성·디자인 항목이 **조를 만한 변경**인가(WP-S10 '능동 동의').

    · 문체(리터칭 diff): before→after 에 뜻 있는 용어·구절 치환이 있나(설치→구축). 기존
      판정 그대로 — 사소한 오타·통짜 추가삭제는 제외(_주목쌍). 차원 표시가 없는 dict 는
      문체 diff 로 본다(문체는 raw diff 를, 구성·디자인은 항목 dict 를 넘긴다).
    · 구성·디자인(항목 dict, `차원` 표시): **델타가 기본 제안과 다를 때만** 주목한다.
      구성은 유형/목차/배치 중 실제로 다른 것만 델타에 담기므로 비어 있지 않으면 주목.
      디자인은 델타에 추천·고른이 늘 함께 있으니 둘이 **다를 때만** 주목(같으면 안 조른다).
    문체의 기존 판정은 안 건드린다 — 차원이 구성·디자인일 때만 새 갈래를 탄다.
    """
    if isinstance(대상, dict) and 대상.get("차원") in ("구성", "디자인"):
        델타 = 대상.get("델타") or {}
        if 대상.get("차원") == "디자인":
            return 델타.get("추천") != 델타.get("고른")
        return bool(델타)
    return _주목쌍(대상) is not None


def 문체_항목(diff, 규칙맥락=None):
    """backtrace diff 하나를 **문체 코퍼스 항목(비식별 전)** 으로 빚는다.

    `전/후` 에는 **바뀐 낱말 스팬만** 담는다(최소 스팬) — 문단 통째가 아니라 설치→구축
    처럼 조를 신호만. 주목할 쌍이 없으면(방어적으로) diff 의 before/after 를 그대로 둔다.
    `구간` 은 어디서 바뀌었나(절·항목)를 남기는 저-PII 구조 라벨이라 그대로 둔다.

    비식별은 여기서 안 한다 — 저장 경로(`동의저장`)가 동의를 확인한 **뒤** 한 번에
    한다(동의 안 하면 비식별조차 필요 없고, 비식별을 저장 앞 한 곳에 모아야 '동의한
    것만, 비식별해서'라는 계약이 한눈에 보인다).

    문체는 리터칭 diff 라 **자유 지시문이 없다** — `지시` 자리는 비운다(None).
    구성·디자인은 재구성/재지시 프롬프트가 있어 `지시` 가 차는데, 그 캡처는 2차다.
    """
    쌍 = _주목쌍(diff)
    전, 후 = 쌍 if 쌍 else (diff.get("before") or "", diff.get("after") or "")
    return {
        "차원": "문체",
        "델타": {"구간": diff.get("segment") or "", "전": 전, "후": 후},
        "지시": None,                 # 2차: 구성·디자인은 여기에 재지시 프롬프트가 온다
        "규칙맥락": 규칙맥락,
    }


# ── 구성 경로: 제안→채택 빌드플랜 델타 → 구조 항목 (WP-S10 2차-A) ──────────────
# 캡처 지점(buildplan/render_plan.py 승인 화면, `승인.status ∈ {되묻기중,대기,승인,
# 수정요청}`): 사용자가 제안 플랜을 채택하거나 수정한다. 신호는 **제안→채택 델타** 세
# 갈래 — 유형(보고목적유형)·목차(순서·구간)·배치(표vs서술·요약박스). 셋 다 온톨로지
# 유래 저-PII 구조라 라벨은 그대로 남기고, 자유 내용은 목차 절 제목뿐이라 그 자리만
# 저장 앞에서 가린다(_델타비식별 자유내용열쇠). 재구성 자유 프롬프트는 `지시` 로 실어
# 보내고, 그것도 저장 앞에서 비식별한다(_항목빚기).

def _보고목적유형(플랜):
    """플랜의 보고목적유형(유형 라벨). 판정 층에 산다 — 통제 어휘라 저-PII."""
    return (플랜.get("판정") or {}).get("보고목적유형")


def _목차시퀀스(플랜):
    """본문 목차 순서(절 이름 열). 순서와 구간(어떤 절이 있나)을 한꺼번에 담는다.

    render_plan.py 승인 화면이 보여주는 `적용방법론.본문.구성.목차패턴.표준시퀀스`
    바로 그 자리. 없으면 압축시퀀스로 물러선다(둘 다 없으면 빈 목록).
    """
    mb = ((((플랜.get("적용방법론") or {}).get("본문") or {})
           .get("구성") or {}).get("목차패턴") or {})
    return mb.get("표준시퀀스") or mb.get("압축시퀀스") or []


def _배치신호(플랜):
    """배치 = 표vs서술·요약박스. 두 저-PII 구조 신호를 뽑는다.

    · 표: `등장요소_전망` 에서 '표' 요소의 가능성(높음/중간/낮음) — 표로 갈지 서술로
      갈지의 신호. 없으면 None.
    · 요약박스: `개체구성` 에서 '요약박스' 개체의 포함(bool)과 위치(개체 순서 인덱스).
      회색 요약 상자를 넣나·어디에 두나 — 위치는 정수라 비식별 대상 아님(구조 그대로).
    """
    표 = None
    for e in (플랜.get("등장요소_전망") or []):
        if e.get("요소") == "표":
            표 = e.get("가능성")
            break
    포함 = 위치 = None
    for i, e in enumerate(플랜.get("개체구성") or []):
        if e.get("개체") == "요약박스":
            포함 = bool(e.get("포함"))
            위치 = i
            break
    return {"표": 표, "요약박스포함": 포함, "요약박스위치": 위치}


def 구성_항목(제안, 채택, 지시=None, 규칙맥락=None):
    """제안·채택 빌드플랜(dict)에서 **구조 델타만** 뽑아 구성 코퍼스 항목을 빚는다.

    델타는 **실제로 바뀐 갈래만** 담는다 — 어떤 갈래가 제안=채택이면 그 갈래는 빠지고,
    셋 다 같으면 델타가 비어 `주목할변경인가` 가 False → None 을 돌려준다(안 조른다,
    구현계획 능동 동의). 유형·배치·양식 라벨은 통제 어휘라 그대로, **목차 절 제목만**
    자유 내용이라 저장 앞 비식별을 지난다(_델타비식별). 재구성 자유 프롬프트는 `지시`.

    비식별은 여기서 안 한다 — 문체_항목과 같은 계약: 동의를 확인한 저장 경로(`동의저장`
    →`_항목빚기`·`_델타비식별`)가 한 곳에서 가린다('동의한 것만, 비식별해서'가 한눈에).
    """
    제안 = 제안 or {}
    채택 = 채택 or {}
    델타 = {}
    p유형, a유형 = _보고목적유형(제안), _보고목적유형(채택)
    if p유형 != a유형:
        델타["유형"] = {"제안": p유형, "채택": a유형}
    p목차, a목차 = _목차시퀀스(제안), _목차시퀀스(채택)
    if p목차 != a목차:
        델타["목차"] = {"제안": p목차, "채택": a목차}
    p배치, a배치 = _배치신호(제안), _배치신호(채택)
    배치델타 = {k: {"제안": p배치[k], "채택": a배치.get(k)}
              for k in p배치 if p배치[k] != a배치.get(k)}
    if 배치델타:
        델타["배치"] = 배치델타
    항목 = {
        "차원": "구성",
        "델타": 델타,
        "지시": _한줄(지시) if 지시 else None,   # 자유 프롬프트 — 저장 경로에서 비식별
        "규칙맥락": 규칙맥락,
    }
    return 항목 if 주목할변경인가(항목) else None


