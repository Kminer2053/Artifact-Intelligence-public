#   못 가릴 수 있으니 입력칸에서 "이름·연락처는 빼고 적으라"고 유의도 함께 안내한다.
# 무엇을 못 가리나(정직하게): 성씨가 흔한 2자 이름(맨이름)·외국식 이름·오탈자 섞인
