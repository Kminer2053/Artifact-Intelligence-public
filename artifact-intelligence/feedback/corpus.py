# 이웃 단어를 넘어 삼키지 않는다(공백은 이 문자군에 없다).
_기관 = re.compile(r"[가-힣A-Za-z0-9]{1,15}(?:" + "|".join(map(re.escape, _기관꼬리)) + r")")

